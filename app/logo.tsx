/**
 * Знак сервиса — в шапке, в подвале и в фавиконе.
 *
 * Тёмная плашка выбрана не для красоты: без неё знак наполовину исчезает на
 * тёмной вкладке браузера, а на шестнадцати пикселях рассыпается на точки.
 * Плашка держит контраст на любом фоне, а внутри — фирменные цвета: бумага,
 * лайм и коралл. Так же устроены чёрные блоки на лендинге, поэтому знак
 * читается как часть сайта, а не как наклейка на нём.
 *
 * Цвета записаны значениями, а не переменными: этот же файл дублируется в
 * public/favicon.svg, который отдаётся браузеру отдельно и до CSS не
 * добирается. При смене знака менять оба.
 *
 * Разметка вставляется в страницу, а не подключается картинкой по ссылке:
 * так знак не требует отдельного запроса, не мигает при загрузке и не зависит
 * от того, как браузер закэшировал favicon.
 */
export function Logo({ size = 27 }: { size?: number }) {
  return <svg
    width={size}
    height={size}
    viewBox="0 0 24 24"
    xmlns="http://www.w3.org/2000/svg"
    role="img"
    aria-label="Живое Тело"
  >
    <rect width="24" height="24" rx="6.5" fill="#171917" />
    <rect x="5" y="5" width="7" height="7" rx="1.9" fill="#f4f1ea" />
    <rect x="14.1" y="5" width="4.9" height="4.9" rx="1.4" fill="#d9e49c" />
    <rect x="5" y="14.1" width="4.9" height="4.9" rx="1.4" fill="#d9e49c" />
    <rect x="12" y="12" width="7" height="7" rx="1.9" fill="#e56d55" />
  </svg>;
}
