import { photoForDelivery } from "@/lib/catalog-photos-store";

/**
 * Раздача снимков продуктов для публичного каталога.
 *
 * Единственный маршрут снимков без авторизации — и потому единственный, где
 * ошибка означает утечку чужого фото еды. Отсюда два решения, каждое из
 * которых сужает поверхность:
 *
 * 1. **Обращение по идентификатору строки каталога, а не по ключу файла.**
 *    Ключ (`<userId>/<uuid>.jpg`) наружу не выходит вовсе, и подобрать чужой
 *    снимок перебором ключей нельзя: маршрут просто не принимает ключи.
 *    Заодно из адреса исчезает идентификатор владельца, который в ключе есть.
 * 2. **Проверка неотделима от выборки.** `photoForDelivery` отдаёт ключ,
 *    только если снимок одобрен модератором и согласие на публикацию не
 *    отозвано; отдельного «а теперь проверим права» здесь нет, потому что
 *    такую проверку однажды забывают.
 *
 * Кеш здесь публичный, в отличие от остальных маршрутов снимков: это
 * согласованный к публикации кадр на странице, открытой для всех, и просить
 * прокси его не кешировать было бы обманом самих себя.
 */
export async function GET(_request: Request, { params }: { params: Promise<{ id: string }> }) {
  const { id: raw } = await params;
  const id = Number(raw);
  if (!Number.isInteger(id) || id <= 0) return new Response("Not found", { status: 404 });

  const photo = await photoForDelivery(id);
  if (!photo) return new Response("Not found", { status: 404 });

  return new Response(new Uint8Array(photo.data), {
    headers: {
      "Content-Type": photo.mime,
      "Cache-Control": "public, max-age=86400",
    },
  });
}
