/**
 * Числа в разделе расчётов — по-русски.
 *
 * В русском тексте дробная часть отделяется запятой, и «61.5 кг» на странице
 * читается как опечатка. По разделу это повторялось `.toFixed(1).replace(".", ",")`
 * в десятке мест; вторая волна калькуляторов добавила бы ещё столько же, и
 * первая же забытая строчка выдала бы точку посреди русского текста.
 *
 * Заодно убираем хвостовой ноль: «52,0 кг» выглядит как измерение с точностью
 * до сотни граммов, которой у нас нет.
 */
export function ru(value: number, digits = 1): string {
  if (!Number.isFinite(value)) return "—";
  const fixed = value.toFixed(digits);
  // Обрезать нули можно только у дробной записи: у целого «100» это дало бы «1».
  const trimmed = fixed.includes(".")
    ? fixed.replace(/0+$/, "").replace(/\.$/, "")
    : fixed;
  return trimmed.replace(".", ",");
}
