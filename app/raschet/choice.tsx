"use client";

/**
 * Вариант ответа в пошаговых расчётах.
 *
 * ## Почему кнопка, а не радиокнопка
 *
 * Раньше это была пара `<label><input type="radio">`, и после выбора нужно
 * было нажать «Далее» — то есть два действия на один ответ, одиннадцать раз
 * подряд. Кнопка выбирает и сразу ведёт дальше.
 *
 * Соблазн оставить радиокнопки и просто переходить по `onChange` — ловушка.
 * В группе радиокнопок стрелки переключают выбор и тоже вызывают `change`:
 * человек, который ходит по вариантам с клавиатуры, улетал бы к следующему
 * вопросу с первого же нажатия стрелки, не успев дочитать варианты. С
 * кнопками этой двусмысленности нет: между ними ходят табом, выбирают
 * пробелом или вводом, и выбор — всегда осознанное действие.
 *
 * ## Про доступность
 *
 * Группу называет `<legend>` внутри `<fieldset>` — там, где эти кнопки
 * стоят. Выбранность передаётся через `aria-pressed`, а не через `role`
 * радиогруппы: роль потребовала бы своей навигации стрелками, от которой мы
 * как раз и уходим.
 */
export function Choice({ selected, onChoose, children }: {
  selected: boolean;
  onChoose: () => void;
  children: React.ReactNode;
}) {
  return <button type="button" className="radio-card" aria-pressed={selected} onClick={onChoose}>
    {children}
  </button>;
}
