import type { Metadata } from "next";
import Link from "next/link";
import { getCurrentUser } from "@/lib/auth";
import { ACCESS_ANCHOR, priceRub, TARIFFS, TRIAL_DAYS } from "@/lib/paid";
import { payLinksFor } from "@/lib/payments/access-links";
import { OPERATION_LABELS, PLAN_LIMITS, USER_FACING_OPERATIONS } from "@/lib/quota-policy";
import { breadcrumbsJsonLd, jsonLdScript } from "@/lib/schema-org";

export const metadata: Metadata = {
  title: "Цена: сколько стоит «Живое Тело» и что входит",
  description:
    "Первый месяц бесплатно и целиком, без карты. Дальше платным становится обращение к модели — разбор по фото, по описанию и голосом. Дневник, план, вес и выгрузка данных открыты всегда.",
  alternates: { canonical: "/tarify" },
};

/**
 * Страница цены.
 *
 * ## Зачем она, если блок «Цена» есть на главной
 *
 * Блок на главной — часть рассказа для того, кто пришёл впервые и читает
 * сверху вниз. А ссылку на цену нужно давать из письма, из бота, из статьи в
 * журнале и из разговора — и до этой страницы её было некуда дать: якорь на
 * середину лендинга тащит человека через весь текст, а `/legal/tarify` —
 * оферта, документ на другом языке и для другого случая.
 *
 * Второе, чего не было нигде на публичном сайте: **кнопок оплаты**. Купить
 * доступ можно было только изнутри продукта — в настройках кабинета, в
 * профиле Mini App или командой бота. Человек, готовый заплатить прямо
 * сейчас, должен был сначала догадаться зайти в настройки.
 *
 * ## Почему кнопки видит не каждый
 *
 * Ссылка оплаты несёт подписанную метку человека (lib/payments/tribute.ts) —
 * без неё платёж не к кому отнести. Незалогиненному такую ссылку неоткуда
 * взять, поэтому ему показывается вход в пробный месяц, а не кнопка оплаты:
 * платить за доступ к аккаунту, которого ещё нет, — верный способ потерять и
 * деньги, и человека.
 *
 * Числа — из кода: `TARIFFS`, `PLAN_LIMITS` и `TRIAL_DAYS`. Второе место с
 * теми же цифрами однажды разойдётся с первым, и разойдётся молча.
 */
export default async function TarifyPage() {
  const user = await getCurrentUser();
  const payLinks = user ? payLinksFor(user.id) : null;

  return <article className="raschet-page">
    <script
      type="application/ld+json"
      dangerouslySetInnerHTML={{
        __html: jsonLdScript(breadcrumbsJsonLd([
          { name: "Главная", path: "/" },
          { name: "Цена", path: "/tarify" },
        ])),
      }}
    />

    <p className="kicker">Цена <i /></p>
    <h1>Сколько это стоит</h1>
    <p className="raschet-lead">
      Первый месяц — бесплатно и целиком, без карты. Дальше платным становится обращение к
      модели: разбор по фотографии, по описанию, голосом и подсказки. Дневник остаётся вашим
      в любом случае.
    </p>

    <section className="tarify-block">
      <h2>Пробный месяц</h2>
      <p>
        {TRIAL_DAYS} дней после регистрации сервис работает целиком. Ни карты, ни обещания
        списать потом — считать начинает календарь, а не банк. Когда месяц закончится, мы
        предупредим заранее, а не поставим перед фактом в момент, когда вы захотите
        сфотографировать обед.
      </p>
    </section>

    <section className="tarify-block">
      <h2>Что становится платным</h2>
      <p>Обращение к модели. Вот сколько его в сутки при открытом доступе:</p>
      <ul className="price-limits">
        {USER_FACING_OPERATIONS.map((operation) => (
          <li key={operation}>
            <b>{PLAN_LIMITS.premium[operation]}</b>
            <span>{OPERATION_LABELS[operation]}</span>
          </li>
        ))}
      </ul>
      <p className="price-note">
        Лимиты не про экономию, а про предохранитель: при сотне разборов в день в них упирается
        только тот, кто снимает не свою еду, а подряд всё, что видит.
      </p>
    </section>

    {/* Главное обещание модели и единственное, что удерживает её от
        превращения в выкуп. Оно же записано в оферте разделом «Что доступно
        всегда» — и стоит здесь выше цен намеренно: человек решает платить или
        нет, уже зная, что теряет он в любом случае ничего. */}
    <section className="tarify-block">
      <h2>Что открыто всегда</h2>
      <p>
        Записи, история, план, вес, недельные обзоры, каталог блюд, расчёты и выгрузка своих
        данных — и в пробный месяц, и после него, и если вы не заплатите никогда. Еду можно
        записывать руками без ограничений. Платим мы за работу модели, а не за доступ к вашему
        прошлому.
      </p>
    </section>

    <section className="tarify-block" id={ACCESS_ANCHOR}>
      <h2>Тарифы</h2>
      <ul className="price-tariffs">
        {TARIFFS.map((tariff) => (
          <li key={tariff.key}>
            <strong>{priceRub(tariff.priceRub)}</strong>
            <span>{tariff.label.toLowerCase()}</span>
          </li>
        ))}
      </ul>
      <p>
        Год дешевле десяти месяцев — не ради скидки, а потому что снимает ежемесячное решение
        «продлевать ли»: у сервиса про привычку оно стоит дороже разницы в деньгах.
      </p>

      {payLinks && payLinks.length > 0 && <div className="pay-links">
        {payLinks.map((link) => (
          <a key={link.key} className="black-button" href={link.url} target="_blank" rel="noopener noreferrer">
            Оплатить — {link.label.toLowerCase()}, {link.priceRub} ₽
          </a>
        ))}
        <p className="access-note">
          Оплата проходит на стороне Tribute. Доступ откроется автоматически в течение минуты.
          Разовая, без автосписания.
        </p>
      </div>}

      {/* Незалогиненному кнопки оплаты не показываем вовсе: ссылка несёт
          подписанную метку человека, а метки у него ещё нет. Предлагать ему
          заплатить — значит предложить платёж, который некому засчитать. */}
      {!user && <div className="pay-links">
        <Link className="black-button" href="/register">Начать — первый месяц бесплатно</Link>
        <p className="access-note">
          Оплата появится здесь же, когда пробный месяц подойдёт к концу. Сейчас платить не за
          что: {TRIAL_DAYS} дней работает всё.
        </p>
      </div>}

      {/* Залогинен, но приём денег выключен. Молчать нельзя — человек пришёл
          на страницу с ценами; обещать кнопку «скоро» тоже: она ведёт в
          пустоту. Называем работающий путь. */}
      {user && !payLinks && <p className="access-note">
        Приём оплаты сейчас выключен — пользоваться сервисом это не мешает. Продлить доступ
        можно приглашением: за каждого пришедшего друга месяц получаете и вы, и он, ссылка
        в <Link href={`/app/settings#${ACCESS_ANCHOR}`}>настройках</Link>.
      </p>}
    </section>

    {/* Про приглашение — сразу после тарифов, а не в конце страницы. Это не
        дополнение к оплате, а равноправный второй способ: им сервисом можно
        пользоваться бесконечно и не заплатить ни разу. Человек, дочитавший до
        цен, должен узнать об этом там же, а не пролистав ещё экран. */}
    <section className="tarify-block">
      <h2>Второй способ: приводите друзей</h2>
      <ol className="referral-steps">
        <li><b>1</b><span>Берёте личную ссылку в настройках или у бота командой <code>/invite</code></span></li>
        <li><b>2</b><span>Друг переходит по ней и заводит дневник</span></li>
        <li><b>3</b><span>Он ведёт записи неделю — и месяц доступа получаете вы оба</span></li>
      </ol>
      <p>
        <strong>Потолка нет.</strong> Привели двоих — два месяца, привели десятерых — десять.
        Месяцы складываются с оплаченными и с пробным: остаток не сгорает, дни просто
        прибавляются к сроку. Так сервисом можно пользоваться бесконечно и не заплатить ни разу.
      </p>
      <p>
        Награда приходит на седьмой день записей приглашённого, а не за переход по ссылке.
        Иначе это была бы не благодарность, а раздача: нам ценен человек, который начал вести
        дневник, а не клик. И приглашённому месяц тоже достаётся — сверх его собственного
        пробного, а не вместо него.
      </p>
    </section>

    <p className="price-note">
      Условия, возврат и порядок оплаты — в <Link href="/legal/tarify">тарифах и оферте</Link>.
    </p>
  </article>;
}
