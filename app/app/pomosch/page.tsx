import type { Metadata } from "next";
import Link from "next/link";
import { hintSheet } from "@/lib/first-run";
import { mascotImage } from "@/lib/mascot";

/**
 * Шпаргалка: все объяснения Живело на одной странице.
 *
 * Подсказки на «Сегодня» показываются по одной, к месту и один раз — так и
 * должно быть. Но у одноразового объяснения есть обратная сторона: вопрос
 * «а где тут неделя» возникает не в первый день, а через месяц, когда
 * подсказка давно закрыта и не вернётся. Эта страница — ответ на него.
 *
 * Тексты берутся из `lib/first-run.ts`, а не пишутся заново: две версии
 * одного объяснения разошлись бы через месяц, и человек, прочитавший справку,
 * не узнал бы в ней то, что видел на экране.
 *
 * Страница внутри кабинета, а не в открытой части сайта: половина текста — про
 * «ваши» экраны, и каждая ссылка ведёт внутрь. Публичная копия была бы вторым
 * текстом про то же самое.
 */

export const metadata: Metadata = {
  title: "Как всё устроено — Живое Тело",
  // Кабинет закрыт от индексации целиком, но метку ставим явно: страница
  // выглядит как статья и рано или поздно попадёт кому-нибудь в ссылку.
  robots: { index: false, follow: false },
};

/** Куда ведёт кнопка шага. Тот же перевод намерений, что в подсказке. */
const HREF: Record<string, string> = {
  camera: "/app/add",
  diary: "/app",
  week: "/app/review",
  weight: "/app/weight",
  profile: "/app/settings",
};

export default function HelpPage() {
  const entries = hintSheet();

  return <main className="help">
    <header className="help-head">
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img src={mascotImage("calm")} alt="" aria-hidden width={288} height={288} />
      <div>
        <h1>Как всё устроено</h1>
        <p>
          То же, что я рассказываю по ходу дела, — но сразу и целиком.
          Читать подряд необязательно: скорее всего, вы пришли за одним пунктом.
        </p>
      </div>
    </header>

    <ol className="help-list">
      {entries.map((entry) => (
        <li key={entry.key}>
          <h2>{entry.title}</h2>
          <p>{entry.text}</p>
          {entry.action && <Link className="help-action" href={HREF[entry.action.target] ?? "/app"}>
            {entry.action.label} →
          </Link>}
        </li>
      ))}
    </ol>

    {/* Дальше — то, о чём подсказки молчат: это не первые шаги, а вещи,
        за которыми приходят позже и целенаправленно. Держать их в правилах
        онбординга значило бы показывать их не вовремя. */}
    <h2 className="help-more-title">И ещё несколько вещей</h2>
    <ol className="help-list">
      <li>
        <h2>Инбокс</h2>
        <p>
          Всё присланное боту копится здесь и ждёт разбора. Записи из инбокса попадают в тот день,
          когда были присланы, — разбирать вечером за весь день не значит свалить всё в вечер.
        </p>
        <Link className="help-action" href="/app/inbox">Открыть инбокс →</Link>
      </li>
      <li>
        <h2>Что съесть дальше</h2>
        <p>
          Карточка на «Сегодня» ведёт на подбор: сервис считает, сколько осталось до конца дня по
          белку и клетчатке, и предлагает варианты под этот остаток. Это подсказка, а не
          предписание, — что съесть, решаете вы.
        </p>
        <Link className="help-action" href="/app/next">Посмотреть подбор →</Link>
      </li>
      <li>
        <h2>Отчёты за неделю и месяц</h2>
        <p>
          Приходят в Telegram или на почту — что выберете. Их можно выключить совсем: отчёт,
          который читают через силу, хуже, чем никакого.
        </p>
        <Link className="help-action" href="/app/settings">Настроить отчёты →</Link>
      </li>
      <li>
        <h2>Доступ для специалиста</h2>
        <p>
          Диетологу или врачу можно открыть дневник по коду, который он вам даст: доступ работает
          только на чтение и только в том объёме, который вы выбрали. Закрывается в одно нажатие,
          без объяснений. Кто и когда заходил, видно в журнале обращений.
        </p>
        <Link className="help-action" href="/app/specialists">Управлять доступом →</Link>
      </li>
      <li>
        <h2>Ваши данные</h2>
        <p>
          Всё, что сервис о вас знает, выгружается одним файлом — приёмы пищи и их состав, вес,
          план, согласия. Аккаунт удаляется оттуда же, вместе со всем содержимым.
        </p>
        <Link className="help-action" href="/app/settings">К настройкам →</Link>
      </li>
    </ol>

    <p className="help-foot">
      Сервис считает и показывает, но не ставит диагнозов и не назначает лечения.
      При заболеваниях, беременности и приёме лекарств план стоит обсудить с врачом.
    </p>
  </main>;
}
