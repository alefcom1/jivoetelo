"use client";

import { useEffect } from "react";
import { GOAL_REPORT_OPENED, reachGoal } from "@/lib/goals";

/**
 * Отмечает открытие недельного обзора.
 *
 * Каждый раз, а не однажды: «сколько людей вообще открывали обзор» — вопрос
 * про воронку, но «как часто его открывают» важнее, и одноразовая отметка
 * ответила бы только на первый.
 *
 * Ссылки из писем ведут сюда же, поэтому отдельной цели для письма нет: с
 * меткой `?from=report` в адресе их всегда можно разделить в отчёте Метрики
 * по параметрам визита.
 */
export function ReportOpened() {
  useEffect(() => { reachGoal(GOAL_REPORT_OPENED); }, []);
  return null;
}
