/**
 * Аватар: фото или монограмма, с короной у оплаченного доступа.
 *
 * ## Монограмма осталась, и это не заглушка
 *
 * Фото есть не у всех и не появится у большинства: загрузка картинки — шаг,
 * который человек делает, только если ему зачем-то нужно. Монограмма —
 * буква и цвет, выведенные из адреса почты, — даёт узнавание без единого
 * запроса и у каждого своя. Серый круг с силуэтом не даёт ничего.
 *
 * ## Почему не фото из Telegram напрямую
 *
 * Оно есть — `photo_url` в подписанном initData. Но лежит на CDN Telegram,
 * то есть в интерфейсе появился бы внешний хост: страница, которая обязана
 * открываться и без доступа наружу, начала бы зависеть от чужого сервера, а
 * заодно сообщать ему, когда её открыли. Поэтому фото из Telegram мы
 * **забираем один раз** и кладём рядом со снимками еды (app/api/tg/avatar) —
 * дальше оно наше.
 *
 * ## Корона
 *
 * Своей рисовкой, а не эмодзи 👑. В Mini App эмодзи рисует Telegram, в вебе —
 * операционная система, и один и тот же значок выглядел бы в двух интерфейсах
 * по-разному (см. правило в docs/miniapp-v2.md). Плюс эмодзи не подкрашивается
 * под палитру.
 */

