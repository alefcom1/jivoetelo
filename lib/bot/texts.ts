/**
 * Подтверждение расшифровки.
 *
 * Расшифровку показываем целиком и дословно — это главное в сообщении.
 * Распознавание ошибается, и человек должен увидеть услышанное до того, как
 * оно станет строчкой в дневнике: «сто грамм» и «сто пятьдесят грамм»
 * отличаются на глаз мгновенно, а в посчитанных калориях — уже нет.
 *
 * Сам разбор идёт в приложении, как и у фото: там есть экран для порций и
 * уточняющих вопросов, а лента сообщений для этого не годится.
 */
export function voiceSavedText(transcript: string): string {
  return `🎤 <b>Услышал:</b>\n«${escapeHtml(transcript)}»\n\n` +
    "Сохранил в инбокс. Разберите — посчитаю состав и запишу в дневник.";
}

export function photoSavedText(pendingToday: number): string {
  if (pendingToday <= 1) {
    return "📸 <b>Сохранил.</b>\n\nВечером напомню разобрать — или откройте инбокс прямо сейчас.";
  }
  return `📸 <b>Сохранил</b>, теперь в инбоксе ${pendingToday}.\n\nВечером напомню разобрать.`;
}

