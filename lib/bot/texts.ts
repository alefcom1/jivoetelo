/**
 * Всё, что бот говорит. Вынесено из handle-update.ts отдельным модулем:
 * текстов стало больше, чем логики, и править формулировки удобнее там, где
 * они лежат рядом и видно интонацию соседей.
 *
 * Тон. Бот — не собеседник и не диетолог. Он принимает снимки, отвечает
 * коротко и всегда говорит, что делать дальше. Три правила, из которых
 * выведены все формулировки ниже:
 *
 * 1. **Никаких оценок еды.** Ни «много», ни «вредно», ни «зато завтра». Это
 *    продуктовое правило всего сервиса, в боте оно особенно важно: сообщение
 *    в мессенджере читается лично.
 * 2. **Тупиков не бывает.** На любое сообщение человек должен узнать, что
 *    делать дальше. Отписка «не понимаю» — это дефект, а не ответ.
 * 3. **Честно про то, чего нет.** Голос, видео, распознавание текста — всё
 *    это бот не умеет. Обещать «скоро» не надо; надо назвать рабочий путь.
 *
 * ## Про разметку и эмодзи
 *
 * Все тексты здесь отправляются с `parse_mode: HTML` — см. lib/bot/markup.ts.
 * Голых `<` и `&` в них быть не должно, за этим следит тест.
 *
 * Эмодзи тут есть, хотя в Mini App их нет и не будет (docs/miniapp-v2.md:
 * «без эмодзи», свой набор иконок). Это не противоречие, а разные среды.
 * В вебе эмодзи рисует шрифт операционной системы: одна и та же строка
 * выглядит по-разному в Windows, macOS и Android и ломает набор рядом с
 * нашей гарнитурой. Внутри Telegram эмодзи рисует сам Telegram, своим
 * набором, одинаково на всех платформах — там это такой же элемент
 * интерфейса, как у нас иконки категорий.
 *
 * Правило употребления: **один значок в начале первой строки как признак
 * состояния** (сохранено, не вышло, выключено) — и значки как маркеры
 * списка там, где список есть. Не в середине фразы и не по два подряд.
 */

