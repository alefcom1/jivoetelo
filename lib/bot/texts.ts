/**
 * Распознавание вопросов по ключевым словам. Не диалоговая система: бот
 * отвечает на десяток тем, которые люди правда спрашивают, а на остальное
 * честно отдаёт справку.
 *
 * Основы слов, а не полные формы, — по той же причине, что и в
 * lib/food-category.ts: в русском меняются окончания. Порядок важен: первое
 * совпадение выигрывает, поэтому узкие темы стоят выше широких.
 */
const QUESTION_ROUTES: Array<{ answer: string; stems: string[] }> = [
  // Здоровье — выше всего: тут ошибиться дороже всего остального вместе.
  { answer: ANSWERS.notMedical, stems: ["врач", "диетолог", "здоров", "болезн", "диабет", "беремен", "лечен", "нутрициолог", "безопасн"] },
  { answer: ANSWERS.privacy, stems: ["удалит", "удали", "данны", "приватн", "конфиденц", "выгруз", "персональн"] },
  { answer: ANSWERS.unlink, stems: ["отвяз", "отключит аккаунт", "сменит аккаунт"] },
  { answer: ANSWERS.price, stems: ["платн", "стоит", "стоимост", "цена", "подписк", "тариф", "бесплатн", "деньг"] },
  { answer: ANSWERS.reminders, stems: ["напомин", "уведомлен", "пуш", "спам"] },
  { answer: ANSWERS.openApp, stems: ["приложен", "открыт", "миниап", "mini app", "дневник открыт"] },
  { answer: ANSWERS.help, stems: ["помощ", "справк", "умеет", "умеешь", "команд", "как польз", "что ты", "кто ты", "не работа", "не понимаю"] },
];

function normalize(text: string): string {
  return text.toLowerCase().replace(/ё/g, "е").replace(/\s+/g, " ").trim();
}

/**
 * Ответ на вопрос словами или null, если тема не опознана.
 *
 * Длинные сообщения не разбираем: чем длиннее текст, тем вероятнее, что это
 * не вопрос, а описание еды или рассказ о себе, и случайное слово внутри не
 * повод выдать справку про тарифы.
 */
export function answerForQuestion(text: string): string | null {
  const normalized = normalize(text);
  if (normalized.length === 0 || normalized.length > 200) return null;
  for (const route of QUESTION_ROUTES) {
    if (route.stems.some((stem) => normalized.includes(stem))) return route.answer;
  }
  return null;
}

/**
 * Похоже ли сообщение на описание еды. Признак простой и намеренно грубый:
 * есть слово из знакомых категорий (lib/food-category.ts опознаёт его не как
 * «прочее») либо цифра рядом с единицей измерения. Ошибиться в эту сторону
 * не страшно: ответ всё равно ведёт в приложение.
 */
export function looksLikeFood(text: string, isKnownFood: (name: string) => boolean): boolean {
  const normalized = normalize(text);
  if (normalized.length < 3 || normalized.length > 200) return false;
  if (normalized.startsWith("/")) return false;
  if (/\d+\s*(г|гр|грамм|мл|шт|ложк|стакан|кусоч|порц)/.test(normalized)) return true;
  return normalized.split(/[^a-zа-я0-9]+/).filter(Boolean).some(isKnownFood);
}

