/**
 * Вес, присланный боту одним сообщением.
 *
 * Зачем вообще. Адаптивная норма стоит на тренде веса (lib/trend.ts), а
 * записать вес до сих пор можно было только в приложении: открыть Mini App,
 * найти вкладку, нажать «добавить». Три движения ради одного числа, которое
 * человек уже держит в голове, стоя на весах. Данных не хватало чаще всего
 * именно поэтому, и это единственная функция бота, где выгода очевидна до
 * объяснений.
 *
 * Модуль чистый: ни базы, ни времени, ни сети. Разбор строки — то место, где
 * ошибиться легче всего, и проверяться он должен таблицей примеров, а не
 * перепиской с ботом.
 *
 * ## Что считается весом, а что нет
 *
 * Только сообщение, которое целиком является числом — с необязательным «кг»
 * и необязательным словом «вес» впереди. «2 яйца и кофе» весом не считается,
 * и это важнее, чем принять побольше вариантов: приняв за вес описание еды,
 * бот запишет в дневник чужое число, а человек узнает об этом через неделю,
 * увидев обрыв на графике.
 *
 * Границы 30–300 кг те же, что в приложении (app/api/tg/profile/weight):
 * бот — ещё один вход в те же данные, и правила у входов должны совпадать.
 */

export const MIN_WEIGHT_KG = 30;
export const MAX_WEIGHT_KG = 300;

/**
 * Необязательное слово «вес» впереди и необязательные «кг» сзади. Точка и
 * запятая равноправны: на телефоне цифровая клавиатура даёт запятую, и
 * требовать точку значит требовать переключения раскладки ради одного знака.
 */
const WEIGHT_RE = /^(?:вес\s*[:-]?\s*)?(\d{1,3}(?:[.,]\d{1,2})?)\s*(?:кг|kg)?$/i;

export type WeightMessage =
  | { kind: "weight"; weightKg: number }
  /** Число распознано, но такого веса не бывает: 5 кг, 900 кг. */
  | { kind: "out_of_range"; value: number }
  | null;

/**
 * Разбирает сообщение как вес. `null` — «это не про вес», и вызывающий идёт
 * дальше по своим веткам, а не отвечает отказом.
 */
export function parseWeightMessage(text: string): WeightMessage {
  const match = WEIGHT_RE.exec(text.trim());
  if (!match) return null;

  const value = Number(match[1].replace(",", "."));
  if (!Number.isFinite(value)) return null;

  // Ноль и мелочь вроде «5» — это не вес и не опечатка веса: скорее человек
  // написал количество чего-то. Отвечать «вес должен быть от 30 кг» на «5»
  // было бы навязчиво, поэтому такие числа просто не наши.
  if (value < MIN_WEIGHT_KG / 2) return null;
  if (value < MIN_WEIGHT_KG || value > MAX_WEIGHT_KG) return { kind: "out_of_range", value };

  // Округляем до сотых: весы дают один знак, а человек может дописать второй.
  return { kind: "weight", weightKg: Math.round(value * 100) / 100 };
}
