/** Границы одной записи. Верхняя — не запрет, а защита от лишнего нуля. */
export const MIN_ENTRY_ML = 10;
export const MAX_ENTRY_ML = 3000;

export type WaterEntry = { id: number; ml: number };

/** Сколько выпито за день. */
export function sumMl(entries: readonly WaterEntry[]): number {
  return entries.reduce((total, entry) => total + entry.ml, 0);
}

/**
 * ## Сколько воды пришло с едой
 *
 * Та самая строка, ради которой счётчик и стоит делать: все считают «сколько
 * выпить», не отделяя того, что придёт с супом и овощами. EFSA нормирует
 * **всю** воду, и еда в обычном рационе даёт 20–30% от неё.
 *
 * Считаем не долей от нормы, а по тому, что человек правда съел. Воду в
 * продукте оцениваем «по остатку»: если из 100 г вычесть белки, жиры,
 * углеводы, клетчатку и золу, останется вода. Зола (минеральный остаток) у
 * обычной еды около 1 г на 100 г — её не храним и берём константой.
 *
 * Метод грубый, но проверяемый, и на настоящей еде ошибается мало:
 * огурец — 95%, борщ — 89%, отварная гречка — 73%, хлеб — 40%, масло — 0%.
 * Всё это сходится со справочными значениями в пределах процента-двух.
 *
 * Где он врёт и почему это не страшно:
 *
 * - **Алкоголь.** У этанола есть калории, но по макронутриентам он не
 *   проходит нигде, и остаток запишет его в воду. Пиво по этому счёту
 *   окажется водой на 92% — что, впрочем, физически почти верно; спорна тут
 *   не вода, а уместность считать её «пришедшей с едой».
 * - **Пустые макросы.** У позиции, разобранной без БЖУ (все нули), остаток
 *   даст 99% воды. Поэтому такие позиции пропускаем целиком: молчание
 *   честнее выдуманного числа.
 *
 * Результат округляем и показываем со знаком «≈». Это оценка, и подавать её
 * точным числом было бы ровно той псевдоточностью, против которой заведён
 * весь расчёт.
 */
export type FoodWaterItem = {
  grams: number;
  proteinPer100: number;
  fatPer100: number;
  carbsPer100: number;
  fiberPer100: number;
};

/** Зола — минеральный остаток, г на 100 г обычной еды. */
const ASH_PER_100 = 1;

export function estimateFoodWaterMl(items: readonly FoodWaterItem[]): number {
  let ml = 0;
  for (const item of items) {
    if (!(item.grams > 0)) continue;
    const solids = item.proteinPer100 + item.fatPer100 + item.carbsPer100 + item.fiberPer100;
    // Позиция без единого макронутриента — это «не разобрали», а не «одна
    // вода». Отличить их по данным нельзя, поэтому не считаем вовсе.
    if (solids <= 0) continue;
    const waterPer100 = Math.max(0, 100 - solids - ASH_PER_100);
    // 1 г воды = 1 мл: для наших целей плотность воды можно считать единицей.
    ml += (waterPer100 * item.grams) / 100;
  }
  return Math.round(ml);
}

/**
 * Ориентир по напиткам на день.
 *
 * Возвращает `null`, когда профиля или веса ещё нет: счётчик работает и без
 * цели — как полосы макронутриентов, которые без плана показывают число без
 * полосы. Придумывать «2 литра всем» вместо этого мы не будем.
 *
 * Жара и нагрузка в ориентир не входят: мы их не знаем. Об этом сказано
 * строкой в интерфейсе, а не молчаливой прибавкой.
 */
export function drinkGoalMl(input: { sex: "female" | "male"; weightKg: number; tdeeKcal: number } | null): number | null {
  if (!input) return null;
  return computeWater(input).drinkMl;
}

/** Полный расчёт нормы — когда нужна ещё и доля из еды по формуле. */
export function waterReference(input: { sex: "female" | "male"; weightKg: number; tdeeKcal: number }): WaterResult {
  return computeWater(input);
}

/**
 * Подпись под счётчиком. Ни одна ветка не ругает и не хвалит: это те же
 * правила, по которым говорит недельный обзор — факт, а не оценка.
 *
 * Перебор молчит отдельно и сознательно. «Вы выпили больше нормы» — фраза,
 * которая пугает без причины: у здорового человека лишний стакан воды не
 * событие, а вот тревожность по поводу цифры — вполне.
 */
export function waterNote(drunkMl: number, goalMl: number | null, foodMl: number): string {
  const food = foodMl > 0 ? `С едой сегодня пришло ещё ≈ ${formatMl(foodMl)}. ` : "";
  if (goalMl === null) {
    return `${food}Ориентир появится, когда будет план: он зависит от пола, веса и расхода энергии.`;
  }
  if (drunkMl >= goalMl) {
    return `${food}Это в пределах ориентира. В жару и после нагрузки нужно больше — ориентир их не знает.`;
  }
  const left = goalMl - drunkMl;
  return `${food}До ориентира ещё ${formatMl(left)}. Это не норма и не долг: в жару и после нагрузки нужно больше, в прохладный день меньше.`;
}

/** «1,4 л» вместо «1400 мл»: литрами меряют день, миллилитрами — глоток. */
export function formatMl(ml: number): string {
  if (ml < 1000) return `${ml} мл`;
  const litres = ml / 1000;
  // Одна десятая — предел осмысленной точности: 1,45 л никто не отмеряет.
  const text = litres.toFixed(1).replace(".", ",");
  return `${text.endsWith(",0") ? text.slice(0, -2) : text} л`;
}
