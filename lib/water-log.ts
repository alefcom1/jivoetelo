/**
 * Счётчик жидкости: чистая логика.
 *
 * Норму считает lib/water.ts — она же стоит за калькулятором `/raschet/voda`,
 * и второй раз её здесь не выводим. Этот модуль отвечает на три вопроса
 * счётчика: сколько выпито за день, сколько воды пришло с едой и что писать
 * рядом с числом.
 *
 * Без обращений к базе — по той же причине, что и lib/diary.ts против
 * lib/meals.ts: модуль с `@/db` не поднимается под голым `node --test`.
 * Работа с базой — в lib/water-store.ts.
 */

import { computeWater, GLASS_ML, type WaterResult } from "./water.ts";

