/**
 * «23 расчёта», а не «23 расчётов».
 *
 * Пока страниц было пятнадцать, форма совпадала со множественной и подпись
 * стояла в разметке строкой. На двадцати трёх она сломалась — ровно тот
 * случай, когда захардкоженное окончание живёт до первого изменения числа.
 */
export function calculatorsWord(count: number): string {
  const mod10 = count % 10;
  const mod100 = count % 100;
  if (mod10 === 1 && mod100 !== 11) return "расчёт";
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return "расчёта";
  return "расчётов";
}
