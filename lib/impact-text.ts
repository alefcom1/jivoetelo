// Как разбор из lib/weight-response.ts превращается в текст.
//
// Отдельным модулем, потому что здесь — самая опасная часть функции. Числа
// нельзя переврать случайно, а формулировку — очень легко: «пельмени повышают
// ваш вес» и «в дни с пельменями весы наутро в среднем выше вашего тренда»
// описывают одну и ту же цифру, но первое — утверждение о причине, которого
// расчёт не делает и сделать не может.
//
// Правила, которые здесь соблюдаются и проверяются тестами:
//
// 1. Никакой причинности. Не «влияет», «из-за», «виновато», «мешает».
//    Только «в дни с …», «после дней с …».
// 2. Никаких оценок еды. Ни «вредно», ни «полезно», ни «плохое»,
//    ни «хорошее» — это прямой запрет спецификации (раздел 4.3) и обещание,
//    записанное в юридическом документе /legal/health.
// 3. Объяснение про воду — частью самой фразы, а не сноской. Человек,
//    прочитавший «+0,7 кг», должен в том же предложении узнать, что это вода.
// 4. Рядом с каждым числом — сколько наблюдений за ним стоит.
// 5. Слово «наблюдение», а не «вывод».

import { dishKeyLabel } from "./dish-key.ts";
import { withPluralRu, type PluralForms } from "./plural.ts";
import {
  FLAG_ALCOHOL,
  FLAG_LATE_MEAL,
  MIN_PAIRS_STATISTICAL,
  type Effect,
  type ImpactReport,
} from "./weight-response.ts";

const DAY_FORMS: PluralForms = ["день", "дня", "дней"];
const OBSERVATION_FORMS: PluralForms = ["наблюдение", "наблюдения", "наблюдений"];

/** Признаки дня называются словами, а не ключами. */
const FLAG_LABELS: Record<string, string> = {
  [FLAG_ALCOHOL]: "алкоголем",
  [FLAG_LATE_MEAL]: "поздним ужином",
};

function subject(key: string): string {
  return FLAG_LABELS[key] ?? dishKeyLabel(key).toLowerCase();
}

function formatKg(value: number): string {
  const rounded = Math.abs(Math.round(value * 10) / 10);
  return rounded.toFixed(1).replace(".", ",");
}

/**
 * Одно наблюдение об одном блюде.
 *
 * «Выше вашего тренда», а не «выше»: тренд — это личная база сравнения
 * человека, и без неё фраза читалась бы как «вы потолстели».
 */
export function describeEffect(effect: Effect): string {
  const direction = effect.deltaKg > 0 ? "выше" : "ниже";
  const water = effect.deltaKg > 0
    ? "Так ведёт себя вода — соль и углеводы задерживают её на день-другой, к жировой массе это отношения не имеет."
    : "Это тоже вода, а не потеря жира: за сутки её уходит и приходит куда больше, чем успевает измениться жировая масса.";

  return `В дни с ${subject(effect.key)} весы наутро в среднем на ${formatKg(effect.deltaKg)} кг ${direction} вашего тренда `
    + `(${withPluralRu(effect.nWith, OBSERVATION_FORMS)} против ${effect.nWithout}). ${water}`;
}

/**
 * Заголовок и текст раздела для экрана, письма и дневника.
 *
 * Возвращает `null`, когда показывать нечего: раздел, который каждую неделю
 * что-нибудь «находит», через месяц читается как гороскоп. Пустой ответ —
 * такой же результат, как непустой, и он честнее выдуманного.
 */
export function buildImpactSection(report: ImpactReport): { title: string; text: string } | null {
  if (report.level === "none") {
    // Ниже самого нижнего порога не говорим даже «пока рано» — на этом
    // уровне человеку нечего с этим делать, а строка в отчёте создавала бы
    // ощущение незакрытого дела.
    return null;
  }

  if (report.level === "descriptive") {
    return {
      title: "Вес и еда",
      text: `Пока мы только копим наблюдения: пар «день с дневником → замер наутро» набралось ${report.usablePairs}, `
        + `для разбора по блюдам нужно ${MIN_PAIRS_STATISTICAL}. Не хватает ещё ${withPluralRu(report.missingPairs, DAY_FORMS)} `
        + `с записями и взвешиванием подряд. Это не задержка — так устроен сам расчёт: чтобы отличить блюдо от обычных `
        + `колебаний воды, наблюдений нужно много.`,
    };
  }

  const reportable = report.effects.filter((effect) => effect.reportable);
  if (reportable.length === 0) {
    return {
      title: "Вес и еда",
      text: `Мы разобрали ${report.usablePairs} пар «день с дневником → замер наутро» и не нашли ни одного блюда, `
        + `после которого весы вели бы себя иначе, чем обычно. Это честный ответ, а не пропущенный раздел: `
        + `у большинства людей еда так и не даёт устойчивого следа на утренних весах.`,
    };
  }

  return {
    title: "Вес и еда",
    text: reportable.map(describeEffect).join(" ")
      + " Это наблюдения по вашему дневнику, а не советы что-то исключать: разовые колебания воды ничего не говорят"
      + " о жировой массе, и убирать из рациона по ним нечего.",
  };
}

/**
 * Строка для «Сегодня» — одно наблюдение о вчерашнем дне.
 *
 * Работает без всякой статистики, с первой же пары замеров, и в этом её
 * смысл: она объясняет человеку колебания весов ровно тогда, когда он их
 * видит, вместо того чтобы ждать восьми недель.
 */
export function describeYesterday(deviationKg: number, flags: string[]): string | null {
  if (Math.abs(deviationKg) < 0.3) return null;

  const named = flags.map((flag) => FLAG_LABELS[flag]).filter(Boolean);
  const because = named.length > 0 ? ` Вчера в записях: ${named.join(" и ")}.` : "";

  return deviationKg > 0
    ? `Сегодня весы на ${formatKg(deviationKg)} кг выше вашего тренда.${because} За ночь столько жира не набирается — `
      + `это вода, и она уходит сама за день-другой.`
    : `Сегодня весы на ${formatKg(deviationKg)} кг ниже вашего тренда.${because} Это тоже вода, а не потеря жира — `
      + `смотреть стоит на тренд, он для того и считается.`;
}
