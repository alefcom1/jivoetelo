/**
 * Когда напоминать о доступе на экране, который открывают каждый день.
 *
 * ## Зачем это отдельным правилом
 *
 * Кнопки оплаты стояли там, где человек их ищет: в настройках, в профиле
 * Mini App, на странице цены. Проблема в том, что **искать их он начинает
 * только когда уже упёрся**, — а до этого момента сервис тридцать дней ведёт
 * себя так, будто денег не существует, и потом ставит перед стеной.
 *
 * Полоса на «Сегодня» закрывает именно этот промежуток. Она не про продажу
 * в лоб: она сообщает срок — то же, что показывают настройки, — но на том
 * экране, куда человек и так заходит каждый день.
 *
 * ## Почему семь дней, а не тридцать
 *
 * Полоса, висящая весь месяц, перестаёт читаться на третий день и начинает
 * мешать: место на первом экране дорогое, а «доступ до 5 сентября» при
 * двадцати восьми оставшихся днях не требует никаких действий. Семь дней —
 * это когда срок уже виден, но ещё не поздно.
 *
 * За три дня бот пишет отдельно (lib/reminders.ts). Одно другому не мешает:
 * полоса молчаливая и живёт на экране, сообщение приходит само. У человека,
 * выключившего бота, остаётся полоса; у того, кто месяц не открывал
 * приложение, — сообщение.
 */

export const ACCESS_PROMPT_DAYS = 7;

export type AccessPrompt = {
  /** Сколько дней осталось. 0 — доступ уже закрыт. */
  daysLeft: number;
  /** Доступ держится пробным месяцем, а не оплатой. */
  trial: boolean;
  /** Закрыт совсем: разбор не работает. */
  closed: boolean;
};

/**
 * Показывать ли полосу. `null` — нет, и это самый частый исход: у человека с
 * открытым доступом и запасом времени на первом экране должен быть его день,
 * а не разговор про деньги.
 *
 * Заплатившему с запасом не показываем ничего. Это не мелочь: напоминание об
 * оплате тому, кто только что заплатил на год, читается как «сервис не помнит,
 * что я плачу», — и стоит дороже, чем даёт.
 */
export function accessPrompt(input: {
  daysLeft: number;
  trial: boolean;
}): AccessPrompt | null {
  if (input.daysLeft <= 0) return { daysLeft: 0, trial: input.trial, closed: true };
  if (input.daysLeft > ACCESS_PROMPT_DAYS) return null;
  return { daysLeft: input.daysLeft, trial: input.trial, closed: false };
}

/**
 * Что написано на полосе.
 *
 * Три состояния и три разных разговора. Пробный месяц на исходе — человек
 * ещё ничего не решал, и ему важно узнать, что именно закончится. Оплаченный
 * доступ на исходе — он уже решал раньше, ему нужен срок и кнопка. Доступ
 * закрыт — тут главное не «заплатите», а «записи на месте»: человек с
 * месяцами дневника в первую очередь боится потерять их, а не лимит.
 */
export function accessPromptText(prompt: AccessPrompt): { title: string; body: string } {
  if (prompt.closed) {
    return {
      title: "Разбор по фото сейчас закрыт",
      body:
        "Дневник, план, вес, обзоры и выгрузка данных на месте — еду можно записывать руками "
        + "как раньше. Разбор открывается оплатой или приглашением друга.",
    };
  }
  const days = plural(prompt.daysLeft);
  if (prompt.trial) {
    return {
      title: `Пробный месяц заканчивается через ${days}`,
      body:
        "Потом закроется только разбор по фото, по описанию и голосом. Дневник, план, вес и "
        + "обзоры останутся открытыми.",
    };
  }
  return {
    title: `Доступ открыт ещё ${days}`,
    body: "Остаток при продлении не сгорает: дни прибавляются к уже оплаченным.",
  };
}

/** «5 дней», «1 день», «22 дня». Отдельно, потому что число подставное. */
function plural(days: number): string {
  const mod100 = days % 100;
  const mod10 = days % 10;
  if (mod100 >= 11 && mod100 <= 14) return `${days} дней`;
  if (mod10 === 1) return `${days} день`;
  if (mod10 >= 2 && mod10 <= 4) return `${days} дня`;
  return `${days} дней`;
}
