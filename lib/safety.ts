/**
 * Одно правило смягчения цели — на весь продукт.
 *
 * ## Зачем понадобилось
 *
 * Правил было два, и они расходились. `evaluateQuiz` (lib/quiz.ts) отговаривал
 * от дефицита по шести признакам: тяжёлые отношения с едой, напряжённые вместе
 * с постоянными диетами, перегрузка, плохой сон, диеты подряд и недавняя диета
 * при немедицинской мотивации. А `effectiveGoal` (lib/onboarding.ts) смягчал
 * цель только по двум: несовершеннолетний возраст и тяжёлые отношения с едой.
 *
 * Из-за этого витрина сайта была бережнее самого дневника. Человек, который на
 * квизе получил бы «сейчас не время», в онбординге спокойно получал дефицит —
 * достаточно было зайти мимо квиза, то есть обычным путём. Хуже того: четырёх
 * из шести признаков онбординг вообще не спрашивал, так что и починить это
 * «добавив проверку» было нельзя.
 *
 * Теперь признаки собраны в один тип, а решение — в одну функцию. Квиз
 * пересказывает её вывод словами, онбординг превращает в цель. Разойтись они
 * больше не могут: тест перебирает все сочетания ответов и требует, чтобы
 * вердикт квиза «не сейчас» всегда означал смягчённую цель.
 *
 * ## Что здесь не решается
 *
 * Это не про безопасность расчёта — нижние границы калорий и потолки темпа
 * живут в lib/targets.ts и lib/pace.ts и работают независимо. Здесь только
 * вопрос «уместно ли вообще предлагать снижение веса прямо сейчас».
 */

export type Relationship = "calm" | "tense" | "hard";
export type Sleep = "ok" | "poor";
export type LifeLoad = "calm" | "busy" | "overloaded";
export type RecentDieting = "no" | "recently" | "constantly";
export type Motivation = "health" | "look" | "energy" | "unsure";

/**
 * Признаки, по которым решается вопрос. Все необязательные: онбординг
 * спрашивает не всё, и отсутствие ответа — это «не знаем», а не «всё хорошо».
 */
export type SafetySignals = {
  relationship?: Relationship;
  sleep?: Sleep;
  lifeLoad?: LifeLoad;
  recentDieting?: RecentDieting;
  motivation?: Motivation;
  /** Возраст меньше восемнадцати. Считается вызывающим, здесь только флаг. */
  minor?: boolean;
};

/**
 * Почему дефицит сейчас неуместен. Порядок перечисления — это порядок
 * приоритета: первая сработавшая причина и становится ответом.
 */
export type SofteningReason =
  | "minor"
  | "hard_relationship"
  | "overload"
  | "dieting_cycle";

/**
 * Причина смягчить цель или `null`, если ничего не мешает.
 *
 * Порядок проверок важен и совпадает с порядком вердиктов в lib/quiz.ts:
 * возраст выше всего, потом отношения с едой, потом перегрузка и сон, потом
 * история диет. Тяжёлые отношения с едой стоят выше перегрузки не случайно —
 * недосып проходит, а расстройство пищевого поведения от подсчёта калорий
 * усугубляется.
 */
export function softeningReason(signals: SafetySignals): SofteningReason | null {
  if (signals.minor) return "minor";

  if (
    signals.relationship === "hard" ||
    (signals.relationship === "tense" && signals.recentDieting === "constantly")
  ) {
    return "hard_relationship";
  }

  if (signals.lifeLoad === "overloaded" || signals.sleep === "poor") return "overload";

  if (
    signals.recentDieting === "constantly" ||
    (signals.recentDieting === "recently" && signals.motivation !== undefined && signals.motivation !== "health")
  ) {
    return "dieting_cycle";
  }

  return null;
}

