/**
 * Тексты, которые уходят наружу: другу в переписку и в соцсети.
 *
 * ## Правило, которое здесь важнее всех остальных
 *
 * Ни одного килограмма. Карточка «−5 кг за месяц» делает три плохие вещи
 * разом: объявляет вес счётом, приглашает сравнивать несравнимые тела и
 * обещает получателю ровно то, чего сервис прямо не обещает в собственных
 * документах. Наружу уходит только факт наблюдения: сколько дней человек вёл
 * дневник и сколько сделал записей. Проверяется тестом на самих наградах
 * (tests/awards.test.mjs).
 *
 * ## И второе: это текст от человека, а не от сервиса
 *
 * Его отправляют друзьям. Поэтому здесь нет ни «присоединяйтесь», ни
 * «попробуйте бесплатно», ни восклицаний: человек делится тем, что у него
 * вышло, а не пересылает рекламу. Строка про сервис — одна и в конце.
 */

import { referralLink } from "./referral.ts";

/**
 * Приглашение без повода: просто «вот чем я пользуюсь».
 *
 * Вторая строка была «Бесплатно, без подписки и без рекламы». Она перестала
 * быть правдой в тот день, когда бесплатный тариф сменился пробным месяцем, —
 * а сообщение с обещанием бесплатности уходит к людям, которые про сервис не
 * знают ничего и проверить его не могут. Теперь там условие приглашения, и
 * оно названо целиком, включая неудобную половину: месяц приходит не за
 * переход по ссылке, а после недели записей.
 */
export function inviteText(code: string | null): string {
  const link = code ? referralLink(code) : "https://jivoetelo.ru";
  return [
    "Веду дневник питания в «Живом Теле»: фотографируешь еду — состав считается сам.",
    "Заведёшь по этой ссылке — через неделю записей нам обоим добавится месяц.",
    link,
  ].join("\n");
}

/** Приглашение по поводу награды: сначала факт, потом ссылка. */
export function awardText(share: string, code: string | null): string {
  const link = code ? referralLink(code) : "https://jivoetelo.ru";
  return [
    `У меня ${share} в «Живом Теле».`,
    "Дневник питания, где еду можно просто сфотографировать.",
    link,
  ].join("\n");
}

/**
 * Ссылка на пересылку в Telegram.
 *
 * `t.me/share/url` — старый и всюду работающий способ: открывает выбор
 * получателя прямо в клиенте. Он же и запасной путь для `shareMessage` из Bot
 * API 8.0, которого у части клиентов нет (та же история, что с событием
 * `activated` при обновлении «Сегодня»).
 */
export function telegramShareLink(text: string): string {
  // Ссылка идёт отдельным параметром, а не внутри текста: клиент показывает
  // по ней превью и не ломает перенос строк в сообщении.
  const lines = text.split("\n");
  const url = lines.at(-1) ?? "";
  const body = lines.slice(0, -1).join("\n");
  return `https://t.me/share/url?url=${encodeURIComponent(url)}&text=${encodeURIComponent(body)}`;
}
