// Словарь: понятия, на которых стоит продукт, — простым языком.
//
// Зачем он есть. Аудит (docs/seo-plan-2026-08.md, п. 4) нашёл нишу пустой:
// глоссария нет ни у сильных англоязычных игроков, ни у русскоязычных таблиц.
// При этом ровно эти понятия — диапазон, уверенность, тренд, дефицит —
// человек встречает у нас на каждом экране, и им нужно место, куда ведёт
// ссылка «что это значит».
//
// Откуда тексты. Каждый термин объясняет решение, которое уже записано в
// коде и защищено тестами: диапазоны — lib/dishes.ts, уверенность —
// lib/confidence.ts, тренд — lib/trend.ts (EMA, α=0,25), дефицит —
// lib/pace.ts, адаптивная цель — lib/adaptive.ts (шаг 150, предел 450,
// минимум 5 дней). Числа здесь не сочиняются — они цитируются из кода, и
// разойтись им не даёт то, что оба конца правит один репозиторий.
//
// Правила — те же, что у конвейера (docs/seo-pipeline.md): одна страница —
// одно понятие, никаких медицинских утверждений, спокойный тон, источники
// только настоящие.

export type GlossaryTerm = {
  slug: string;
  /** Название термина — для хаба, хлебных крошек и DefinedTerm.name. */
  title: string;
  /** Заголовок страницы вопросом — так его и ищут. */
  question: string;
  /**
   * Ответ в два-три предложения: идёт в description, в карточку хаба и в
   * DefinedTerm.description. Обязан отвечать на вопрос сам по себе — это то,
   * что человек увидит, не открывая страницу.
   */
  short: string;
  /** Разделы страницы: заголовок + абзацы. */
  sections: Array<{ heading: string; paragraphs: string[] }>;
  /** Куда пойти дальше — внутренняя перелинковка кластера. */
  related: Array<{ href: string; label: string }>;
  /**
   * Дата последней содержательной правки, `ГГГГ-ММ-ДД`. Не задана у
   * большинства — тогда берётся общая дата словаря.
   */
  updatedAt?: string;
};

/**
 * Общая дата словаря — для терминов без собственной.
 *
 * Своя, а не `LEGAL_UPDATED_AT`: правка оферты не меняет объяснение того, что
 * такое диапазон КБЖУ, и показывать её поисковику как изменение содержимого
 * значит обесценивать поле `lastmod` на всех остальных страницах тоже.
 */
export const GLOSSARY_UPDATED_AT = "2026-08-03";

export function glossaryUpdatedAt(term: { updatedAt?: string }): Date {
  return new Date(term.updatedAt ?? GLOSSARY_UPDATED_AT);
}

