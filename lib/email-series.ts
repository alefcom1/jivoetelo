const PLACEHOLDER_RE = /\{\{(\w+)\}\}/g;

/**
 * Возвращает null, если хоть один плейсхолдер сослался на число, которого в
 * контексте нет, — вместо того чтобы падать. У калькулятора белка нет
 * kcalTarget, у страницы блюда нет вообще ничего, и это не повод ронять всё
 * письмо: `renderLetter` использует null, чтобы пропустить абзац или
 * подставить текст без чисел.
 */
function fillPlaceholders(source: string, ctx: SeriesContext): string | null {
  let resolved = true;
  const filled = source.replace(PLACEHOLDER_RE, (match, key: string) => {
    const value = ctx[key as SeriesContextField];
    if (typeof value !== "number") {
      resolved = false;
      return match;
    }
    return formatNumber(value);
  });
  return resolved ? filled : null;
}

/**
 * 1 870 вместо 1870, с неразрывным пробелом. Группы разрядов расставляем
 * сами: toLocaleString вставляет то обычный пробел, то узкий неразрывный — в
 * зависимости от сборки ICU, а письмо должно выглядеть одинаково всегда.
 */
function formatNumber(value: number): string {
  return String(value).replace(/\B(?=(\d{3})+(?!\d))/g, "\u00A0");
}

function escapeHtml(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

export function renderLetter(letter: LetterNumber, ctx: SeriesContext, links: LetterLinks): RenderedLetter {
  const template = TEMPLATES[letter];
  // Тема без подстановки — на fallback, где числа нет вовсе. Абзац с
  // отсутствующим числом просто выпадает: письмо остаётся связным текстом
  // про сам подход, только без конкретной цифры для этого человека.
  const subject = fillPlaceholders(template.subject, ctx) ?? template.subjectFallback ?? template.subject;
  const preheader = fillPlaceholders(template.preheader, ctx) ?? template.preheader;
  const paragraphs = template.paragraphs
    .map((p) => fillPlaceholders(p, ctx))
    .filter((p): p is string => p !== null);

  const signature = "Живое Тело\n" + links.siteUrl;
  const footer =
    `Вы получаете это письмо, потому что оставили адрес после расчёта на ${links.siteUrl}. ` +
    `Отписаться: ${links.unsubscribeUrl}`;

  const text = [...paragraphs, "—", signature, "", footer].join("\n\n");

  const html = [
    // Прехедер: первая строка в списке писем. Прячем её от глаз, но не от
    // почтового клиента — display:none в письмах поддерживается не везде,
    // поэтому дополнительно уводим за пределы экрана.
    `<div style="display:none;max-height:0;overflow:hidden;opacity:0">${escapeHtml(preheader)}</div>`,
    `<div style="max-width:600px;margin:0 auto;padding:24px;font:16px/1.6 -apple-system,BlinkMacSystemFont,'Segoe UI',Roboto,Helvetica,Arial,sans-serif;color:#1c1a17">`,
    ...paragraphs.map((p) => `<p style="margin:0 0 16px">${escapeHtml(p)}</p>`),
    `<p style="margin:32px 0 0;color:#6f6a63">Живое Тело<br><a href="${escapeHtml(links.siteUrl)}" style="color:#6f6a63">${escapeHtml(links.siteUrl)}</a></p>`,
    `<p style="margin:16px 0 0;font-size:13px;line-height:1.5;color:#8c8780">Вы получаете это письмо, потому что оставили адрес после расчёта на сайте. <a href="${escapeHtml(links.unsubscribeUrl)}" style="color:#8c8780">Отписаться</a>.</p>`,
    `</div>`,
  ].join("\n");

  return { subject, preheader, text, html };
}

/**
 * Когда отправить письмо. Сдвигает срок в дневное окно: письмо, выпавшее на
 * четыре утра, придёт в десять того же дня, а не разбудит уведомлением.
 */
export function scheduleLetterAt(subscribedAt: Date, letter: LetterNumber, timeZone?: string): Date {
  const base = new Date(subscribedAt.getTime() + LETTER_DELAY_DAYS[letter] * 24 * 60 * 60 * 1000);

  // Первое письмо — ответ на действие человека, его ждут прямо сейчас.
  if (LETTER_DELAY_DAYS[letter] === 0) return base;

  let at = base;
  for (let step = 0; step < 48; step += 1) {
    const hour = localMoment(at, timeZone).hour;
    if (hour >= SEND_WINDOW_FROM_HOUR && hour < SEND_WINDOW_UNTIL_HOUR) return at;
    at = new Date(at.getTime() + 60 * 60 * 1000);
  }
  return at;
}
