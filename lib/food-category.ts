const PRIORITY = new Map(FOOD_CATEGORIES.map((info, index) => [info.key, index]));

/**
 * Плоский список основ, отсортированный так, чтобы первое найденное
 * совпадение было и самым длинным, и (при равной длине) из более
 * приоритетной категории. Сортируем один раз при загрузке модуля, а не на
 * каждый вызов: список из нескольких сотен строк, а вызывается он на каждую
 * строку дневника.
 */
const SORTED_STEMS: Array<{ stem: string; key: FoodCategory }> = Object.entries(STEMS)
  .flatMap(([key, stems]) => stems.map((stem) => ({ stem, key: key as FoodCategory })))
  .sort((a, b) => b.stem.length - a.stem.length || PRIORITY.get(a.key)! - PRIORITY.get(b.key)!);

/**
 * Нормализация: строчные буквы, «ё» к «е» (модель пишет и так, и так), а всё,
 * что не буква и не цифра, становится границей слова. Дефис здесь именно
 * разделитель: «крем-суп» должен находиться по «суп».
 */
function words(name: string): string[] {
  return name
    .toLowerCase()
    .replace(/ё/g, "е")
    .split(/[^a-zа-я0-9]+/i)
    .filter(Boolean);
}

/**
 * Служебные слова, после которых начинается уточнение, а не само блюдо.
 * «Гречка с курицей» — про гречку, «блины с творогом» — про блины, «каша на
 * воде» — не про воду. Поэтому ищем сначала в голове названия, до первого
 * такого слова, и только если там ничего не нашлось — по всей строке.
 */
const TAIL_MARKERS = new Set([
  "с", "со", "и", "в", "во", "на", "из", "под", "без", "от", "к", "ко", "по", "до", "при",
]);

/**
 * Прилагательное в русском стоит перед существительным, а блюдо называет
 * именно существительное: «молочный шоколад» — шоколад, «оливковое масло» —
 * масло, «сырое яйцо» — яйцо. Совпадение по слову с таким окончанием не
 * отбрасываем совсем (иначе «арахисовая паста» станет пастой), а делаем
 * слабее на несколько букв — этого хватает, чтобы существительное рядом
 * перевесило.
 */
const ADJECTIVE_ENDINGS = [
  "ого", "его", "ому", "ему", "ый", "ий", "ой", "ая", "яя", "ое", "ее", "ые", "ие",
  "ым", "им", "ом", "ем", "ую", "юю", "ых", "их", "ья", "ье", "ьи",
];
const ADJECTIVE_PENALTY = 3;

function looksLikeAdjective(word: string): boolean {
  return word.length > 4 && ADJECTIVE_ENDINGS.some((ending) => word.endsWith(ending));
}

/** Лучшая категория для набора слов или null, если ни одна основа не подошла. */
function bestMatch(parts: string[]): FoodCategory | null {
  let best: { score: number; key: FoodCategory } | null = null;
  for (const word of parts) {
    const penalty = looksLikeAdjective(word) ? ADJECTIVE_PENALTY : 0;
    for (const { stem, key } of SORTED_STEMS) {
      if (!word.startsWith(stem)) continue;
      const score = stem.length - penalty;
      // Основы отсортированы по убыванию длины, поэтому первая подошедшая —
      // лучшая для этого слова; остальные проверять незачем.
      if (!best || score > best.score || (score === best.score && PRIORITY.get(key)! < PRIORITY.get(best.key)!)) {
        best = { score, key };
      }
      break;
    }
  }
  return best?.key ?? null;
}

/** Категория одной позиции. Неизвестное — `other`, а не выдуманная догадка. */
export function foodCategory(name: string): FoodCategory {
  const parts = words(name);
  if (parts.length === 0) return "other";

  const tailAt = parts.findIndex((word) => TAIL_MARKERS.has(word));
  const head = tailAt > 0 ? parts.slice(0, tailAt) : parts;
  return bestMatch(head) ?? bestMatch(parts) ?? "other";
}

/**
 * Категория приёма пищи целиком — по первой позиции, которая тянет на
 * основное блюдо. Соус, напиток и нераспознанное пропускаем: приём
 * «оливковое масло, куриная грудка, огурцы» — про курицу, а не про масло.
 * Если ничего не осталось, берём первую позицию как есть.
 */
export function mealCategory(names: string[]): FoodCategory {
  const categories = names.map(foodCategory);
  const main = categories.find((key) => key !== "sauce" && key !== "drink" && key !== "other");
  return main ?? categories[0] ?? "other";
}
