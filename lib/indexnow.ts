/**
 * IndexNow — уведомление поисковиков о том, что изменилось, в момент выкатки.
 *
 * Зачем. Обычный путь новой страницы в индекс — дождаться, пока робот сам
 * зайдёт по карте сайта. Для хвоста программатик-каталога это недели: чем
 * дальше страница от главной, тем реже к ней заглядывают. IndexNow переворачивает
 * порядок: не робот приходит проверять, а мы говорим, что именно поменялось.
 * Яндекс протокол поддерживает (`docs/seo-plan-2026-08.md`, п. 3.8), а участники
 * делятся заявками между собой, так что одной отправки хватает на всех.
 *
 * ## Почему ключ лежит в репозитории открыто
 *
 * Ключ IndexNow — не секрет. Он по устройству протокола публикуется на самом
 * сайте (`public/<ключ>.txt`), чтобы поисковик мог убедиться: тот, кто
 * присылает заявку, действительно распоряжается этим доменом. Прятать его в
 * переменную окружения означало бы держать одно и то же значение в двух местах
 * — в секрете CI и в файле на сайте — и однажды их рассинхронизировать.
 *
 * Худшее, что даёт чужому знание ключа, — возможность попросить переобход
 * наших же страниц: заявки на чужой хост протокол отклоняет (код 422). Это и
 * есть та модель угроз, ради которой ключ сделан публичным.
 *
 * ## Что именно отправляется
 *
 * Только то, что действительно изменилось. Список берётся не из головы, а из
 * разницы двух карт сайта — до выкатки и после (`changedUrls`). Карта сайта уже
 * знает и адреса, и даты правок, так что второго источника правды не заводим.
 *
 * Отправлять весь каталог на каждой выкатке нельзя — это ровно тот шум, из-за
 * которого поисковик перестаёт верить сигналу. По той же причине здесь есть
 * `MAX_URLS`: если разошлось больше, значит поменялось что-то общее (шаблон,
 * дата в шапке), и точечное уведомление тут не поможет.
 */

/** Ключ. Ему в паре обязан существовать `public/<ключ>.txt` — см. тест. */
export const INDEXNOW_KEY = "0d37d4472a0e66c9b1788658aee9a3db";

/** Имя файла-подтверждения. Только в корне сайта: ключ из подкаталога
 * авторизует лишь адреса этого подкаталога, а нам нужен весь домен. */
export function indexNowKeyFile(): string {
  return `${INDEXNOW_KEY}.txt`;
}

/**
 * Куда отправлять. Участники протокола пересылают заявки друг другу, но
 * Яндекс для нас основной, поэтому к нему обращаемся напрямую, а не через
 * общую точку входа.
 */
export const INDEXNOW_ENDPOINTS = [
  "https://yandex.com/indexnow",
  "https://api.indexnow.org/indexnow",
];

/**
 * Потолок на одну выкатку.
 *
 * Смысл числа — отличить «вышли новые страницы» от «поменялось что-то общее».
 * Ночной конвейер даёт одну-две страницы за запуск, ручная правка — десяток;
 * сорок с лишним изменившихся адресов при неполной сотне публичных страниц
 * означают не новый контент, а сдвиг даты у всего сразу. Уведомлять о таком
 * поштучно бессмысленно: это ровно тот шум, из-за которого сигнал перестают
 * учитывать.
 *
 * Тест держит потолок между этими двумя величинами, чтобы он не оказался
 * однажды ниже обычного пополнения или выше всего каталога — в обоих случаях
 * он перестаёт что-либо значить.
 */
export const MAX_URLS = 40;

export type SitemapEntry = { url: string; lastModified: string };

/**
 * Что изменилось между двумя картами сайта.
 *
 * Изменением считаются две вещи: адрес, которого раньше не было, и адрес с
 * новой датой правки. Исчезнувшие адреса не отправляем — IndexNow сообщает об
 * изменении содержимого, а про удаление поисковик всё равно узнаёт по 404.
 *
 * Порядок результата — как в новой карте: она отсортирована осмысленно
 * (разделами), и заявка читается так же, как выдача.
 */
export function changedUrls(before: SitemapEntry[], after: SitemapEntry[]): string[] {
  const known = new Map(before.map((entry) => [entry.url, entry.lastModified]));
  const changed: string[] = [];
  for (const entry of after) {
    const previous = known.get(entry.url);
    if (previous === undefined || previous !== entry.lastModified) changed.push(entry.url);
  }
  return changed;
}

/**
 * Тело заявки. `keyLocation` указывается явно, хотя ключ и лежит там, где
 * поисковик стал бы искать его по умолчанию: с явным адресом ошибка «файл не
 * найден» читается в ответе, а не гадается.
 */
export function indexNowPayload(host: string, urls: string[]): Record<string, unknown> {
  return {
    host,
    key: INDEXNOW_KEY,
    keyLocation: `https://${host}/${indexNowKeyFile()}`,
    urlList: urls,
  };
}
