/**
 * Правила напоминаний в боте. Модуль намеренно чистый: никакой базы, никакого
 * `new Date()` внутри — весь контекст приходит аргументом. Иначе поведение
 * «в 23:40 бот молчит» пришлось бы проверять, дожидаясь 23:40.
 *
 * Главное правило здесь не техническое: напоминание не должно вызывать вину.
 * Поэтому мы не пишем «вы пропустили» и никогда не отправляем больше одного
 * сообщения в день.
 *
 * Серии дней раньше не считались вовсе — именно из-за этого правила. Теперь
 * они есть (lib/streak.ts), но в напоминание попадают не числом, а репликой
 * Живело: «серия сбилась, но 43 дня с записями остались». Разница не
 * косметическая. Голое число в сообщении бота работает как счётчик долга; та
 * же цифра из уст персонажа, который пропустил вместе с человеком, — как
 * напоминание о сделанном. Правила, при которых бот вообще открывает рот,
 * при этом не меняются ни на йоту: повод нужен прежний.
 */

import { mascotReminderLine } from "./mascot.ts";
import { pluralRu, withPluralRu } from "./plural.ts";
import type { StreakResult } from "./streak.ts";

/** Час, раньше которого бот не пишет. Утро — не время для напоминаний о еде. */
export const QUIET_HOURS_END = 9;
/** Час, начиная с которого бот молчит до утра. */
export const QUIET_HOURS_START = 22;

export const DEFAULT_DIGEST_HOUR = 20;
export const MIN_DIGEST_HOUR = QUIET_HOURS_END;
export const MAX_DIGEST_HOUR = QUIET_HOURS_START - 1;

/** Час дайджеста от пользователя — недоверенное значение. */
export function normalizeDigestHour(raw: unknown): number {
  const n = Math.trunc(Number(raw));
  if (!Number.isFinite(n)) return DEFAULT_DIGEST_HOUR;
  return Math.min(MAX_DIGEST_HOUR, Math.max(MIN_DIGEST_HOUR, n));
}

export type ReminderKind =
  | "photo_digest"
  | "gentle_nudge"
  /** Седьмой день тишины — единственное сообщение с картинкой. */
  | "silence_week"
  /** Четырнадцатый: прощание, после него бот молчит совсем. */
  | "silence_farewell"
  | "weigh_nudge";

export type ReminderPlan = {
  kind: ReminderKind;
  text: string;
};

export type ReminderContext = {
  now: Date;
  /** Локальные день и час пользователя — из `localMoment`. */
  localDay: string;
  localHour: number;
  remindersEnabled: boolean;
  digestHour: number;
  /** До этого момента бот молчит — кнопка «Пауза на 3 дня». */
  snoozedUntil: Date | null;
  /** День, когда бот уже писал. Больше одного сообщения в день не бывает. */
  lastReminderOn: string | null;
  /**
   * Неразобранные фото за сегодняшний день. Именно за сегодня, а не за всё
   * время: иначе одно забытое фото превратило бы дайджест в ежедневный укор.
   * Старые снимки никуда не деваются — они просто ждут в инбоксе молча.
   */
  pendingPhotosToday: number;
  /** Сколько приёмов пищи записано сегодня — в любом из клиентов. */
  mealsToday: number;
  /**
   * Сколько дней подряд нет ни одной записи, считая сегодняшний.
   *
   * Отсчёт от последней записи, а у того, кто не записал ни разу, — от дня
   * регистрации: иначе «ни одной записи никогда» и «забросил вчера» пришлось
   * бы обслуживать одной веткой, а это два разных человека и два разных
   * разговора.
   */
  silentDays: number;
  /**
   * Серия дней. Необязательна: без неё напоминание остаётся ровно таким, каким
   * было, — строка Живело просто не добавляется.
   */
  streak?: StreakResult | null;
};

const PHOTO_FORMS = ["фото", "фото", "фото"] as const;
const DAY_FORMS = ["день", "дня", "дней"] as const;
const WAITING_FORMS = ["ждёт", "ждут", "ждут"] as const;

/**
 * Оба текста уходят с `parse_mode: HTML` — как и всё остальное, что говорит
 * бот (lib/bot/markup.ts). Значок здесь один и означает время суток:
 * напоминание приходит вечером, и по первому символу это видно раньше, чем
 * прочитана строка.
 */
export function photoDigestText(pendingPhotos: number): string {
  const photos = withPluralRu(pendingPhotos, PHOTO_FORMS);
  const wait = pluralRu(pendingPhotos, WAITING_FORMS);
  return `🌙 <b>Собрали ваш день.</b>\n\n${photos} ${wait} разбора. Пара уточнений — и день закрыт.`;
}

export const GENTLE_NUDGE_TEXT =
  "🌙 <b>Как прошёл день?</b>\n\n" +
  "Если было не до записей — просто пришлите фото, остальное соберём сами.";

/**
 * ## Лестница молчания: что писать тому, кто перестал записывать
 *
 * До неё пустой день получал одну и ту же строку — **каждый вечер, бесконечно**.
 * Человек, забросивший дневник в марте, в декабре всё ещё получал «как прошёл
 * день?». Это худший из возможных вариантов сразу по двум причинам: одинаковое
 * сообщение перестаёт читаться на третий раз, а неостановимое напоминание
 * заканчивается не возвращением, а кнопкой «заблокировать».
 *
 * Теперь сообщений четыре, они разные, и приходят на 1-й, 3-й, 7-й и 14-й день
 * тишины. В остальные вечера бот молчит. **После четырнадцатого — молчит
 * навсегда**, пока человек не вернётся сам.
 *
 * ### Почему именно так, а не «как в Duolingo»
 *
 * Приём оттуда взят сознательно: нарастающая, всё более личная просьба
 * работает — это видно по любому продукту с привычкой. Но у Duolingo пропуск
 * урока и пропуск записи о еде — разные вещи, и разница здесь принципиальна.
 *
 * Дневник питания читают люди, у которых с едой сложные отношения. «Вы
 * ничего не записали, я за вас переживаю» такой человек прочитает не как
 * «скучаю», а как «ты опять сорвался» — то есть получит укор за еду от
 * приложения, которое обещало его не судить. Поэтому три правила, из которых
 * выведены все четыре текста ниже:
 *
 * 1. **Живело скучает по человеку, а не оценивает его питание.** Ни слова о
 *    том, что человек ел, не ел, сорвался или набрал. Тоска — про отсутствие
 *    собеседника, а не про результат.
 * 2. **Право забросить признаётся вслух.** «Это ваше право, спорить не буду» —
 *    не реверанс, а точная формулировка отношений: дневник ведут для себя.
 * 3. **У серии есть конец, и он объявлен.** Последнее сообщение прямо говорит,
 *    что оно последнее. Это честно и, как ни странно, работает лучше:
 *    прощание читают, тридцатое напоминание — нет.
 */
export const SILENCE_STEPS = [1, 3, 7, 14] as const;

/** После этого дня бот молчит совсем — до возвращения человека. */
export const SILENCE_LAST_STEP = 14;

/**
 * Сообщение по числу дней тишины — или `null`, если сегодня не наш вечер.
 *
 * `totalDays` — сколько дней с записями накопилось за всё время. Ноль тоже
 * бывает: человек завёл дневник и не записал ни разу. Ему нельзя говорить
 * «ваши записи ждут» — записей нет, и обещание рассыпается на первой же фразе.
 */
export function silenceNudge(silentDays: number, totalDays: number): ReminderPlan | null {
  if (silentDays === 1) return { kind: "gentle_nudge", text: GENTLE_NUDGE_TEXT };

  if (silentDays === 3) {
    return {
      kind: "gentle_nudge",
      text:
        "🌙 <b>Третий вечер открываю ваш дневник — а он пустой.</b>\n\n" +
        "Ничего страшного не случилось: неделя бывает плотнее любых планов, и я это понимаю. " +
        "Но скучаю, если честно.\n\n" +
        "Вернуться проще, чем начать: пришлите фото ужина, остальное я соберу сам.",
    };
  }

  if (silentDays === 7) {
    // Единственное сообщение с картинкой — грустный Живело. Дальше по
    // лестнице картинки нет: повторённая, она превращается в приём.
    const saved = totalDays > 0
      ? `\n\nВаши ${withPluralRu(totalDays, DAY_FORMS)} с записями никуда не делись — они на месте и `
        + "ждут продолжения. Никакого «начать сначала» не будет."
      : "";
    return {
      kind: "silence_week",
      text:
        "🌙 <b>Неделя тишины. Сижу, жду.</b>\n\n" +
        "Забросить дневник — ваше право, и спорить я не стану: это ваша жизнь и ваша еда. " +
        "Скажу только честно — мне жаль. Не потому, что вы кому-то что-то должны, а потому " +
        "что вы начинали не просто так, и я это помню."
        + saved
        + "\n\nПросто пришлите фото — и день снова записан.",
    };
  }

  if (silentDays === SILENCE_LAST_STEP) {
    return {
      kind: "silence_farewell",
      text:
        "🌙 <b>Две недели. Это последнее письмо — дальше я замолкаю.</b>\n\n" +
        "Не обижаюсь и не исчезаю: дневник, все записи и замеры веса останутся на месте, " +
        "сколько бы ни прошло времени. Захотите вернуться — просто пришлите фото еды, и я " +
        "снова рядом. Включать и настраивать ничего не придётся.\n\n" +
        "Спасибо, что попробовали. Правда.",
    };
  }

  // Все прочие вечера — тишина. Это не пропуск в правилах, а само правило.
  return null;
}

/**
 * Решает, что отправить пользователю прямо сейчас, и отправлять ли вообще.
 * `null` означает «сегодня молчим» — это самый частый и совершенно нормальный
 * исход.
 */
export function planReminder(ctx: ReminderContext): ReminderPlan | null {
  if (!ctx.remindersEnabled) return null;
  if (ctx.snoozedUntil && ctx.now < ctx.snoozedUntil) return null;
  if (ctx.lastReminderOn === ctx.localDay) return null;
  if (ctx.localHour < QUIET_HOURS_END || ctx.localHour >= QUIET_HOURS_START) return null;
  if (ctx.localHour < normalizeDigestHour(ctx.digestHour)) return null;

  // Неразобранные фото — единственный повод, где у нас есть что показать.
  if (ctx.pendingPhotosToday > 0) {
    return { kind: "photo_digest", text: withMascot(photoDigestText(ctx.pendingPhotosToday), ctx.streak) };
  }

  // Пустой день. Что именно сказать — решает лестница молчания: на первый
  // вечер это лёгкое «как прошёл день», на четырнадцатый — прощание, а между
  // ними бот чаще всего молчит вовсе.
  if (ctx.mealsToday === 0) {
    const plan = silenceNudge(ctx.silentDays, ctx.streak?.totalDays ?? 0);
    if (!plan) return null;
    // Реплику про серию дописываем только к лёгкому первому шагу. Ниже по
    // лестнице она мешает: у сообщения о неделе тишины уже есть своя фраза
    // про сохранённые дни, и вторая рядом читается как торг.
    return plan.kind === "gentle_nudge" ? { ...plan, text: withMascot(plan.text, ctx.streak) } : plan;
  }

  // День записан, фото разобраны — писать не о чем.
  return null;
}

/**
 * Дописывает реплику Живело, если ему есть что сказать. Повод для самого
 * сообщения уже найден выше — персонаж не добавляет поводов, он добавляет
 * контекст к тому, что и так отправляется.
 */
function withMascot(text: string, streak: StreakResult | null | undefined): string {
  const line = streak ? mascotReminderLine(streak) : null;
  return line ? `${text}\n\n${line}` : text;
}

/**
 * ## Напоминание взвеситься
 *
 * Отдельно от вечернего дайджеста, и не только по времени суток.
 *
 * Во-первых, повод другой. Дайджест говорит о еде и приходит вечером, когда
 * день уже прожит. Взвешиваться имеет смысл утром натощак — это единственный
 * замер, который сравним со вчерашним.
 *
 * Во-вторых, согласие другое. `/stop` выключает разговор про еду, и человек,
 * нажавший его, не соглашался получать вместо этого «встаньте на весы».
 * Поэтому переключатель свой (`bot_preferences.weigh_reminders_enabled`), и
 * выключается он независимо.
 *
 * В-третьих, частота другая. Ежедневное напоминание о весе — это ежедневный
 * вопрос «ну что, похудел?», то есть ровно тот тон, которого мы избегаем во
 * всём остальном продукте. Раз в неделю, и только если замеров правда нет.
 */
export const WEIGH_REMINDER_HOUR = 9;
/** Не чаще раза в неделю. */
export const WEIGH_REMINDER_EVERY_DAYS = 7;
/**
 * Сколько дней без замера считаем поводом написать. Четыре, а не семь:
 * взвешивающемуся по субботам не за что напоминать, а тот, кто пропал на
 * четыре дня, скорее всего просто забыл.
 */
export const WEIGH_SILENCE_DAYS = 4;

export const WEIGH_REMINDER_TEXT =
  "⚖️ <b>Доброе утро.</b>\n\n" +
  "Если сегодня встанете на весы — пришлите число прямо сюда, одним сообщением: «72,4». " +
  "Больше ничего делать не нужно.\n\n" +
  "По этим замерам сервис уточняет вашу норму — формула про вас не знает, а тренд знает. " +
  "Не взвешиваться тоже нормально: дневник работает и без единой цифры веса.";

export type WeighReminderContext = {
  localDay: string;
  localHour: number;
  enabled: boolean;
  /** Дата последнего напоминания о весе — не чаще раза в неделю. */
  lastWeighReminderOn: string | null;
  /** Дата последнего замера веса. null — замеров не было вовсе. */
  lastWeightOn: string | null;
  /** Есть ли у человека профиль: без него норму всё равно не посчитать. */
  hasProfile: boolean;
};

/** Разница в днях между двумя датами `ГГГГ-ММ-ДД`. */
function daysBetween(from: string, to: string): number {
  const ms = Date.parse(`${to}T00:00:00Z`) - Date.parse(`${from}T00:00:00Z`);
  return Math.round(ms / 86_400_000);
}

/**
 * Писать ли сегодня про весы. `null` — «нет», и это самый частый исход.
 *
 * Функция чистая, как и planReminder: «в понедельник в 9 утра человеку,
 * который взвешивался в субботу, бот молчит» — это утверждение, которое
 * должно проверяться таблицей, а не ожиданием понедельника.
 */
export function planWeighReminder(ctx: WeighReminderContext): ReminderPlan | null {
  if (!ctx.enabled) return null;
  if (!ctx.hasProfile) return null;
  // Утро, и узкое: в час дня «доброе утро» звучит как сбой рассылки.
  if (ctx.localHour < WEIGH_REMINDER_HOUR || ctx.localHour >= WEIGH_REMINDER_HOUR + 3) return null;
  if (ctx.lastWeighReminderOn && daysBetween(ctx.lastWeighReminderOn, ctx.localDay) < WEIGH_REMINDER_EVERY_DAYS) {
    return null;
  }
  // Человек взвешивается сам — напоминать не о чем. Это главное условие:
  // напоминание существует ради пустого графика, а не ради ритуала.
  if (ctx.lastWeightOn && daysBetween(ctx.lastWeightOn, ctx.localDay) < WEIGH_SILENCE_DAYS) return null;

  return { kind: "weigh_nudge", text: WEIGH_REMINDER_TEXT };
}

/**
 * «Пауза» вместо привычного «напомнить позже». Отложить на два часа
 * бессмысленно: до конца дня бот всё равно больше не пишет, а следующий заход
 * будет только завтра вечером. Поэтому кнопка честно называется паузой и
 * действительно выключает напоминания на несколько дней.
 */
export const SNOOZE_DAYS = 3;

export function snoozeUntil(now: Date): Date {
  return new Date(now.getTime() + SNOOZE_DAYS * 24 * 60 * 60 * 1000);
}

/**
 * Предупреждение о конце пробного месяца.
 *
 * ## Зачем оно есть
 *
 * До него человек узнавал о конце пробного месяца **в момент отказа**: навёл
 * камеру на обед, нажал «Разобрать» и получил «пробный месяц закончился».
 * Тридцать дней сервис молчал об этом, а потом поставил перед фактом ровно
 * тогда, когда человек занят чем-то другим.
 *
 * Это невежливо и, отдельно, невыгодно: решение платить принимают спокойно, а
 * не с телефоном над остывающей тарелкой. Предупреждение за три дня даёт
 * время решить — и оказывается лучшей точкой разговора о деньгах, какая у нас
 * вообще есть.
 *
 * ## Почему три дня, а не семь и не один
 *
 * Семь — это ещё четверть месяца впереди, и письмо читается как реклама
 * посреди работающего сервиса. Один — уже не выбор, а уведомление. Три дня
 * — срок, за который можно и решить, и позвать друга: награда за приглашение
 * приходит на седьмой день его записей, так что позвать лучше заранее, и об
 * этом в тексте сказано прямо.
 *
 * ## Почему выключенные напоминания уважаются
 *
 * Человек, нажавший /stop, попросил ему не писать. Считать, что запрет
 * распространяется на всё, кроме наших сообщений про деньги, — ровно тот
 * приём, за который мессенджеры и не любят. Он всё равно увидит срок в
 * настройках и в Mini App: там дни до конца доступа показаны всегда.
 */
export const TRIAL_WARNING_DAYS_BEFORE = 3;

/** Днём, а не утром: сообщение про решение, а не про действие сегодня. */
export const TRIAL_WARNING_HOUR = 12;

export type TrialWarningContext = {
  localHour: number;
  enabled: boolean;
  /** Сколько дней доступа осталось. 0 и меньше — уже кончился, поздно. */
  daysLeft: number;
  /** Открыт ли доступ оплатой. Заплатившему предупреждать не о чем. */
  paid: boolean;
  /** Уже предупреждали? Сообщение одноразовое. */
  warned: boolean;
  /** Дата окончания словами — «5 сентября». Форматирует вызывающий. */
  until: string;
};

export function trialWarningText(daysLeft: number, until: string): string {
  const days = daysLeft === 1 ? "завтра" : `через ${daysLeft} дн.`;
  return (
    "🗓 <b>Пробный месяц заканчивается " + days + "</b> — " + until + ".\n\n" +
    "После этого закроется только обращение к модели: разбор по фото, по описанию и голосом. " +
    "Дневник, история, план, вес, обзоры и выгрузка данных останутся на месте, еду можно будет " +
    "записывать руками без ограничений.\n\n" +
    "Открыть разбор дальше можно двумя способами: оплатой или приглашением — за каждого " +
    "пришедшего друга месяц получаете и вы, и он. Награда приходит на седьмой день его " +
    "записей, так что звать лучше сейчас: /invite."
  );
}

/**
 * Писать ли сегодня про конец пробного месяца. `null` — «нет».
 *
 * Чистая, как и соседи: «за три дня до конца, в полдень, тому, кто не платил
 * и кому ещё не писали» — утверждение, которое проверяется таблицей, а не
 * ожиданием нужного дня.
 */
export function planTrialWarning(ctx: TrialWarningContext): { text: string } | null {
  if (!ctx.enabled) return null;
  if (ctx.paid) return null;
  if (ctx.warned) return null;
  // Полдень и три часа вокруг: попасть в окно должен любой заход планировщика,
  // но «пробный месяц кончается» в четыре утра выглядит сбоем рассылки.
  if (ctx.localHour < TRIAL_WARNING_HOUR || ctx.localHour >= TRIAL_WARNING_HOUR + 3) return null;
  // Строго больше нуля: у того, у кого доступ уже закрылся, предупреждать
  // нечего — он это и так увидел отказом.
  if (ctx.daysLeft <= 0 || ctx.daysLeft > TRIAL_WARNING_DAYS_BEFORE) return null;
  return { text: trialWarningText(ctx.daysLeft, ctx.until) };
}
