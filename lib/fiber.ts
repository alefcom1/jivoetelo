/**
 * Норма клетчатки и то, чем её закрыть.
 *
 * ## Норма
 *
 * Отечественные методические рекомендации МР 2.3.1.0253-21 дают взрослому
 * 20 г пищевых волокон в сутки как физиологическую потребность. Мировые
 * рекомендации выше: EFSA считает адекватным потреблением 25 г, ВОЗ в
 * руководстве 2023 года — не менее 25 г для взрослых. Мы берём 25 г как
 * ориентир по умолчанию (он же стоит целью в дневнике) и показываем
 * диапазон 20–30, потому что единственного «правильного» числа тут нет.
 *
 * Поправка на калорийность рациона осмысленнее плоского числа: тому, кто ест
 * 3000 ккал, 25 г мало, а тому, кто ест 1400, — уже прилично. Классическое
 * правило — 14 г на 1000 ккал; его и используем, зажимая в разумные границы.
 *
 * ## Чем закрыть
 *
 * Здесь наше преимущество: у нас есть справочник на три сотни позиций с
 * клетчаткой в каждой. Вместо общих слов «ешьте овощи» страница показывает,
 * сколько конкретных граммов конкретного продукта нужно, — и сразу видно,
 * что 25 г клетчатки не набрать одними огурцами.
 */

import { FOOD_REFERENCE, type ReferenceFood } from "./food-reference.ts";

/** Ориентир по умолчанию, г. Тот же, что цель дневника (lib/targets.ts). */
export const FIBER_DEFAULT = 25;

/** Граммы клетчатки на 1000 ккал рациона. */
const PER_1000_KCAL = 14;

export type FiberTarget = {
  /** Ориентир, г. */
  target: number;
  /** Разумный диапазон, г. */
  range: { from: number; to: number };
};

export function fiberTarget(kcalPerDay?: number): FiberTarget {
  if (!kcalPerDay || !(kcalPerDay > 0)) {
    return { target: FIBER_DEFAULT, range: { from: 20, to: 30 } };
  }
  const raw = (kcalPerDay / 1000) * PER_1000_KCAL;
  const target = Math.round(clamp(raw, 18, 40));
  return {
    target,
    range: { from: Math.round(clamp(raw * 0.8, 15, 35)), to: Math.round(clamp(raw * 1.2, 22, 50)) },
  };
}

function clamp(value: number, min: number, max: number): number {
  return Math.min(max, Math.max(min, value));
}

export type FiberSource = ReferenceFood & {
  /** Клетчатки в типичной порции, г. */
  perPortion: number;
  /** Сколько таких порций закрыло бы всю норму. */
  portionsForTarget: number;
};

/**
 * Лучшие источники клетчатки из справочника — по количеству в типичной
 * порции, а не на 100 г. На 100 г побеждают отруби, которых никто не ест
 * стаканами; в порциях список становится применимым.
 */
export function topFiberSources(target = FIBER_DEFAULT, limit = 12): FiberSource[] {
  return FOOD_REFERENCE
    .filter((food) => food.fiber > 0)
    .map((food) => {
      const perPortion = Math.round(((food.fiber * food.portionG) / 100) * 10) / 10;
      return {
        ...food,
        perPortion,
        portionsForTarget: perPortion > 0 ? Math.round((target / perPortion) * 10) / 10 : Infinity,
      };
    })
    .filter((food) => food.perPortion >= 1)
    .sort((a, b) => b.perPortion - a.perPortion)
    .slice(0, limit);
}

/** Сколько граммов продукта нужно, чтобы получить столько-то клетчатки. */
export function gramsForFiber(food: ReferenceFood, fiberGrams: number): number | null {
  if (!(food.fiber > 0)) return null;
  return Math.round((fiberGrams / food.fiber) * 100);
}

