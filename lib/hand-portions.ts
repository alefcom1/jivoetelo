/** Сколько граммов даёт мера с учётом пола и количества. */
export function handGrams(measure: HandMeasure, sex: "female" | "male", count = 1): number {
  const per = sex === "female" ? measure.gramsFemale : measure.gramsMale;
  return Math.round(per * count);
}

/** Сколько мер в приёме пищи по методу. */
export function handPerMeal(measure: HandMeasure, sex: "female" | "male"): number {
  return sex === "female" ? measure.perMealFemale : measure.perMealMale;
}
