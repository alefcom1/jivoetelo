/**
 * Порция по ладони: мера, которая всегда с собой.
 *
 * ## Откуда метод
 *
 * Приём известен по работе Precision Nutrition: ладонь — белок, кулак —
 * овощи, сложенная горсть — углеводы, большой палец — жиры. Его ценность не
 * в точности, а в двух свойствах: рука масштабируется вместе с человеком
 * (у крупного мужчины ладонь больше, и порция больше — это и нужно) и она
 * всегда при себе, в отличие от весов.
 *
 * ## Что мы делаем иначе
 *
 * Обычно метод подают таблицей «мужчинам — 2 ладони, женщинам — 1». Мы
 * пересчитываем его в граммы и калории: у нас есть справочник продуктов, и
 * умалчивать о том, во что мера превращается на тарелке, незачем. Заодно
 * видно, где метод врёт: для творога ладонь — совсем не то же, что для
 * куриной грудки, и это честнее показать числом.
 *
 * Размеры мер — типовые для взрослого; они и заявлены как «примерно».
 */

export type HandMeasure = {
  key: "palm" | "fist" | "cupped" | "thumb";
  /** Название меры. */
  name: string;
  /** Что ей меряют. */
  measures: string;
  /** Типичный вес меры, г — женская и мужская рука. */
  gramsFemale: number;
  gramsMale: number;
  /** Сколько таких мер в одном приёме пищи по методу. */
  perMealFemale: number;
  perMealMale: number;
  /** Примеры продуктов из нашего справочника. */
  examples: string[];
  /** Что метод не учитывает именно у этой меры. */
  caveat: string;
};

