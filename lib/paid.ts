/**
 * Доступ к сервису: пробный месяц, оплата и срок.
 *
 * ## Одно поле вместо трёх состояний
 *
 * Оплаченный доступ хранится сроком — `users.access_until`, — а не флагом и
 * не строкой тарифа. Причина в том, что источников у него несколько (оплата,
 * ваучер, награда за приглашение), а вопрос к ним всегда один: открыт ли
 * доступ прямо сейчас. Флаг «premium: да» пришлось бы снимать по расписанию,
 * и первый же упавший cron оставил бы людям доступ, за который никто не
 * платил, — или, что хуже, снял бы его у тех, кто заплатил.
 *
 * Поэтому `plan` вычисляется при каждом чтении пользователя, а не хранится
 * согласованным с ним. Рассогласовать нечего.
 *
 * ## Пробный месяц не хранится вовсе
 *
 * Первый месяц открыт всем и считается от `users.created_at`, а не выдаётся
 * записью в `access_until` при регистрации. Это выбор, и вот почему такой:
 *
 *  - **нечего забыть.** Пользователи заводятся в нескольких местах — почтой,
 *    из Telegram, по приглашению специалиста. Выдача срока при регистрации
 *    означала бы, что каждый новый путь обязан про неё помнить, и первый
 *    забывший отдал бы человека без пробного периода вовсе;
 *  - **нечего мигрировать.** У всех уже заведённых `created_at` есть, значит
 *    правило применяется к ним ровно так же, как к новым, в момент выкатки;
 *  - **`access_until` остаётся честным.** В нём лежит только то, за что
 *    заплатили или что подарили. Смешать туда пробный период значило бы
 *    потерять ответ на вопрос «этот человек платил хоть раз».
 *
 * ## Что закрывается, когда доступ кончился
 *
 * Только обращения к AI — распознавание по фото, по описанию, по голосу,
 * чтение весов и подсказки (PLAN_LIMITS в lib/quota-policy.ts). Сам дневник,
 * история, план, вес, обзоры, каталог, расчёты и выгрузка своих данных
 * открыты всегда и никем не закрываются. Записи человека принадлежат ему;
 * сервис берёт деньги за работу модели, а не за доступ к чужому прошлому.
 */

import type { Plan } from "./quota-policy.ts";

/**
 * Пробный период, дни. Ровно месяц — столько же, сколько даёт приглашение и
 * сколько стоит месячный тариф: три разных числа человек держать в голове не
 * станет, а одно и то же «месяц» он запомнит с первого раза.
 */
export const TRIAL_DAYS = 30;

/** Когда кончается пробный месяц у человека, заведённого в `createdAt`. */
export function trialEndsAt(createdAt: Date): Date {
  return new Date(createdAt.getTime() + TRIAL_DAYS * 86_400_000);
}

/** Идёт ли пробный месяц прямо сейчас. */
export function inTrial(createdAt: Date, now: Date): boolean {
  return now.getTime() < trialEndsAt(createdAt).getTime();
}

export type TariffKey = "month" | "year";

export type Tariff = {
  key: TariffKey;
  label: string;
  /** На сколько дней продлевает доступ. */
  days: number;
  /** Цена в рублях, целыми. */
  priceRub: number;
};

/**
 * Тарифы. Год дешевле десяти месяцев — это не скидка ради скидки: годовая
 * оплата снимает ежемесячное решение «продлевать ли», а оно у сервиса про
 * привычку стоит дороже разницы в деньгах.
 */
export const TARIFFS: readonly Tariff[] = [
  { key: "month", label: "Месяц", days: 30, priceRub: 190 },
  { key: "year", label: "Год", days: 365, priceRub: 1900 },
];

export function tariffByKey(key: string): Tariff | null {
  return TARIFFS.find((tariff) => tariff.key === key) ?? null;
}

/**
 * Открыт ли **оплаченный** доступ прямо сейчас — без учёта пробного месяца.
 *
 * Отдельно от `hasAccess` намеренно: на вопрос «этот человек платил» и на
 * вопрос «можно ли ему сейчас разобрать фотографию» ответы разные, и
 * склеивать их нельзя. Первый нужен, чтобы не звать к оплате того, кто уже
 * заплатил; второй — чтобы решить, пускать ли к модели.
 */
export function hasPaidAccess(accessUntil: Date | null, now: Date): boolean {
  return accessUntil !== null && accessUntil.getTime() > now.getTime();
}

/** Открыт ли доступ вообще — оплатой или пробным месяцем. */
export function hasAccess(accessUntil: Date | null, createdAt: Date, now: Date): boolean {
  return hasPaidAccess(accessUntil, now) || inTrial(createdAt, now);
}

/** Тариф, действующий сейчас. Вычисляется, а не хранится. */
export function effectivePlan(accessUntil: Date | null, createdAt: Date, now: Date): Plan {
  return hasAccess(accessUntil, createdAt, now) ? "premium" : "free";
}

/**
 * До какого момента доступ открыт с учётом обеих причин. `null` — закрыт.
 *
 * Нужно и экрану («доступ до 5 сентября»), и продлению: без этого начисление
 * во время пробного месяца частично пропадало бы, см. `extendAccess`.
 */
export function accessEndsAt(accessUntil: Date | null, createdAt: Date, now: Date): Date | null {
  const trial = trialEndsAt(createdAt);
  const paid = accessUntil;
  const latest = paid && paid.getTime() > trial.getTime() ? paid : trial;
  return latest.getTime() > now.getTime() ? latest : null;
}

/**
 * Продлить доступ на `days` дней.
 *
 * Отсчёт идёт от самого позднего из трёх: «сейчас», оплаченный срок и конец
 * пробного месяца. Первые два были здесь и раньше — у того, кто продлевает
 * заранее, остаток не должен сгорать; обратное поведение («продлил за неделю
 * до конца и потерял неделю») читается как обман, и человек начинает тянуть
 * до последнего дня.
 *
 * Пробный месяц добавлен третьим, и это не мелочь. Награда за приглашение
 * начисляется на седьмой день записей, то есть заведомо внутри пробного
 * месяца. Без этого условия месяц отсчитывался бы от «сейчас» — то есть с
 * седьмого дня, — и двадцать три дня пробного периода человек терял бы молча:
 * вместо шестидесяти дней получалось бы тридцать семь. Ровно тот случай,
 * когда награда за приведённого друга уменьшает доступ вместо того, чтобы
 * его увеличить.
 */
export function extendAccess(accessUntil: Date | null, createdAt: Date, days: number, now: Date): Date {
  const candidates = [now.getTime(), trialEndsAt(createdAt).getTime()];
  if (accessUntil) candidates.push(accessUntil.getTime());
  return new Date(Math.max(...candidates) + days * 86_400_000);
}

/**
 * Сколько дней доступа осталось, округляя вверх.
 *
 * Вверх, потому что «осталось 0 дней» при доступе до вечера — неправда.
 * Ноль здесь означает, что доступа уже нет.
 */
export function daysLeft(accessUntil: Date | null, createdAt: Date, now: Date): number {
  const until = accessEndsAt(accessUntil, createdAt, now);
  if (!until) return 0;
  return Math.ceil((until.getTime() - now.getTime()) / 86_400_000);
}

/** Цена строкой: «190 ₽». Неразрывный пробел — число и знак не разрываются. */
export function priceRub(value: number): string {
  return `${value} ₽`;
}
