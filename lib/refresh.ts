/**
 * Нужно ли перезагружать «Сегодня».
 *
 * ## Откуда взялось
 *
 * Экран Mini App грузился ровно один раз — при монтировании. Переключение
 * вкладок монтирование не повторяет, а Telegram при сворачивании webview не
 * убивает: он остаётся жив со всем состоянием React. Для приложения
 * «свернул и открыл заново» неотличимо от «ничего не произошло», и цифры
 * оставались вчерашними, пока приложение не закроешь совсем.
 *
 * Устареть за это время может многое, и не только от собственных действий:
 * снимок, отправленный боту прямо в переписке, попадает в инбокс мимо
 * приложения, а счётчик инбокса показан на «Сегодня».
 *
 * ## Почему три исхода, а не «да/нет»
 *
 * Первая загрузка и фоновое обновление ведут себя по-разному при ошибке.
 * Первой падать можно и нужно — показывать нечего, человек увидит экран с
 * кнопкой «повторить». Фоновой падать нельзя: экран уже открыт, и стирать
 * цифры дня из-за секундного обрыва связи — значит наказывать человека за
 * то, чего он не делал и не поймёт.
 *
 * Отсюда `full` (со всеми состояниями ошибок), `silent` (молча, неудача
 * ничего не меняет) и `skip`.
 */

/** Сколько ждать между фоновыми обновлениями. */
export const REFRESH_GAP_MS = 10_000;

export type RefreshDecision = "full" | "silent" | "skip";

export function shouldRefresh(input: {
  /** День, за который показаны данные (`YYYY-MM-DD`), или null, если данных нет. */
  dataDay: string | null;
  /** Сегодняшний день по часам устройства. */
  today: string;
  /** Когда последний раз успешно загрузились, мс. */
  lastLoadedAt: number;
  now: number;
  gapMs?: number;
}): RefreshDecision {
  const { dataDay, today, lastLoadedAt, now, gapMs = REFRESH_GAP_MS } = input;

  // Показывать нечего — грузим обычным порядком.
  if (!dataDay) return "full";

  // День сменился, пока приложение висело открытым. Порог здесь не
  // применяется ни при каких условиях: вчерашние итоги под заголовком
  // «сегодня» — это неверные данные, а не устаревшие на десять секунд.
  if (dataDay !== today) return "silent";

  // Между вкладками щёлкают быстро; без порога каждый щелчок бил бы по сети.
  if (now - lastLoadedAt < gapMs) return "skip";

  return "silent";
}
