import sharp from "sharp";

/**
 * Подготовка снимка перед отправкой в модель — два разных ограничения.
 *
 * ## Пиксели: сколько стоит разбор
 *
 * Claude смотрит на картинку патчами 28×28, и снимок стоит
 * `⌈ширина/28⌉ × ⌈высота/28⌉` токенов зрения. Телефонный кадр 3024×4032
 * упирается в потолок модели и обходится в тысячи токенов, хотя для
 * узнавания еды такое разрешение бессмысленно: модели важны цвет, форма и
 * относительный размер порций, а не резкость на уровне зерна риса.
 * MAX_DIMENSION_PX даёт 1296 токенов — вчетверо дешевле потолка и заметно
 * ниже той границы (1568 px), за которой Anthropic сама уменьшает картинку.
 *
 * ## Байты: доедет ли запрос вообще
 *
 * До этой правки ограничение было только по пикселям, и это оказалось
 * половиной дела. Снимок, уже уложившийся в 1024 px, мог весить сколько
 * угодно: пёстрая тарелка в JPEG качества 82 легко даёт 300–400 КБ, а
 * скриншот в PNG — мегабайты, и он вообще не пересжимался, потому что «по
 * геометрии всё в порядке». Токенов такое тело не добавляет — зато его
 * нужно физически протолкнуть через прокси, и именно на этом разбор фото
 * вставал: текст проходил за секунду, крошечная картинка за три, настоящий
 * снимок висел минутами.
 *
 * Поэтому теперь есть TARGET_BYTES: качество понижается ступенями, пока
 * тело не уложится в бюджет. Документация Anthropic прямо говорит, что
 * сжатие в JPEG или WebP снижает задержку за счёт размера запроса — но
 * предупреждает про артефакты, поэтому ступени кончаются на 42, а не на 10.
 *
 * ## Почему WebP
 *
 * Тот же кадр в WebP весит на четверть-треть меньше JPEG при неотличимом
 * на глаз качестве, а модель принимает его наравне. Токенов это не
 * экономит (их считают по пикселям), но байты — единственное, чем мы можем
 * управлять на пути до прокси.
 *
 * Сжимаем только копию, которая уходит в AI. В хранилище (lib/storage.ts)
 * остаётся оригинал — это то, что показывается пользователю на странице
 * приёма пищи, и его качество не должно зависеть от того, как мы экономим
 * на распознавании.
 */
const MAX_DIMENSION_PX = 1024;

/**
 * Бюджет тела запроса. Выбран не из красоты числа: 1024 px еды в WebP
 * качества 80 весит 80–150 КБ, так что 180 КБ — это «обычный снимок
 * проходит первой же ступенью, а выбросы поджимаются».
 *
 * Считаем в исходных байтах, хотя в запрос уходит base64, который на треть
 * длиннее. Пересчитывать не стали: множитель постоянный, и бюджет проще
 * держать в тех единицах, в которых его видно в логах и в хранилище.
 */
const TARGET_BYTES = 180 * 1024;

/**
 * Ступени качества. Первая — рабочая для почти всех снимков; дальше идём
 * только если кадр настолько пёстрый, что не влез. Ниже 42 не опускаемся:
 * артефакты начинают съедать то самое, ради чего снимок и отправляется, —
 * границы между продуктами на тарелке.
 */
const QUALITY_STEPS = [80, 68, 55, 42];

export type CompressedPhoto = { data: Buffer; mediaType: "image/webp" };

/**
 * Готовит копию снимка для модели: уменьшает до `MAX_DIMENSION_PX` по
 * длинной стороне (пропорции сохраняются, апскейла нет) и перекодирует в
 * WebP, понижая качество, пока тело не уложится в `TARGET_BYTES`.
 *
 * `rotate()` без аргументов — авто-поворот по EXIF: у телефонных снимков
 * ориентация часто лежит в EXIF-теге, а не в самих пикселях, и без этого
 * шага модель получит кадр, повёрнутый на 90°.
 *
 * Возвращает `null`, когда трогать нечего или не получилось:
 *  - снимок уже мал по обоим меркам — и по пикселям, и по весу. Тогда
 *    перекодирование ничего не экономит, а качество (прозрачность PNG,
 *    кадр GIF) может испортить зря;
 *  - sharp упал на обработке (повреждённый файл, экзотический кодек,
 *    нехватка памяти). Сжатие — оптимизация, а не условие разбора,
 *    поэтому ошибку не бросаем: вызывающий код отправит оригинал.
 */
export async function compressPhotoForAi(
  data: Buffer,
  /**
   * Потолок веса. Умолчание — жёсткий бюджет для отправки телом запроса.
   *
   * Маршрут, отдающий снимок по ссылке, передаёт сюда Infinity, и это не
   * лень, а разные условия: по ссылке картинка едет обычным HTTP внутрь, где
   * порога в 32 КБ нет вовсе. Лестница качества там гоняла бы кодек до
   * четырёх раз ради ограничения, которого на этом пути не существует, — и
   * отдавала бы картинку хуже, чем можно.
   */
  targetBytes: number = TARGET_BYTES,
  /**
   * Потолок по длинной стороне. Умолчание рассчитано на еду, где важны цвет и
   * форма, а не резкость.
   *
   * Чтение весов передаёт сюда больше (lib/ai/scale.ts): там задача обратная —
   * узнать цифру высотой в несколько десятков точек, и каждый снятый пиксель
   * идёт прямо в число, которое попадёт в историю веса.
   */
  maxDimension: number = MAX_DIMENSION_PX,
): Promise<CompressedPhoto | null> {
  try {
    const metadata = await sharp(data, { failOn: "none" }).metadata();
    const longSide = Math.max(metadata.width ?? 0, metadata.height ?? 0);
    const fitsByPixels = longSide > 0 && longSide <= maxDimension;
    const fitsByBytes = data.length <= targetBytes;
    if (fitsByPixels && fitsByBytes) {
      return null;
    }

    // Геометрию считаем один раз: менять между ступенями будем только
    // качество. Уменьшать картинку дальше ради веса — плохой размен:
    // потеря пикселей бьёт по узнаванию сильнее, чем потеря качества.
    const resized = sharp(data, { failOn: "none" })
      .rotate()
      .resize({
        width: maxDimension,
        height: maxDimension,
        fit: "inside",
        withoutEnlargement: true,
      });

    let best: Buffer | null = null;
    for (const quality of QUALITY_STEPS) {
      // clone() обязателен: sharp-конвейер одноразовый, повторный toBuffer()
      // на том же объекте вернёт результат первой ступени.
      const candidate = await resized.clone().webp({ quality }).toBuffer();
      best = candidate;
      if (candidate.length <= targetBytes) break;
    }
    if (!best) return null;

    if (fitsByPixels && best.length >= data.length) {
      // Пересжатие вышло не легче оригинала. Так бывает на кадрах, которым
      // кодеку нечего сжимать, — зерно, шум, мелкая текстура во весь кадр.
      // Геометрия и так в пределах, значит токенов мы не экономим, а байтов
      // прибавляем: отправлять такое вместо оригинала незачем.
      return null;
    }

    if (best.length > targetBytes) {
      // Досюда доходят редкие кадры — очень пёстрые или очень широкие.
      // Отправляем как есть: лучше тяжёлый запрос, чем каша вместо еды.
      console.warn(`[ai] снимок не ужался в бюджет: ${Math.round(best.length / 1024)} КБ`);
    }
    return { data: best, mediaType: "image/webp" };
  } catch (error) {
    console.error("photo compression failed, sending original to AI", error);
    return null;
  }
}
