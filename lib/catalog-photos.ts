// Фотографии продуктов от людей — то, чего нет ни у одного каталога в рунете.
//
// Конкуренты либо не ставят фото вовсе, либо ставят сток: одна и та же
// студийная тарелка гречки на пяти сайтах. Настоящий снимок с домашней кухни
// отличается от стока сразу и решает ровно ту задачу, ради которой человек
// пришёл, — показать, как выглядит порция, о которой идёт речь.
//
// Скопировать это нельзя: снимки берутся из дневников, а дневников с разбором
// у конкурентов нет.
//
// Цена — три условия, без которых снимок не показывается никогда. Они
// проверяются здесь, в одном месте, а не рассыпаны по страницам:
//
// 1. **Проверен человеком.** На снимке еды регулярно оказывается то, чего
//    автор не имел в виду публиковать: лица за столом, интерьер кухни,
//    документы рядом с тарелкой, отражения в посуде. Автоматически это не
//    ловится, и «потом посмотрим» здесь не работает — опубликованное уже
//    опубликовано.
// 2. **Согласие на публикацию не отозвано.** Это отдельное согласие, не то,
//    по которому мы разбираем еду: там снимок обрабатывается для самого
//    человека и остаётся в его дневнике.
// 3. **Аккаунт жив.** Обеспечивается каскадом в схеме: удаление уносит и
//    вклад в каталог.
//
// Здесь — только то, что не ходит в базу: типы и подпись к снимку. Запросы
// живут в `catalog-photos-store.ts`, и разделение не косметическое: подпись
// попадает в `alt`, `title` и разметку, то есть её надо покрывать тестами, а
// модуль с `next/cache` и алиасом `@/db` в юнит-тест не импортируется.

export type CatalogPhoto = {
  id: number;
  photoKey: string;
  /** Подпись: идёт в `alt`, в `title`, в видимую подпись и в `ImageObject.caption`. */
  caption: string;
  createdAt: Date;
};

export const PHOTO_STATUSES = ["pending", "approved", "rejected"] as const;
export type PhotoStatus = (typeof PHOTO_STATUSES)[number];

/**
 * Подпись к снимку.
 *
 * Собирается из названия продукта и веса порции, а не из фантазии: подпись
 * видят и человек, и поисковик, и она обязана описывать именно то, что на
 * снимке. «Творог 5%, порция 150 г» — проверяемое утверждение; «вкусный
 * полезный завтрак» — набор слов, который к тому же нарушает наш тон.
 *
 * Автора не называем даже именем: человек соглашался на публикацию снимка
 * еды, а не на то, чтобы его имя стояло рядом с его же рационом. Атрибуция
 * — «читатель «Живого Тела»».
 */
export function buildCaption(productName: string, grams?: number | null): string {
  const base = productName.trim();
  if (!grams || grams <= 0) return base;
  return `${base}, порция ${Math.round(grams)} г`;
}

