/**
 * Юридический слой: версии документов, виды согласий и тексты, общие для
 * интерфейса и документов. Здесь нет обращений к окружению и к базе, поэтому
 * модуль безопасно импортировать в клиентские компоненты — реквизиты
 * оператора живут отдельно, в lib/legal-operator.ts.
 *
 * Версии документов важны не для красоты: по 152-ФЗ оператор должен уметь
 * показать, на какую именно редакцию пользователь дал согласие. Поэтому
 * версия сохраняется вместе с каждым согласием (таблица user_consents).
 */

/**
 * Дата последней редакции юридических документов.
 *
 * Двигается вслед за офертой, потому что `/legal/tarify` подставляет числа
 * из кода и подписывает «Редакция от …»: старая дата под новой таблицей была
 * бы неправдой.
 *
 * - 6 августа 2026 — снижены дневные лимиты бесплатного тарифа.
 * - 8 августа 2026 — в политику добавлено, что предложить публикацию
 *   фотографии может и Оператор, и что предложение согласием не является:
 *   до утвердительного ответа снимок не публикуется, а молчание согласием
 *   не считается (152-ФЗ, ст. 10.1 ч. 8). Плюс запрет на предложения в
 *   настройках.
 * - 7 августа 2026 — бесплатный тариф отменён. Вместо него пробный месяц от
 *   даты регистрации; после него платными становятся обращения к модели, а
 *   дневник, история, план, вес, обзоры, каталог и выгрузка остаются
 *   открытыми — это записано в оферте отдельным разделом.
 *
 * `LEGAL_VERSION` при этом **не двигается**: версия отвечает на вопрос, на
 * какую редакцию человек дал согласие по 152-ФЗ, а состав обрабатываемых
 * данных, цели и основания не изменились — изменились коммерческие условия.
 * Поднять версию значило бы потребовать согласие заново там, где согласовывать
 * нечего.
 */
export const LEGAL_UPDATED_AT = "2026-08-08";

/**
 * Версия документов, которая сохраняется вместе с согласием пользователя.
 *
 * 1.3 набиралась двумя правками, и обе описаны здесь, чтобы через год было
 * видно, на что именно человек соглашался под этим номером:
 *
 * - периодические отчёты: в политику добавлена цель обработки, в таблицу
 *   получателей — поставщик почты и то, что на самом деле уходит в Telegram,
 *   а на страницу «Границы сервиса» — прямое описание того, как ведёт себя
 *   счётчик серии;
 * - публикация фотографий в каталоге (раздел 8 политики): отдельная цель,
 *   отдельное согласие в момент отправки снимка, модерация человеком и
 *   отзыв в настройках.
 *
 * Согласия, данные под 1.2, остаются действительными: состав данных и
 * основания не изменились, изменилось описание того, что мы с ними делаем.
 */
export const LEGAL_VERSION = "1.3";

/**
 * Виды согласий. Разделены сознательно:
 *
 * - `terms` — принятие оферты и политики: обычные данные (e-mail).
 * - `ai_processing` — данные о питании, весе и фото еды. Они близки к
 *   сведениям о здоровье, поэтому согласие берётся отдельно и явно. Этот же
 *   документ покрывает передачу обезличенных данных AI-провайдеру за
 *   пределы РФ — без неё разбор еды невозможен.
 * - `waitlist` — e-mail из формы на лендинге, до появления аккаунта.
 * - `email_series` — e-mail из формы под калькулятором, для серии писем с
 *   разбором расчёта. Отдельно от `waitlist`: там ожидание приглашения,
 *   здесь рассылка, и отписаться от одного, оставшись в другом, человек
 *   должен иметь возможность.
 * - `photo_publication` — публикация присланной фотографии еды в публичном
 *   каталоге продуктов. Отдельно от `ai_processing` намеренно: там снимок
 *   обрабатывается, чтобы посчитать еду этого же человека, и остаётся в его
 *   дневнике; здесь он уходит на страницу, которую увидит кто угодно. Это
 *   разные цели обработки, и согласие на первую не покрывает вторую.
 *   Отзывается отдельно, и отзыв убирает снимки с публичных страниц.
 */
export const CONSENT_KINDS = ["terms", "ai_processing", "waitlist", "email_series", "photo_publication"] as const;
export type ConsentKind = (typeof CONSENT_KINDS)[number];

export const CONSENT_LABELS: Record<ConsentKind, string> = {
  terms: "Пользовательское соглашение и Политика конфиденциальности",
  ai_processing: "Согласие на обработку данных о питании, весе и фотографий еды",
  waitlist: "Согласие на обработку e-mail для приглашения в сервис",
  email_series: "Согласие на обработку e-mail для получения разбора расчёта",
  photo_publication: "Согласие на публикацию присланной фотографии еды в каталоге продуктов",
};

export function isConsentKind(value: string): value is ConsentKind {
  return (CONSENT_KINDS as readonly string[]).includes(value);
}

