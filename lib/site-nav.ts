/**
 * Состав главного меню — отдельно от разметки шапки.
 *
 * ## Зачем отдельный файл
 *
 * В шапке меню жило прямо в JSX, и там накопилось четыре ошибки, каждую из
 * которых видно только глазами и только если знать, куда смотреть:
 *
 *  - «Продукт» и «Решения» открывали одну и ту же панель с обоими списками
 *    сразу — состояние на всю шапку было одно;
 *  - «О нас» вело на якорь `about`, которого на главной нет вовсе, — кнопка
 *    просто ничего не делала;
 *  - ссылки внутри панели никто не сверял с настоящими маршрутами;
 *  - три расчёта из шести — про калории, про белок и про темп — в меню не
 *    попали вовсе, хотя это ровно те страницы, на которые люди приходят из
 *    поиска. Дотуда добирались только через `/raschet`, догадавшись, что
 *    «Для себя» означает расчёты.
 *
 * Здесь это данные, а не разметка, поэтому их можно проверить тестом:
 * tests/site-nav.test.mjs сверяет каждый адрес с файлами приложения, каждый
 * якорь — с настоящими `id` на главной, а заодно следит, чтобы ни одна
 * публичная страница не осталась без входа из меню.
 */

export type NavLink = { href: string; label: string };

/**
 * Картинка в правой части панели. Раньше там стояла салатовая плашка с
 * подписью — одна и та же на оба раздела, то есть ещё одно место, где
 * разделы выглядели одинаково.
 */
export type NavArt = { src: string; alt: string; caption: string; accent: string };

/**
 * Раздел меню: панель с ссылками, якорь на главной или прямая ссылка.
 *
 * Третий вид добавлен, когда журнал переехал с главной на свою страницу.
 * До этого выбор был только между «панель» и «якорь», и пункт, ведущий на
 * отдельную страницу, приходилось притворять якорем — что и случилось:
 * «Журнал» указывал на блок, которого на главной больше нет.
 */
export type NavSection =
  | { label: string; links: NavLink[]; art: NavArt }
  | { label: string; anchor: string }
  | { label: string; href: string };

