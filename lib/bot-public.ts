/**
 * Публичные ссылки на бота — то, что можно показать кому угодно.
 *
 * Имя бота не секрет: оно написано в его профиле и в любой ссылке на него.
 * Поэтому оно здесь константой, а не переменной окружения. Так его можно
 * подставить в статическую страницу и в QR-код, собираемый при сборке, — а
 * переменная окружения потребовала бы генерировать QR в рантайме и тащить
 * ради этого кодировщик в приложение.
 *
 * Секретное про бота — токен и секрет вебхука — живёт в окружении и сюда
 * не попадает никогда: этот модуль импортируется клиентскими компонентами.
 */

export const BOT_USERNAME = "jivelo_bot";

/**
 * Ссылка на бота. `start=<метка>` — необязательный признак, откуда человек
 * пришёл: бот по нему меняет приветствие, чтобы не предлагать посчитать
 * норму тому, кто её только что посчитал на сайте.
 */
export function botLink(start?: string): string {
  const base = `https://t.me/${BOT_USERNAME}`;
  return start ? `${base}?start=${encodeURIComponent(start)}` : base;
}

/**
 * Метки диплинков. Держим списком, а не строками по месту: метка попадает и
 * в ссылку на сайте, и в разбор в боте, и разойтись им нельзя.
 */
export const START_PAYLOADS = {
  /** Пришёл с экрана результата расчёта — норму уже знает. */
  plan: "plan",
  /** Пришёл из пустого дневника в вебе — аккаунт уже есть. */
  web: "web",
} as const;

export type StartPayload = (typeof START_PAYLOADS)[keyof typeof START_PAYLOADS];

export function isStartPayload(value: string): value is StartPayload {
  return (Object.values(START_PAYLOADS) as string[]).includes(value);
}
