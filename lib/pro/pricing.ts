/**
 * Кто и за что платит в «Живом Теле Pro».
 *
 * ## Правило
 *
 * **Кабинет специалиста бесплатен. Всегда, без срока и без условий.**
 * Деньги сервис берёт только с клиента — за его собственный дневник, по
 * общему тарифу (`lib/paid.ts`), после общего пробного месяца. Специалист не
 * платит ни за подключение, ни за число клиентов, ни за объём данных.
 *
 * ## Почему так, а не подпиской для специалиста
 *
 * Кабинет ничего не считает сам. Он показывает то, что уже посчитано в
 * дневнике клиента: итоги недели, записи, тренд веса. Расходы на модель
 * несёт клиентская сторона, и она же оплачена. Брать за просмотр второй раз
 * значило бы продавать одну работу дважды.
 *
 * Вторая причина практическая. Специалист приводит людей, которые заводят
 * дневники и платят за них; подписка для него была бы платой за то, что он
 * приводит нам плательщиков. Это ровно тот случай, когда цена стоит на пути
 * у собственной выручки.
 *
 * ## Что из этого следует для кода
 *
 * Ни одна проверка доступа в разделе не смотрит на тариф. `lib/pro/guard.ts`
 * и `lib/pro/access.ts` знают про статус специалиста и про разрешения
 * клиента — и не знают про `plan`, `accessUntil` и `PLAN_LIMITS`. Это не
 * случайность, а условие: tests/pro-pricing.test.mjs читает исходники обоих
 * модулей и падает, если оплата в них появится.
 *
 * Проверка нужна именно такая — по тексту модулей, а не по поведению. Плату
 * за кабинет вводят не «функцией включения тарифа», а одной строкой
 * `if (user.plan !== "premium") return null` в проходе, и снаружи это
 * выглядит как обычный отказ в доступе.
 */

