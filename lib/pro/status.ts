/**
 * Статус клиента в списке специалиста: оценка **вместе с основанием**.
 *
 * ## Почему не просто «Стабильный ритм»
 *
 * Голый ярлык — это утверждение о человеке, показанное третьему лицу. Клиент
 * дал согласие делиться данными, а не быть охарактеризованным; а специалист,
 * увидевший «нужна поддержка» у клиента, который на самом деле в порядке,
 * спишет со счетов не ярлык, а нас — и это ровно та аудитория, которую терять
 * нельзя.
 *
 * Поэтому у каждой оценки рядом стоит то, из чего она сделана: «6 из 7 дней»,
 * «нет записей 9 дней». Специалист видит основание и может не согласиться —
 * а мы не делаем заявлений, которые нечем подкрепить.
 *
 * ## Почему не просто «сколько дней»
 *
 * Потому что список из пятнадцати клиентов, где у каждого написано «4 из 7»,
 * читается дольше, чем взглядом. Цветная метка нужна — она и есть навигация
 * по списку. Вопрос был только в том, чем её подпирать.
 *
 * ## Что здесь не решается
 *
 * Это оценка **регулярности записей**, а не человека и не его питания. Про
 * содержимое дневника здесь нет ничего: тем ведает `withClientScope`, и без
 * открытого доступа специалист состава не увидит. Регулярность же — тот же
 * класс сведений, что и дата последней записи, которую список показывал
 * всегда (см. комментарий к `listClients`): факт о том, ведётся ли дневник,
 * а не о том, что в нём.
 */

export type ClientStatusKind = "steady" | "attention" | "idle";

export type ClientStatus = {
  kind: ClientStatusKind;
  /** Короткая метка — то, что читается взглядом. */
  label: string;
  /** Из чего сделан вывод. Без него метку не показываем. */
  basis: string;
};

/** Сколько дней из последних семи считаем «стабильным ритмом». */
export const STEADY_DAYS = 5;

export type StatusInput = {
  /** Дней с записями за последние семь. */
  loggedDays: number;
  /** Дата последней записи, `null` — записей не было вовсе. */
  lastMealOn: string | null;
  /** Сегодня в таймзоне продукта. */
  today: string;
};

/** Разница в днях между двумя датами вида `2026-07-31`. */
function daysBetween(from: string, to: string): number {
  const ms = Date.parse(`${to}T12:00:00Z`) - Date.parse(`${from}T12:00:00Z`);
  return Math.round(ms / 86_400_000);
}

export function clientStatus(input: StatusInput): ClientStatus {
  const { loggedDays, lastMealOn, today } = input;

  // Записей не было вовсе — это не «нужна поддержка». Человек мог принять
  // приглашение час назад, и упрекать его не в чем.
  if (!lastMealOn) {
    return { kind: "idle", label: "Ещё не начал", basis: "записей нет" };
  }

  if (loggedDays >= STEADY_DAYS) {
    return { kind: "steady", label: "Стабильный ритм", basis: `${loggedDays} из 7 дней` };
  }

  // За неделю ни одной записи — считаем по давности последней, иначе основание
  // «0 из 7 дней» одинаково у того, кто пропал вчера, и у того, кто месяц назад.
  if (loggedDays === 0) {
    const silence = Math.max(daysBetween(lastMealOn, today), 0);
    return { kind: "attention", label: "Нужна поддержка", basis: `нет записей ${silence} дн.` };
  }

  return { kind: "attention", label: "Нужна поддержка", basis: `${loggedDays} из 7 дней` };
}
