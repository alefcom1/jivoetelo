export const MICRO_GROUPS = ["Витамины", "Минералы"] as const;

export function nutrientsIn(group: (typeof MICRO_GROUPS)[number]): Micronutrient[] {
  return MICRONUTRIENTS.filter((item) => item.group === group);
}

/** Норма нутриента для пола. */
export function normFor(nutrient: Micronutrient, sex: "female" | "male"): number {
  return sex === "female" ? nutrient.female : nutrient.male;
}

/** Сколько граммов продукта закроют норму целиком. */
export function gramsForNorm(nutrient: Micronutrient, sex: "female" | "male", per100: number): number {
  const norm = normFor(nutrient, sex);
  if (!(per100 > 0)) return 0;
  return Math.round((norm / per100) * 100);
}
