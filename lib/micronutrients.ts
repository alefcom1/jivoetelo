/**
 * Витамины и минералы: суточные нормы и чем их закрыть.
 *
 * ## Почему это самая нужная страница раздела
 *
 * Полноценного русского калькулятора микронутриентов нет: выдача забита
 * таблицами «норма витамина C — 90 мг» без единого указания, откуда взято
 * число и из чего эти миллиграммы брать. Между тем нормы в России
 * официально установлены — МР 2.3.1.0253-21 «Нормы физиологических
 * потребностей в энергии и пищевых веществах для различных групп населения
 * Российской Федерации».
 *
 * ## Что мы делаем сверх нормы
 *
 * Показываем **источники в порциях**. У нас есть справочник на три сотни
 * позиций, и вместо «ешьте больше овощей» страница отвечает: столько-то
 * граммов такого-то продукта — и норма закрыта. Это единственный способ
 * сделать микронутриенты не абстракцией.
 *
 * ## Границы
 *
 * Нормы — для здорового взрослого. Беременность, кормление, детский
 * возраст и заболевания меняют потребность, иногда в разы, и там нужен
 * врач, а не калькулятор. Верхние допустимые уровни приводим для тех
 * нутриентов, где передозировка реальна: витамины A и D, железо, цинк.
 */

export type Micronutrient = {
  key: string;
  name: string;
  unit: "мг" | "мкг" | "г";
  /** Норма для женщин и мужчин: у части нутриентов они различаются. */
  female: number;
  male: number;
  /** Верхний допустимый уровень потребления, если он значим. */
  upper?: number;
  group: "Витамины" | "Минералы";
  /** Зачем он нужен — одной фразой, без списка из двадцати функций. */
  role: string;
  /** Продукты из нашего справочника, богатые этим нутриентом. */
  sources: Array<{ name: string; per100: number }>;
  /** Что стоит знать помимо цифры. */
  note?: string;
};

