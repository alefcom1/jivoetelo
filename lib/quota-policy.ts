/**
 * Политика тарифов: какие дневные лимиты действуют и как о них говорить.
 * Здесь нет обращений к базе — только правила, поэтому модуль тестируется
 * напрямую и переиспользуется на клиенте.
 *
 * ## Что здесь изменилось и почему это важно читать
 *
 * Модель менялась дважды, и оба прежних текста здесь оставлены нарочно: без
 * них в коде остаются комментарии, объясняющие правила, которых больше нет.
 *
 *  1. Сначала было: «лимиты — не монетизация, а защита от неумеренного
 *     расхода; они выставлены заметно выше реального дневного сценария».
 *  2. С августа 2026 бесплатный тариф стал «знакомством и лёгким режимом»:
 *     шесть разборов по фото в сутки бессрочно, дальше за деньги.
 *  3. Сейчас бесплатного тарифа нет вовсе. Есть **пробный месяц**: первые
 *     тридцать дней от регистрации доступ полный, дальше — оплата.
 *
 * Отсюда `PLAN_LIMITS.free` со сплошными нулями. Это не «очень маленький
 * лимит», а закрытый доступ, и читать его надо именно так: `free` в этом
 * файле теперь значит «пробный месяц кончился, оплаты нет», а не «бесплатный
 * тариф». Имя оставлено прежним, потому что им же названы колонка в базе и
 * ключи этой таблицы; смысл — нет.
 *
 * Что при этом **не изменилось и меняться не должно**: платным становится
 * обращение к модели, а не дневник. Ручная запись еды, история, план, вес,
 * обзоры, каталог, расчёты и выгрузка своих данных доступны всегда — и во
 * время пробного месяца, и после него, и тому, кто не заплатит никогда.
 * Записи принадлежат человеку; за доступ к собственному прошлому денег не
 * берут. Это правило сторожит tests/quota.test.mjs.
 */

/**
 * Операции, которые обслуживает языковая модель Anthropic. Отдельно от
 * AiOperation, потому что у них есть то, чего нет у расшифровки: модель,
 * таймаут, число повторов и цена за токен (lib/ai/client.ts).
 */
export const MODEL_OPERATIONS = ["analyze_photo", "analyze_text", "suggest", "read_scale"] as const;

export type ModelOperation = (typeof MODEL_OPERATIONS)[number];

/**
 * Всё, что считает предохранитель расхода. Расшифровка речи денег не стоит —
 * она идёт на нашем же сервере, — но лимит частоты ей нужен не меньше:
 * точка приёма мегабайтных файлов без ограничения занимает сервер целиком.
 */
export const AI_OPERATIONS = [...MODEL_OPERATIONS, "transcribe"] as const;

export type AiOperation = (typeof AI_OPERATIONS)[number];
export type Plan = "free" | "premium";
export type PlanLimits = Record<AiOperation, number>;

export const PLAN_LIMITS: Record<Plan, PlanLimits> = {
  /**
   * Доступа нет: пробный месяц кончился, оплаты нет.
   *
   * Нули, а не маленькие числа. Полумера — «оставим два разбора в сутки» —
   * выглядит добрее, но работает хуже всего: человеку её не хватает, чтобы
   * вести дневник, и хватает, чтобы не решать. Граница, проведённая
   * наполовину, не граница.
   *
   * Дневник при этом остаётся полным. Ноль стоит здесь и только здесь —
   * в таблице обращений к модели.
   */
  free: { analyze_photo: 0, analyze_text: 0, suggest: 0, read_scale: 0, transcribe: 0 },
  /**
   * Доступ открыт — пробным месяцем, оплатой, ваучером или приглашением.
   * Числа не «в разы больше для красоты»: при 100 разборах по фото в день
   * человек упирается в них, только если снимает не свою еду, а подряд всё,
   * что видит, — то есть там, где начинается уже не дневник.
   */
  premium: { analyze_photo: 100, analyze_text: 200, suggest: 60, read_scale: 40, transcribe: 300 },
};

