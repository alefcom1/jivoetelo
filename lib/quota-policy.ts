/**
 * Политика тарифов: какие дневные лимиты действуют и как о них говорить.
 * Здесь нет обращений к базе — только правила, поэтому модуль тестируется
 * напрямую и переиспользуется на клиенте.
 *
 * ## Что здесь изменилось и почему это важно читать
 *
 * Раньше в этом комментарии стояло: «лимиты — не монетизация, а защита от
 * неумеренного расхода; они выставлены заметно выше реального дневного
 * сценария, так что обычный пользователь их не заметит». С августа 2026 это
 * больше не так, и оставить прежний текст было бы хуже, чем не иметь его
 * вовсе: он описывал бы сервис, которого нет.
 *
 * Теперь бесплатный тариф рассчитан на **знакомство и лёгкий режим**, а не на
 * полное ведение дневника по фото. Шесть разборов по фото — это 3–4 приёма
 * пищи с запасом на один-два перезаснятых кадра; человек, снимающий каждую
 * тарелку и каждый перекус, границу увидит. Это и есть граница платного
 * доступа.
 *
 * Что при этом **не изменилось и меняться не должно**: ручная запись еды не
 * ограничена ничем и никогда. Бесплатный путь ведения дневника остаётся
 * полным — платным становится не дневник, а объём распознавания.
 */

/**
 * Операции, которые обслуживает языковая модель Anthropic. Отдельно от
 * AiOperation, потому что у них есть то, чего нет у расшифровки: модель,
 * таймаут, число повторов и цена за токен (lib/ai/client.ts).
 */
export const MODEL_OPERATIONS = ["analyze_photo", "analyze_text", "suggest", "read_scale"] as const;

export type ModelOperation = (typeof MODEL_OPERATIONS)[number];

/**
 * Всё, что считает предохранитель расхода. Расшифровка речи денег не стоит —
 * она идёт на нашем же сервере, — но лимит частоты ей нужен не меньше:
 * точка приёма мегабайтных файлов без ограничения занимает сервер целиком.
 */
export const AI_OPERATIONS = [...MODEL_OPERATIONS, "transcribe"] as const;

export type AiOperation = (typeof AI_OPERATIONS)[number];
export type Plan = "free" | "premium";
export type PlanLimits = Record<AiOperation, number>;

export const PLAN_LIMITS: Record<Plan, PlanLimits> = {
  /**
   * Бесплатный тариф — знакомство и лёгкий режим.
   *
   * Шесть разборов по фото это 3–4 приёма пищи плюс запас на перезаснятый
   * кадр. Двенадцать по описанию вдвое больше — текст и стоит впятеро дешевле
   * снимка, и чаще служит уточнением к уже записанному. Три снимка весов при
   * одном взвешивании в день — с запасом на неудачный ракурс.
   */
  free: { analyze_photo: 6, analyze_text: 12, suggest: 6, read_scale: 3, transcribe: 12 },
  /**
   * Платный. Числа не «в разы больше для красоты»: при 100 разборах по фото
   * в день человек упирается в них, только если снимает не свою еду, а
   * подряд всё, что видит, — то есть там, где начинается уже не дневник.
   */
  premium: { analyze_photo: 100, analyze_text: 200, suggest: 60, read_scale: 40, transcribe: 300 },
};

export const OPERATION_LABELS: Record<AiOperation, string> = {
  analyze_photo: "разборов по фото",
  analyze_text: "разборов по описанию",
  suggest: "подборов «что съесть дальше»",
  read_scale: "снимков весов",
  transcribe: "расшифровок голосом",
};

/**
 * Те же операции одним-двумя словами — для заголовков таблиц.
 *
 * Подписи выше написаны для фразы «на сегодня доступные … закончились», и в
 * шапке колонки «подборов „что съесть дальше“» растягивало таблицу шире
 * экрана: обрезалась крайняя правая колонка — итог, ради которого таблицу и
 * открывают. Родительный падеж там же не нужен: в шапке стоит название, а не
 * продолжение предложения.
 */
export const OPERATION_SHORT: Record<AiOperation, string> = {
  analyze_photo: "фото",
  analyze_text: "текст",
  suggest: "подсказки",
  read_scale: "весы",
  transcribe: "голос",
};

/**
 * Минимальный интервал между двумя обращениями к ОДНОЙ операции — защита от
 * скриптового перебора. Считается пооперационно: нормально сохранить еду и
 * сразу спросить совет, а вот долбить один эндпоинт подряд — нет. Общий
 * потолок расхода всё равно держат дневные лимиты.
 */
export const MIN_INTERVAL_MS = 3000;

/**
 * Цены за миллион токенов — по модели, которая реально обслуживает операцию
 * (см. resolveModel в lib/ai/client.ts). Раньше здесь была одна ставка Opus
 * на всё, и это было не просто неточно: дневной предохранитель считал расход
 * впятеро больше настоящего и обрубал разбор задолго до реального потолка —
 * то есть съедал ровно ту экономию, ради которой модели и разводились.
 *
 * Ставки прейскурантные, без вводных скидок: предохранитель должен
 * ошибаться в сторону осторожности, а не оптимизма.
 */
const PRICE_PER_MTOK: Record<AiOperation, { input: number; output: number }> = {
  analyze_photo: { input: 3, output: 15 }, // Sonnet 5
  analyze_text: { input: 1, output: 5 }, // Haiku 4.5
  suggest: { input: 1, output: 5 }, // Haiku 4.5
  read_scale: { input: 3, output: 15 }, // Sonnet 5
  // Своя установка на нашем же сервере: денег наружу не уходит вовсе, и
  // токенов у неё нет. Ноль здесь — не заглушка, а точная цена.
  transcribe: { input: 0, output: 0 },
};

/** Самая дорогая из ставок — умолчание, когда операция неизвестна. */
const PRICE_FALLBACK = { input: 5, output: 25 };

export type TokenUsage = { inputTokens: number; outputTokens: number };

/**
 * Операцию передавать необязательно: без неё считаем по ставке Opus. Это
 * сознательный перестраховочный путь для вызовов, где операция не известна, —
 * завысить оценку безопаснее, чем занизить.
 */
export function estimateCostUsd(usage: TokenUsage, operation?: AiOperation): number {
  const price = (operation && PRICE_PER_MTOK[operation]) || PRICE_FALLBACK;
  return (usage.inputTokens / 1_000_000) * price.input + (usage.outputTokens / 1_000_000) * price.output;
}

/** Глобальный дневной потолок расходов на AI, USD. Переопределяется env. */
export function globalDailyBudgetUsd(): number {
  const raw = Number(process.env.AI_DAILY_BUDGET_USD);
  return Number.isFinite(raw) && raw > 0 ? raw : 25;
}

export function normalizePlan(plan: string | null | undefined): Plan {
  return plan === "premium" ? "premium" : "free";
}

export type QuotaDenial =
  | { allowed: false; reason: "daily_limit"; used: number; limit: number; operation: AiOperation; plan: Plan }
  | { allowed: false; reason: "too_fast" }
  | { allowed: false; reason: "service_budget" };

export type QuotaDecision = { allowed: true; used: number; limit: number } | QuotaDenial;

/**
 * Сообщения об отказе. Формулировки поддерживающие и без обвинений
 * (языковые правила, раздел 4.3 спеки): лимит — свойство сервиса, а не
 * оценка пользователя.
 */
export function quotaMessage(denial: QuotaDenial): string {
  switch (denial.reason) {
    case "too_fast":
      return "Секунду — предыдущий запрос ещё обрабатывается. Попробуйте ещё раз через пару секунд.";
    case "daily_limit": {
      const base = `На сегодня доступные ${OPERATION_LABELS[denial.operation]} закончились (${denial.limit} в день). Лимит обновится завтра, а записать еду вручную можно без ограничений.`;
      /**
       * Про платный доступ говорим только тому, кто может им воспользоваться,
       * и только когда оплата действительно работает. Предложить заплатить
       * там, где платить некуда, — худший вид рекламы: человек нажимает и
       * упирается в пустоту.
       *
       * Переменная окружения читается прямо здесь, как и в
       * `globalDailyBudgetUsd()` выше. На клиенте её нет, и там условие даст
       * `false` — то есть по умолчанию мы молчим, а не зовём в никуда.
       */
      const canUpgrade = denial.plan === "free" && process.env.PAYMENTS_ENABLED === "true";
      return canUpgrade
        ? `${base} На платном тарифе лимиты выше — открыть можно в настройках.`
        : base;
    }
    case "service_budget":
      return "Сервис распознавания сегодня работает с повышенной нагрузкой. Попробуйте позже или добавьте еду вручную — это доступно всегда.";
  }
}
