/**
 * Квиз «Стоит ли вам сейчас снижать вес» — тексты вердиктов.
 *
 * Само решение здесь больше не принимается: его принимает `softeningReason`
 * из lib/safety.ts, а этот модуль лишь пересказывает вывод словами. Раньше
 * правила были записаны тут, а в онбординге — своя, вдвое более короткая их
 * версия, и дневник получался менее бережным, чем витрина сайта.
 *
 * Порядок вердиктов совпадает с порядком причин в safety.ts и проверяется
 * тестом: любой набор ответов, на который квиз говорит «не сейчас», обязан
 * смягчать цель и в онбординге.
 */

import { softeningReason } from "./safety.ts";

export type QuizAnswers = {
  motivation: "health" | "look" | "energy" | "unsure";
  recentDieting: "no" | "recently" | "constantly";
  relationship: "calm" | "tense" | "hard";
  sleep: "ok" | "poor";
  lifeLoad: "calm" | "busy" | "overloaded";
};

export type QuizVerdict = {
  key: "reduce" | "maintain" | "steady" | "care";
  title: string;
  summary: string;
  advice: string[];
};

export function evaluateQuiz(answers: QuizAnswers): QuizVerdict {
  const reason = softeningReason(answers);

  if (reason === "hard_relationship") {
    return {
      key: "care",
      title: "Сейчас важнее отношения с едой, а не цифры",
      summary:
        "Судя по ответам, еда сейчас забирает много душевных сил. В таком состоянии подсчёт калорий чаще усиливает " +
        "тревогу, чем помогает. Это не значит, что с вами что-то не так, — это значит, что начинать стоит с " +
        "другого места.",
      advice: [
        "Попробуйте вести дневник в режиме «скрыть калории»: остаются белок, клетчатка и регулярность, без цифр энергии.",
        "Если еда стала источником постоянной вины или потери контроля, это повод поговорить со специалистом по расстройствам пищевого поведения.",
        "Никаких дефицитов сейчас: сначала спокойствие, потом любые изменения.",
      ],
    };
  }

  if (reason === "overload") {
    return {
      key: "steady",
      title: "Хорошее время для регулярности, а не для дефицита",
      summary:
        "Недосып и перегрузка делают дефицит заметно тяжелее: сильнее голод, ниже устойчивость к срывам. Это " +
        "физиология, а не слабая воля. Разумнее сначала вернуть сон и разгрузить график.",
      advice: [
        "Держите питание на уровне поддержания — вес при этом обычно не растёт.",
        "Сфокусируйтесь на белке и регулярности приёмов пищи: это работает даже без дефицита.",
        "Вернитесь к вопросу снижения веса, когда сон и нагрузка выровняются.",
      ],
    };
  }

  if (reason === "dieting_cycle") {
    return {
      key: "maintain",
      title: "Похоже, вам стоит сделать паузу",
      summary:
        "Диеты подряд без перерывов изматывают и хуже работают: организм экономит энергию, а желание сорваться " +
        "накапливается. Время на поддержании — не потерянное время.",
      advice: [
        "Побудьте на поддержании хотя бы несколько недель: это почти никогда не плохой вариант.",
        "На поддержании при достаточном белке состав тела всё равно меняется, просто медленнее.",
        "Следующий дефицит после паузы обычно переносится заметно легче.",
      ],
    };
  }

  return {
    key: "reduce",
    title: "Можно спокойно двигаться к снижению веса",
    summary:
      "По ответам ничего не мешает начать. Главное — темп: мягкий дефицит переносится лучше и реже заканчивается " +
      "срывом, чем резкий.",
    advice: [
      "Начните с дефицита около 15 процентов от вашего ориентира — без экстремальных ограничений.",
      "Ориентируйтесь на недельный тренд веса, а не на дневные колебания: они в основном про воду.",
      "Если через две-три недели вес не двигается, план стоит уточнить по факту, а не урезать наугад.",
    ],
  };
}
