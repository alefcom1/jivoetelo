/**
 * Выбор камеры, когда их несколько.
 *
 * ## Зачем
 *
 * На ноутбуке `getUserMedia` без явного указания устройства отдаёт то, что
 * система считает камерой по умолчанию, — и это регулярно оказывается не
 * встроенная камера, а виртуальная: OBS, Snap Camera, Camo. Человек нажимает
 * «снять тарелку» и видит заставку стрима.
 *
 * Угадать до выдачи доступа нельзя: пока разрешение не дано, браузер
 * возвращает список устройств без названий — это защита от слежки по набору
 * оборудования. Поэтому порядок такой: сначала берём любую камеру, потом
 * читаем названия и, если активной оказалась виртуальная, переключаемся.
 *
 * ## Почему список, а не только автовыбор
 *
 * Эвристика по названию не может быть полной: виртуальных камер много, и
 * завтра появится ещё одна. Автовыбор снимает частый случай, список решает
 * остальные — и заодно даёт на телефоне переключение между задней и передней
 * камерой, которого иначе нет.
 */

export type CameraDevice = { deviceId: string; label: string; virtual: boolean };

/**
 * Названия виртуальных камер. Список заведомо неполный и таким и останется —
 * поэтому он влияет только на порядок предпочтения и никогда ничего не
 * запрещает: незнакомую виртуальную камеру человек выберет сам, а ошибочно
 * принятую за виртуальную настоящую — тоже сам.
 */
const VIRTUAL = /obs|virtual|виртуал|snap camera|manycam|droidcam|epoccam|iriun|xsplit|streamlabs|mmhmm|\bcamo\b|\bndi\b/i;

export function isVirtualCamera(label: string): boolean {
  return VIRTUAL.test(label);
}

/**
 * Приводит список устройств к нашему виду. Камеры без названия оставляем:
 * названия нет либо до выдачи доступа, либо у части устройств в некоторых
 * браузерах — выбрасывать их значило бы спрятать настоящую камеру.
 */
export function toCameraDevices(devices: MediaDeviceInfo[]): CameraDevice[] {
  return devices
    .filter((device) => device.kind === "videoinput")
    .map((device, index) => ({
      deviceId: device.deviceId,
      label: device.label || `Камера ${index + 1}`,
      virtual: isVirtualCamera(device.label),
    }));
}

/**
 * Какую камеру взять вместо текущей — или `null`, если менять не нужно.
 *
 * Меняем ровно в одном случае: активна виртуальная, а невиртуальная есть.
 * Во всех остальных не трогаем: человек мог выбрать виртуальную намеренно,
 * и переключать её под ним каждый раз было бы хуже, чем не угадать однажды.
 */
export function preferredCamera(devices: CameraDevice[], activeLabel: string): string | null {
  if (!isVirtualCamera(activeLabel)) return null;
  const real = devices.find((device) => !device.virtual && device.deviceId);
  return real?.deviceId ?? null;
}
