/**
 * Качество кадра — числами, без всякого распознавания.
 *
 * ## Зачем
 *
 * Два применения, и это не совпадение, а условие задачи:
 *
 * 1. **Живой видоискатель.** Автоспуск срабатывает, когда телефон замер и
 *    кадр резкий, — это и есть «оно меня понимает» без единого мегабайта
 *    модели.
 * 2. **Разбор своего архива.** Те же числа считаются по уже снятым фото из
 *    дневника и сопоставляются с уверенностью разбора. Так выясняется, что
 *    на самом деле портит распознавание: размытие, темнота или что-то ещё.
 *
 * Считать их двумя разными кусками кода было бы бессмысленно: пороги,
 * подобранные по архиву, должны применяться к живому кадру буквально, иначе
 * измерение ничего не доказывает.
 *
 * ## Почему без модели
 *
 * Всё ниже — арифметика по яркости: свёртка 3×3, среднее, дисперсия. На кадре
 * 256×192 это доли миллисекунды и нулевая загрузка. Распознавание еды — задача
 * другого порядка (см. lib/food-presence.ts), и она ортогональна: даже
 * безошибочно узнав «гречка», модель не подскажет, что кадр смазан.
 */

export type FrameStats = {
  /**
   * Резкость: дисперсия лапласиана яркости. Ноль — равномерная заливка,
   * сотни — чёткие границы. Значения зависят от размера кадра и от того,
   * что в нём, поэтому сравнивать их можно только между кадрами одного
   * размера — а размер здесь фиксирован (см. SAMPLE_WIDTH).
   */
  sharpness: number;
  /** Средняя яркость, 0..255. */
  luma: number;
  /** Доля пикселей, выбитых в белое или проваленных в чёрное, 0..1. */
  clipped: number;
};

/**
 * Размер, к которому приводится кадр перед измерением.
 *
 * Он часть определения метрик, а не настройка производительности: уменьшение
 * само по себе размывает картинку, поэтому резкость, посчитанная на 640×480 и
 * на 256×192, — два разных числа. Менять здесь значит обесценить все пороги
 * ниже и все замеры по архиву.
 */
export const SAMPLE_WIDTH = 256;
export const SAMPLE_HEIGHT = 192;

/** Яркость по Rec. 601 — та же формула, что и у остальных «серых» переводов. */
export function toGrayscale(rgba: Uint8ClampedArray | Uint8Array, out?: Uint8ClampedArray): Uint8ClampedArray {
  const count = rgba.length >> 2;
  const gray = out ?? new Uint8ClampedArray(count);
  for (let i = 0, p = 0; i < count; i++, p += 4) {
    gray[i] = (rgba[p] * 299 + rgba[p + 1] * 587 + rgba[p + 2] * 114) / 1000;
  }
  return gray;
}

/**
 * Резкость, яркость и выбитость по серому кадру.
 *
 * Лапласиан считается по внутренним пикселям: у краёв нет полного соседства,
 * и досчитывать их отражением значило бы добавить в статистику границу,
 * которой в кадре нет.
 */
export function frameStats(gray: Uint8ClampedArray, width: number, height: number): FrameStats {
  let sum = 0;
  let clipped = 0;
  for (let i = 0; i < gray.length; i++) {
    sum += gray[i];
    if (gray[i] <= 4 || gray[i] >= 251) clipped++;
  }

  let lapSum = 0;
  let lapSquares = 0;
  let n = 0;
  for (let y = 1; y < height - 1; y++) {
    for (let x = 1; x < width - 1; x++) {
      const i = y * width + x;
      const value = 4 * gray[i] - gray[i - 1] - gray[i + 1] - gray[i - width] - gray[i + width];
      lapSum += value;
      lapSquares += value * value;
      n++;
    }
  }

  const mean = n > 0 ? lapSum / n : 0;
  return {
    sharpness: n > 0 ? lapSquares / n - mean * mean : 0,
    luma: gray.length > 0 ? sum / gray.length : 0,
    clipped: gray.length > 0 ? clipped / gray.length : 0,
  };
}

/**
 * Насколько кадр отличается от предыдущего, 0..1.
 *
 * Это мера движения: дрожание рук, поворот телефона, проход мимо. Шум матрицы
 * даёт около 0.005 даже на неподвижной сцене — поэтому «замер» это не ноль,
 * а «меньше порога» (см. STEADY_MOTION).
 */
export function frameDifference(a: Uint8ClampedArray, b: Uint8ClampedArray): number {
  if (a.length === 0 || a.length !== b.length) return 1;
  let sum = 0;
  for (let i = 0; i < a.length; i++) sum += Math.abs(a[i] - b[i]);
  return sum / a.length / 255;
}

/**
 * Пороги готовности кадра.
 *
 * ## Откуда взяты
 *
 * Это первое приближение, а не результат измерения: подобраны на съёмке
 * тарелки с рук и заведомо будут двигаться. Пересчитать их — работа
 * scripts/photo-quality.mjs: он считает те же метрики по реальным снимкам из
 * дневника и сопоставляет с уверенностью разбора. Пока такого замера нет,
 * пороги намеренно мягкие: цена ложного «готово» — один лишний снимок, цена
 * ложного «не готово» — человек стоит над тарелкой и ждёт непонятно чего.
 */
/**
 * Порог «камера замерла».
 *
 * Из всех чисел здесь это то, которое вероятнее всего придётся двигать: своей
 * съёмки с рук у нас пока нет, а шум матрицы и подстройка экспозиции дают
 * ненулевое движение даже на неподвижном штативе. Взят с запасом сознательно.
 * Строгость тут почти ничего не защищает: смазанный от движения кадр всё
 * равно не пройдёт по резкости, а слишком строгий порог просто выключил бы
 * автоспуск насовсем — и мы бы об этом даже не узнали.
 */
export const STEADY_MOTION = 0.02;
export const MIN_SHARPNESS = 90;
export const MIN_LUMA = 42;
export const MAX_LUMA = 226;
export const MAX_CLIPPED = 0.34;

export type Readiness = {
  steady: boolean;
  sharp: boolean;
  lit: boolean;
  /** Всё сразу: только в этом случае имеет смысл спускать затвор самому. */
  ready: boolean;
};

export function readiness(stats: FrameStats, motion: number): Readiness {
  const steady = motion <= STEADY_MOTION;
  const sharp = stats.sharpness >= MIN_SHARPNESS;
  const lit = stats.luma >= MIN_LUMA && stats.luma <= MAX_LUMA && stats.clipped <= MAX_CLIPPED;
  return { steady, sharp, lit, ready: steady && sharp && lit };
}
