/**
 * Цели Яндекс.Метрики — что именно мы считаем и почему.
 *
 * ## Зачем отдельный модуль на четыре строки
 *
 * Идентификаторы целей заведены в панели Метрики руками, и там же настроено
 * строгое совпадение. Опечатка в коде не сломает ни сборку, ни тесты — она
 * просто даст цель, которая никогда не сработает, и заметить это можно
 * только через неделю по пустому отчёту. Поэтому имена лежат в одном месте
 * и разложены по константам, а не пишутся строкой по месту вызова.
 *
 * ## Что считаем
 *
 * Не «регистрация». Человек, который завёл аккаунт и ничего не записал,
 * продукта не увидел, и считать его успехом воронки значит обманывать себя.
 * Главная цель — **первая запись еды**: это момент, когда обещание сайта
 * («сфотографируйте, посчитаем») сбылось.
 *
 * ## Чего здесь нет
 *
 * Ничего, что описывало бы человека или его еду. В Метрику уходит только имя
 * события — ни веса, ни калорий, ни идентификатора пользователя. Сведения о
 * питании и теле мы обещали не передавать третьим лицам, и это обещание
 * дороже любой аналитики.
 */

/** Расчёт на /raschet/plan доведён до экрана результата. */
export const GOAL_PLAN_DONE = "plan_done";

/** Первая запись еды в дневнике. Главная цель воронки. */
export const GOAL_MEAL_SAVED = "meal_saved";

/**
 * Онбординг доведён до конца — у человека есть план.
 *
 * Здесь стояла цель «привязал Telegram», и от неё пришлось отказаться: связка
 * завершается внутри бота, а не в браузере, и веб-страница о ней просто не
 * узнаёт. Померить её можно было бы, поставив счётчик в Mini App, но там
 * открыт дневник питания, и запускать туда вебвизор ради одной цифры — плохой
 * обмен. Цель, которую нельзя честно измерить, лучше не заводить: пустой
 * отчёт выглядит как «никто не привязывает», а не как «мы не считаем».
 */
export const GOAL_PLAN_SET = "plan_set";

export const ALL_GOALS = [GOAL_PLAN_DONE, GOAL_MEAL_SAVED, GOAL_PLAN_SET] as const;
export type Goal = (typeof ALL_GOALS)[number];

type Ym = (id: number, action: string, target?: string) => void;

/**
 * Отправляет цель, если счётчик на странице есть.
 *
 * Молча ничего не делает, когда счётчика нет: в разработке, в e2e-прогонах и
 * внутри Telegram Mini App (там своё окружение, и тянуть туда счётчик мы не
 * стали). Аналитика не тот повод, ради которого стоит уронить экран.
 */
export function reachGoal(goal: Goal): void {
  if (typeof window === "undefined") return;
  const ym = (window as unknown as { ym?: Ym }).ym;
  const id = (window as unknown as { __ymCounterId?: number }).__ymCounterId;
  if (typeof ym !== "function" || typeof id !== "number") return;
  try {
    ym(id, "reachGoal", goal);
  } catch {
    // Счётчик мог не догрузиться. Это не причина ломать то, что человек делал.
  }
}
