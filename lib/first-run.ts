/**
 * Какую подсказку показать сейчас. `null` — нормальный и самый частый исход.
 *
 * Возвращается ровно одна: две подсказки на экране одновременно — это уже не
 * объяснение, а поток сообщений.
 */
export function nextHint(state: FirstRunState): Hint | null {
  const seen = new Set(state.seen);
  const rule = RULES.find((r) => !seen.has(r.key) && r.when(state));
  if (!rule) return null;
  // Условие наружу не отдаём: снаружи оно не нужно и только соблазняло бы
  // вызвать его повторно с другим состоянием.
  return { key: rule.key, pose: rule.pose, text: rule.text, ...(rule.action ? { action: rule.action } : {}) };
}

/**
 * Шаги, которые считаются пройденными по данным, а не по нажатию.
 *
 * Тот, кто сфотографировал еду, не увидев подсказки, не должен получить её
 * после. Поэтому при каждой загрузке отмечаем всё, что человек уже сделал, —
 * даже если подсказку он никогда не видел.
 */
export function passedByData(state: FirstRunState): HintKey[] {
  const passed: HintKey[] = [];
  if (state.loggedDays > 0) passed.push("firstMeal");
  if (state.diaryOpened) passed.push("diary");
  if (state.botEverUsed) passed.push("bot");
  if (state.hasWeight) passed.push("weight");
  if (!state.showCalories) passed.push("calories", "ring");
  return passed;
}

/** Шаг в развёрнутом виде — для страницы-шпаргалки. */
export type SheetEntry = {
  key: HintKey;
  pose: MascotPose;
  title: string;
  text: string;
  action?: { label: string; target: HintTarget };
};

/**
 * Все объяснения разом, в том же порядке.
 *
 * Подсказка показывается один раз и исчезает навсегда — это правильно для
 * подсказки и никуда не годится как единственный способ узнать. Вопрос «а где
 * тут неделя» возникает не в первый день, а через месяц, и к тому времени
 * подсказка давно закрыта. Шпаргалка — ответ на него.
 */
export function hintSheet(): SheetEntry[] {
  return RULES.map((rule) => ({
    key: rule.key,
    pose: rule.pose,
    title: rule.sheet.title,
    text: rule.sheet.text,
    ...(rule.action ? { action: rule.action } : {}),
  }));
}

/** Проверка ключа перед записью в базу: снаружи приходит строка. */
export function isHintKey(value: unknown): value is HintKey {
  return typeof value === "string" && (FIRST_RUN_HINTS as readonly string[]).includes(value);
}
