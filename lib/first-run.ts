/**
 * Первые шаги: что Живело объясняет новому человеку и когда.
 *
 * Разбор задачи и три отвергнутых формата — в `docs/first-run.md`. Здесь
 * только правила, и они целиком чистые: состояние приходит снаружи, наружу
 * уходит подсказка или ничего.
 *
 * ## Главное правило: шаги ждут повода, а не идут по расписанию
 *
 * Обычный онбординг показывает пять экранов подряд в первую минуту. Здесь
 * каждый шаг ждёт своего состояния: подсказка про недельный обзор не
 * появится, пока недели нет, а подсказка про первую запись — у того, кто уже
 * записал сорок. Человек, записавший за вечер десять приёмов пищи, пройдёт
 * половину шагов за вечер; записавший один — не увидит ничего лишнего.
 *
 * ## Условие по данным сильнее памяти
 *
 * Отметка «показано» умеет только прятать шаг, но не показывать его. Если
 * условие по данным не выполнено, шага нет, сколько бы раз человек его ни
 * пропускал. Это и есть ответ на вопрос «показывать ли давним
 * пользователям»: да — но только то, что им сейчас впору. Человек без единой
 * записи за месяц находится ровно там же, где новичок.
 *
 * ## Чего здесь нет и не будет
 *
 * Ни «вы должны», ни «не забудьте», ни «обязательно». Ни полоски прогресса
 * обучения, ни «осталось 2 из 8»: это превращает объяснение в задание, а мы
 * обещали обратное. Ни одного шага про вес как цель — шаг про вес объясняет,
 * как на него смотреть, а не зачем его снижать.
 *
 * Правила персонажа из `lib/mascot.ts` действуют и тут. В обучающем тексте
 * их нарушить проще всего: объясняющий тон легко скатывается в требовательный.
 */

import type { MascotPose } from "./mascot.ts";

/** Ключи шагов. Хранятся в базе, поэтому переименование — миграция. */
export const FIRST_RUN_HINTS = [
  "firstMeal",
  "ring",
  "diary",
  "bot",
  "weight",
  "week",
  "calories",
] as const;

export type HintKey = (typeof FIRST_RUN_HINTS)[number];

/**
 * Состояние, по которому решается, что показать.
 *
 * Собирается вызывающей стороной из того, что и так приходит на экран, —
 * отдельных запросов ради подсказок не делаем.
 */
export type FirstRunState = {
  /** Отмеченные пройденными, из `users.first_run_hints`. */
  seen: readonly string[];
  /** Настроен ли план: без него объяснять нечего, человек ещё в анкете. */
  hasPlan: boolean;
  /** Дней с записями всего. */
  loggedDays: number;
  /** Записей за сегодня. */
  mealsToday: number;
  /** Приходило ли хоть раз что-то от бота. */
  botEverUsed: boolean;
  /** Внесён ли вес хоть раз. */
  hasWeight: boolean;
  /** Открывал ли «Дневник» в этой установке. */
  diaryOpened: boolean;
  /** Показаны ли калории — шаг про режим без них имеет смысл только тогда. */
  showCalories: boolean;
};

export type Hint = {
  key: HintKey;
  pose: MascotPose;
  text: string;
  /** Куда ведёт подсказка, если ведёт. Ссылка внутри приложения. */
  action?: { label: string; tab: "camera" | "diary" | "plan" | "profile" };
};

type Rule = Hint & {
  /** Показывать ли сейчас — по данным, не по памяти. */
  when: (s: FirstRunState) => boolean;
};

/**
 * Порядок здесь — это порядок важности, а не расписание. Показывается первый
 * подходящий, остальные ждут своего состояния.
 */
const RULES: Rule[] = [
  {
    key: "firstMeal",
    pose: "calm",
    text: "План готов. Теперь главное — записать, что вы съели. Проще всего сфотографировать.",
    action: { label: "Сфотографировать", tab: "camera" },
    // Ни одной записи за всё время. Тот, у кого они есть, это уже умеет.
    when: (s) => s.hasPlan && s.loggedDays === 0,
  },
  {
    key: "ring",
    pose: "happy",
    text: "Кольцо — это весь день, а не норма, которую надо закрыть. Оно и не должно закрываться каждый раз.",
    // Две записи за день — момент, когда кольцо впервые заметно наполнилось
    // и человек начинает гадать, что значит незакрытое.
    when: (s) => s.mealsToday >= 2 && s.showCalories,
  },
  {
    key: "diary",
    pose: "calm",
    text: "В «Дневнике» лежат все дни. Можно листать назад и дописывать задним числом — вчерашний ужин никуда не делся.",
    action: { label: "Открыть дневник", tab: "diary" },
    // Есть что смотреть, но человек туда ещё не заходил.
    when: (s) => s.loggedDays >= 1 && !s.diaryOpened,
  },
  {
    key: "bot",
    pose: "surprised",
    text: "Снимок можно просто прислать мне в переписку. Разберём вечером, когда будет удобно.",
    // После второго дня: в первый человек занят самим приложением.
    when: (s) => s.loggedDays >= 2 && !s.botEverUsed,
  },
  {
    key: "weight",
    pose: "calm",
    text: "Вес смотрят трендом, а не сегодняшней цифрой. Взвешивайтесь как удобно — усредню я.",
    action: { label: "Внести вес", tab: "plan" },
    when: (s) => s.loggedDays >= 2 && !s.hasWeight,
  },
  {
    key: "week",
    pose: "happy",
    text: "Набралось три дня. На «Плане» появилось, что смотреть за неделю.",
    action: { label: "Посмотреть", tab: "plan" },
    when: (s) => s.loggedDays >= 3,
  },
  {
    key: "calories",
    pose: "calm",
    text: "Калории можно выключить совсем — останутся белок, клетчатка и сами записи. Это в «Профиле».",
    action: { label: "В профиль", tab: "profile" },
    // Самый последний по важности: показываем, когда человек уже освоился,
    // иначе это выглядит как предложение бросить на второй день.
    when: (s) => s.loggedDays >= 5 && s.showCalories,
  },
];

/**
 * Какую подсказку показать сейчас. `null` — нормальный и самый частый исход.
 *
 * Возвращается ровно одна: две подсказки на экране одновременно — это уже не
 * объяснение, а поток сообщений.
 */
export function nextHint(state: FirstRunState): Hint | null {
  const seen = new Set(state.seen);
  const rule = RULES.find((r) => !seen.has(r.key) && r.when(state));
  if (!rule) return null;
  // Условие наружу не отдаём: снаружи оно не нужно и только соблазняло бы
  // вызвать его повторно с другим состоянием.
  return { key: rule.key, pose: rule.pose, text: rule.text, ...(rule.action ? { action: rule.action } : {}) };
}

/**
 * Шаги, которые считаются пройденными по данным, а не по нажатию.
 *
 * Тот, кто сфотографировал еду, не увидев подсказки, не должен получить её
 * после. Поэтому при каждой загрузке отмечаем всё, что человек уже сделал, —
 * даже если подсказку он никогда не видел.
 */
export function passedByData(state: FirstRunState): HintKey[] {
  const passed: HintKey[] = [];
  if (state.loggedDays > 0) passed.push("firstMeal");
  if (state.diaryOpened) passed.push("diary");
  if (state.botEverUsed) passed.push("bot");
  if (state.hasWeight) passed.push("weight");
  if (!state.showCalories) passed.push("calories", "ring");
  return passed;
}

/** Проверка ключа перед записью в базу: снаружи приходит строка. */
export function isHintKey(value: unknown): value is HintKey {
  return typeof value === "string" && (FIRST_RUN_HINTS as readonly string[]).includes(value);
}
