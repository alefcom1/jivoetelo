/**
 * Первые шаги: что Живело объясняет новому человеку и когда.
 *
 * Разбор задачи и три отвергнутых формата — в `docs/first-run.md`. Здесь
 * только правила, и они целиком чистые: состояние приходит снаружи, наружу
 * уходит подсказка или ничего.
 *
 * ## Главное правило: шаги ждут повода, а не идут по расписанию
 *
 * Обычный онбординг показывает пять экранов подряд в первую минуту. Здесь
 * каждый шаг ждёт своего состояния: подсказка про недельный обзор не
 * появится, пока недели нет, а подсказка про первую запись — у того, кто уже
 * записал сорок. Человек, записавший за вечер десять приёмов пищи, пройдёт
 * половину шагов за вечер; записавший один — не увидит ничего лишнего.
 *
 * ## Условие по данным сильнее памяти
 *
 * Отметка «показано» умеет только прятать шаг, но не показывать его. Если
 * условие по данным не выполнено, шага нет, сколько бы раз человек его ни
 * пропускал. Это и есть ответ на вопрос «показывать ли давним
 * пользователям»: да — но только то, что им сейчас впору. Человек без единой
 * записи за месяц находится ровно там же, где новичок.
 *
 * ## Чего здесь нет и не будет
 *
 * Ни «вы должны», ни «не забудьте», ни «обязательно». Ни полоски прогресса
 * обучения, ни «осталось 2 из 8»: это превращает объяснение в задание, а мы
 * обещали обратное. Ни одного шага про вес как цель — шаг про вес объясняет,
 * как на него смотреть, а не зачем его снижать.
 *
 * Правила персонажа из `lib/mascot.ts` действуют и тут. В обучающем тексте
 * их нарушить проще всего: объясняющий тон легко скатывается в требовательный.
 */

import type { MascotPose } from "./mascot.ts";

/** Ключи шагов. Хранятся в базе, поэтому переименование — миграция. */
export const FIRST_RUN_HINTS = [
  "firstMeal",
  "ring",
  "diary",
  "bot",
  "weight",
  "week",
  "calories",
] as const;

export type HintKey = (typeof FIRST_RUN_HINTS)[number];

/**
 * Состояние, по которому решается, что показать.
 *
 * Собирается вызывающей стороной из того, что и так приходит на экран, —
 * отдельных запросов ради подсказок не делаем.
 */
export type FirstRunState = {
  /** Отмеченные пройденными, из `users.first_run_hints`. */
  seen: readonly string[];
  /** Настроен ли план: без него объяснять нечего, человек ещё в анкете. */
  hasPlan: boolean;
  /** Дней с записями всего. */
  loggedDays: number;
  /** Записей за сегодня. */
  mealsToday: number;
  /** Приходило ли хоть раз что-то от бота. */
  botEverUsed: boolean;
  /** Внесён ли вес хоть раз. */
  hasWeight: boolean;
  /** Открывал ли «Дневник» в этой установке. */
  diaryOpened: boolean;
  /** Показаны ли калории — шаг про режим без них имеет смысл только тогда. */
  showCalories: boolean;
};

/**
 * Куда ведёт подсказка.
 *
 * Намерение, а не адрес: в Mini App это вкладка, в вебе — маршрут, и хранить
 * здесь и то и другое означало бы, что модуль знает про обе разметки. Каждая
 * поверхность переводит намерение по-своему.
 */
export type HintTarget = "camera" | "diary" | "week" | "weight" | "profile";

export type Hint = {
  key: HintKey;
  pose: MascotPose;
  text: string;
  action?: { label: string; target: HintTarget };
};

type Rule = Hint & {
  /** Показывать ли сейчас — по данным, не по памяти. */
  when: (s: FirstRunState) => boolean;
  /**
   * Тот же шаг для страницы-шпаргалки: заголовок и полное объяснение.
   *
   * Держится рядом с коротким текстом, а не отдельным файлом, чтобы правка
   * шла в одном месте. Расходящиеся объяснения одного и того же — худший
   * исход: человек читает справку и не узнаёт в ней то, что видел на экране.
   */
  sheet: { title: string; text: string };
};

