export function findDish(slug: string): Dish | undefined {
  return DISHES.find((dish) => dish.slug === slug);
}

/**
 * Соседи по кластеру — блюда той же категории. Перелинковка по типу блюда,
 * а не по алфавиту: человеку, читающему про борщ, интересна солянка, а не
 * блины, оказавшиеся рядом по первой букве.
 */
export function relatedDishes(dish: Dish, limit = 3): Dish[] {
  const sameCategory = DISHES.filter((d) => d.category === dish.category && d.slug !== dish.slug);
  const rest = DISHES.filter((d) => d.category !== dish.category && d.slug !== dish.slug);
  return [...sameCategory, ...rest].slice(0, limit);
}

/** Диапазон на порцию: то, что человек на самом деле съедает. */
export function portionRange(dish: Dish): [number, number] {
  const scale = dish.portionG / 100;
  return [Math.round((dish.kcal[0] * scale) / 5) * 5, Math.round((dish.kcal[1] * scale) / 5) * 5];
}

/**
 * Середина диапазона. Показываем её рядом с границами, а не вместо: точка
 * помогает сориентироваться, границы удерживают от веры в точность, которой
 * нет (тот же принцип, что в расчёте нормы энергии).
 */
export function midpoint(range: [number, number]): number {
  return Math.round((range[0] + range[1]) / 2 / 5) * 5;
}
