// Данные для страниц «сколько калорий в [блюдо]».
//
// Смысл этих страниц — не ещё одна таблица калорийности. Русскоязычные
// таблицы дают одно число с точностью до единицы: «борщ — 49 ккал». Это
// неправда не потому, что цифра плохая, а потому, что борща вообще не
// существует — есть постный борщ у одного человека и борщ на говяжьей
// грудинке со сметаной у другого, и между ними разница втрое. Точное число
// скрывает главное: от чего оно зависит.
//
// Поэтому у каждого блюда здесь диапазон и список того, что двигает цифру
// внутри него. Диапазон — это не «мы не знаем», а «вот в каких пределах
// живёт настоящий ответ, и вот почему».
//
// Откуда числа. Диапазоны собраны по типовым рецептурам блюда: берутся
// распространённые варианты приготовления, для каждого считается состав по
// ингредиентам, границами становятся самый лёгкий и самый сытный из
// массовых вариантов. Экзотические версии в диапазон не входят — иначе он
// растянулся бы так, что перестал бы что-либо значить.

export type DishCategory = "supy" | "vtorye" | "salaty" | "zavtraki" | "vypechka" | "fastfud";

export type Dish = {
  slug: string;
  /** Именительный падеж с заглавной: заголовки и списки. */
  name: string;
  /**
   * Предложный падеж целиком, вместе с предлогом: «в борще», «в оливье».
   * Хранится готовой строкой, а не склоняется правилом, — русские падежи
   * правилу не поддаются, а ошибка в заголовке видна каждому посетителю.
   */
  inDish: string;
  category: DishCategory;
  /** Килокалории на 100 г: нижняя и верхняя границы типовых рецептур. */
  kcal: [number, number];
  protein: [number, number];
  fat: [number, number];
  carbs: [number, number];
  /** Обычная порция и как она выглядит по-человечески. */
  portionG: number;
  portionLabel: string;
  /** Одна фраза: что это за блюдо с точки зрения расчёта. */
  summary: string;
  /** Что двигает цифру внутри диапазона. Ради этого страница и существует. */
  drivers: string[];
  /** Крайние варианты одного блюда — нагляднее любого объяснения. */
  variants: Array<{ label: string; kcal: number; note: string }>;
  /**
   * Дата последней содержательной правки страницы, `ГГГГ-ММ-ДД`.
   *
   * Не задана у большинства блюд — тогда берётся общая дата каталога. Своя
   * нужна тем, чьи числа или текст правились отдельно: карта сайта обязана
   * показывать дату содержимого, а не дату сборки.
   */
  updatedAt?: string;
};

/**
 * Общая дата каталога — для блюд без собственной.
 *
 * Раньше карта сайта подставляла страницам блюд `LEGAL_UPDATED_AT` — дату
 * правки оферты. Правка юридического документа не имеет никакого отношения к
 * содержимому страницы борща, и поисковик, которому раз за разом показывают
 * несуществующие изменения, перестаёт верить этому полю.
 */
export const DISHES_UPDATED_AT = "2026-08-03";

export function dishUpdatedAt(dish: Dish): Date {
  return new Date(dish.updatedAt ?? DISHES_UPDATED_AT);
}

