/**
 * Что делать с числом, которое модель прочитала на весах.
 *
 * ## Почему распознавание никогда не сохраняет само
 *
 * Семисегментный индикатор — худший в мире шрифт для распознавания: 8 без
 * одного сегмента становится 0, 6 или 9, а точка между целыми и десятыми на
 * тёмном стекле под бликом видна хуже всех символов сразу. Ошибка в разряде
 * десятков — это десять килограммов, и она не выглядит ошибкой: 80,2 и 90,2
 * одинаково правдоподобны.
 *
 * Цена такой ошибки здесь выше, чем кажется. Вес не просто показывается: по
 * его тренду считается адаптивная поправка плана (lib/adjustment.ts), и один
 * фантомный замер тянет за собой пересчёт нормы. Человек увидит не «неверную
 * цифру в списке», а изменившийся план — и не свяжет одно с другим.
 *
 * Поэтому распознавание здесь предлагает, а записывает человек. Число
 * подставляется в то же поле, куда его вводят руками, и сохраняется той же
 * кнопкой. Разница с ручным вводом ровно одна: не надо набирать.
 *
 * ## Что проверяется до показа
 *
 * Диапазон (те же 30–300 кг, что и у ручного ввода) и расхождение с прошлым
 * замером. Второе ловит как раз ошибку в разряде десятков: за неделю человек
 * не меняется на десять килограммов, а вот 8 в 9 модель перепутать может.
 * Предупреждение не запрещает сохранить — оно называет прошлый вес и даёт
 * сравнить.
 */

/** Границы ручного ввода — распознанному числу верим не больше, чем набранному. */
export const MIN_KG = 30;
export const MAX_KG = 300;

/**
 * Расхождение с прошлым замером, после которого стоит переспросить.
 *
 * Пять килограммов: суточные колебания воды укладываются в два, месячное
 * снижение при обычном темпе — в три-четыре. А вот ошибка в разряде десятков
 * даёт минимум десять и всегда попадёт под порог.
 */
export const BIG_JUMP_KG = 5;

export type ScaleUnit = "kg" | "lb" | "st";

/** Что вернула модель, до всякой проверки. */
export type RawScaleReading = {
  /** Число, как оно написано на индикаторе, — в единицах `unit`. */
  reading: number | null;
  unit: ScaleUnit | null;
  confidence: "high" | "medium" | "low";
  /** Почему не прочиталось, если не прочиталось. */
  problem: "no_display" | "unreadable" | "not_weight" | null;
};

export type ScaleVerdict =
  /** Число прочитано и правдоподобно. `warning` — повод посмотреть внимательнее. */
  | { kind: "read"; weightKg: number; warning: string | null; converted: ScaleUnit | null }
  /** Прочитать не вышло. Дальше — обычный ручной ввод. */
  | { kind: "rejected"; message: string };

/** Коэффициенты перевода. Точные, а не округлённые: округляем один раз, в конце. */
const TO_KG: Record<ScaleUnit, number> = {
  kg: 1,
  lb: 0.45359237,
  st: 6.35029318,
};

const UNIT_NAMES: Record<ScaleUnit, string> = { kg: "килограммах", lb: "фунтах", st: "стоунах" };

/** Килограммы с одним знаком после запятой — шаг ввода и шаг любых бытовых весов. */
export function toKilograms(reading: number, unit: ScaleUnit): number {
  return Math.round(reading * TO_KG[unit] * 10) / 10;
}

/**
 * Решение по прочитанному числу.
 *
 * `lastKg` — прошлый замер, если он есть. Без него сравнивать не с чем, и
 * это нормально: у первого замера никакого «было» не существует.
 */
export function judgeReading(raw: RawScaleReading, lastKg: number | null): ScaleVerdict {
  if (raw.problem === "no_display" || raw.reading === null || raw.unit === null) {
    return {
      kind: "rejected",
      message: "Не вижу на снимке показаний весов. Попробуйте снять индикатор поближе — или введите вес числом.",
    };
  }
  if (raw.problem === "not_weight") {
    return {
      kind: "rejected",
      message: "На индикаторе не вес — возможно, весы показывают что-то другое. Дождитесь числа и снимите ещё раз.",
    };
  }
  if (raw.problem === "unreadable") {
    return {
      kind: "rejected",
      message: "Цифры на снимке не разобрать: мешает блик или размытие. Второй кадр обычно выходит лучше.",
    };
  }
  if (!Number.isFinite(raw.reading)) {
    return { kind: "rejected", message: "Не получилось прочитать число. Введите вес вручную." };
  }

  const weightKg = toKilograms(raw.reading, raw.unit);
  if (weightKg < MIN_KG || weightKg > MAX_KG) {
    return {
      kind: "rejected",
      // Число называем: человек сразу видит, что именно прочиталось не так, —
      // «8,2» вместо «82,5» объясняет отказ лучше любой формулировки.
      message: `Прочиталось ${fmt(weightKg)} кг — это вне рабочего диапазона. Проверьте кадр или введите вес числом.`,
    };
  }

  const warnings: string[] = [];
  // Не килограммы — говорим об этом всегда, даже при уверенном разборе:
  // человек должен знать, что число на экране и число на весах разные.
  const converted = raw.unit === "kg" ? null : raw.unit;
  if (converted) {
    warnings.push(`Весы показывают в ${UNIT_NAMES[converted]} — перевела в килограммы.`);
  }
  if (lastKg !== null && Math.abs(weightKg - lastKg) > BIG_JUMP_KG) {
    warnings.push(`Прошлый замер был ${fmt(lastKg)} кг — расхождение большое, стоит взглянуть на число.`);
  } else if (raw.confidence === "low") {
    // Только когда расхождения нет: два предупреждения подряд об одном
    // числе читаются как «не доверяй ничему», и человек перестаёт читать оба.
    warnings.push("В цифрах я не уверена — сверьте с индикатором.");
  }

  return { kind: "read", weightKg, warning: warnings.length > 0 ? warnings.join(" ") : null, converted };
}

/** Русская запись: десятые через запятую, целое — без хвоста. */
function fmt(value: number): string {
  return (Math.round(value * 10) / 10).toString().replace(".", ",");
}
