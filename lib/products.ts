function build(): Product[] {
  const byName = new Map(FOOD_REFERENCE.map((food) => [food.name, food]));
  const products: Product[] = [];

  for (const [name, meta] of Object.entries(PRODUCT_META)) {
    const food = byName.get(name);
    // Молча пропустить — значит однажды потерять страницу из-за переименования
    // в справочнике и не заметить. Тест на это есть, но и здесь не притворяемся.
    if (!food) continue;
    products.push({ ...food, ...meta });
  }

  return products.sort((a, b) => a.name.localeCompare(b.name, "ru"));
}

export const PRODUCTS: Product[] = build();

/** Имена, для которых заведена карточка каталога, — для теста связности. */
export const PRODUCT_META_NAMES = Object.keys(PRODUCT_META);

export function findProduct(slug: string): Product | undefined {
  return PRODUCTS.find((product) => product.slug === slug);
}

/** Калорийность порции, округлённая до целого: дробные ккал никому не нужны. */
export function kcalFor(product: Pick<Product, "kcal">, grams: number): number {
  return Math.round((product.kcal * grams) / 100);
}

/**
 * Сколько получится готового из заданного веса сухого — и наоборот.
 * Возвращает `null` там, где вопрос не имеет смысла (яблоко не варят).
 */
export function cookedFromRaw(product: Product, rawGrams: number): number | null {
  return product.raw ? Math.round(rawGrams * product.raw.ratio) : null;
}

export function rawFromCooked(product: Product, cookedGrams: number): number | null {
  return product.raw ? Math.round(cookedGrams / product.raw.ratio) : null;
}
