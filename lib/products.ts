// Каталог продуктов: публичное лицо той же базы, которой пользуется приложение.
//
// Числа сюда не переписываются — они берутся из `lib/food-reference.ts`, того
// же массива, по которому ищет «Собрать руками» в мини-аппе. Две копии одного
// состава разошлись бы на первой же правке, и разошлись бы молча.
//
// Здесь добавляется то, что нужно странице и не нужно приложению: падеж для
// заголовка, бытовые меры, сухой вид крупы, что двигает цифру, связь с
// блюдами.
//
// Чего в каталоге намеренно нет — диапазона на всё подряд. У борща диапазон
// честен, потому что борща не существует: постный и на грудинке различаются
// втрое. У «творога 5%» жирность стоит в названии, и рисовать там
// неопределённость значило бы изображать незнание, которого нет. Мы против
// ложной точности, а не против точности.

import { FOOD_REFERENCE, type ReferenceFood } from "./food-reference.ts";

/** Бытовая мера — для случая, когда весов нет, а он основной. */
export type HouseholdMeasure = { label: string; grams: number };

/**
 * Состав в сухом виде и во сколько раз продукт прибавляет в весе при варке.
 *
 * Ради этого поля половина каталога и затевалась. Крупы у нас даны
 * отварными (так их и взвешивают дома), а ищут их часто по сухим числам:
 * сухая гречка — 340 ккал, отварная — 110. Человек, взявший не ту цифру,
 * ошибается втрое, и никто в рунете этот вопрос системно не закрывает.
 */
export type RawForm = {
  kcal: number;
  protein: number;
  fat: number;
  carbs: number;
  fiber: number;
  /** Во сколько раз растёт вес: 100 г сухой гречки → ~300 г готовой. */
  ratio: number;
};

export type ProductMeta = {
  slug: string;
  /**
   * Предложный падеж целиком, с предлогом: «в твороге 5%», «в гречке».
   * Готовой строкой, а не правилом, — по той же причине, что и у блюд:
   * русские падежи правилу не поддаются, а ошибка в заголовке видна всем.
   */
  inProduct: string;
  household: HouseholdMeasure[];
  raw?: RawForm;
  /** Что двигает цифру. Ради этого страница и существует. */
  drivers: string[];
  /** Блюда, где продукт заметен, — перелинковка с `/skolko-kalorij`. */
  dishSlugs: string[];
};

export type Product = ReferenceFood & ProductMeta;

