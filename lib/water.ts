/**
 * Норма воды в день — и почему привычная формула её завышает.
 *
 * ## Что не так с «30 мл на килограмм»
 *
 * Эта формула заполнила всю русскую выдачу, но у неё нет источника: ни ВОЗ,
 * ни EFSA, ни отечественные методические рекомендации такого правила не
 * дают. Она удобна тем, что даёт число, и вредна тем же — число выглядит
 * точным и не учитывает главного.
 *
 * ## На чём считаем мы
 *
 * EFSA (2010) определяет **адекватное потребление всей воды**: 2,0 л в сутки
 * для женщин и 2,5 л для мужчин при умеренной активности и умеренном
 * климате. Ключевое слово — «всей»: сюда входит вода из еды, а это в
 * обычном рационе 20–30% от общего объёма. То есть напитками нужно закрыть
 * не 2 литра, а примерно 1,5.
 *
 * Поэтому калькулятор считает две величины: общую воду и ту её часть,
 * которую надо выпить. Разницу — воду из еды — показываем отдельной строкой,
 * иначе человек будет добирать её сверх и удивляться, почему «не лезет».
 *
 * Масса тела в расчёте всё же участвует: потребность растёт вместе с
 * расходом энергии, и у человека 50 кг она объективно ниже, чем у 100 кг.
 * Берём поправку через энергию, а не «мл на кг»: 1 мл воды на 1 ккал
 * суточного расхода — старое правило института медицины США, и оно хотя бы
 * имеет физиологический смысл.
 */

export type WaterInput = {
  sex: "female" | "male";
  weightKg: number;
  /** Расход энергии за сутки, ккал. Если не знаем — оценим по весу. */
  tdeeKcal?: number;
  /** Дополнительные часы физической нагрузки в этот день. */
  activeHours?: number;
  /** Жаркая погода или жаркое помещение. */
  hot?: boolean;
};

export type WaterResult = {
  /** Вся вода за сутки, мл: напитки плюс вода из еды. */
  totalMl: number;
  /** Сколько выпить напитками, мл. */
  drinkMl: number;
  /** Сколько придёт с едой, мл. */
  fromFoodMl: number;
  /** Прибавка за нагрузку и жару, мл — чтобы показать её отдельной строкой. */
  extraMl: number;
  /** Стаканов по 250 мл — так проще примерить на день. */
  glasses: number;
};

/** Базовое адекватное потребление всей воды, мл (EFSA, 2010). */
const BASE_TOTAL: Record<WaterInput["sex"], number> = { female: 2000, male: 2500 };

/** Доля воды, приходящая с едой, от общего объёма. */
export const FOOD_WATER_SHARE = 0.25;

/** Прибавка на час заметной физической нагрузки, мл. */
const PER_ACTIVE_HOUR = 500;

/** Прибавка за жару, мл. */
const HOT_WEATHER = 500;

/** Объём стакана, мл — им меряют норму в быту. */
export const GLASS_ML = 250;

export function computeWater(input: WaterInput): WaterResult {
  const base = BASE_TOTAL[input.sex];

  // Поправка на массу: 1 мл на 1 ккал расхода. Отклонение от «среднего»
  // расхода 2000 ккал переводим в миллилитры и добавляем к базе.
  const tdee = input.tdeeKcal ?? estimateTdee(input.weightKg, input.sex);
  const byEnergy = Math.round((tdee - 2000) * 0.5);

  const extra =
    Math.max(0, Math.round((input.activeHours ?? 0) * PER_ACTIVE_HOUR)) + (input.hot ? HOT_WEATHER : 0);

  const total = Math.max(1200, base + byEnergy + extra);
  const fromFood = Math.round(total * FOOD_WATER_SHARE);
  const drink = total - fromFood;

  return {
    totalMl: round50(total),
    drinkMl: round50(drink),
    fromFoodMl: round50(fromFood),
    extraMl: extra,
    glasses: Math.round(drink / GLASS_ML),
  };
}

/**
 * Грубая оценка расхода, если человек не считал его калькулятором: 30 ккал
 * на килограмм у женщин, 33 у мужчин. Нужна только чтобы поправка на массу
 * работала, когда точного расхода нет.
 */
function estimateTdee(weightKg: number, sex: WaterInput["sex"]): number {
  const perKg = sex === "female" ? 30 : 33;
  return Math.max(1200, Math.round(weightKg * perKg));
}

/** Округление до полусотни: обещать воду с точностью до миллилитра глупо. */
function round50(ml: number): number {
  return Math.round(ml / 50) * 50;
}

