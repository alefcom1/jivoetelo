/**
 * Монограмма: буква и цвет вместо фото профиля.
 *
 * Не заглушка. Фото ставит меньшинство — это шаг, который делают, только
 * если зачем-то нужно; а серый круг с силуэтом не даёт ничего. Буква и тон,
 * выведенные из адреса почты, дают узнавание без единого запроса наружу и у
 * каждого человека свои.
 *
 * Отдельным модулем в lib, а не рядом с рисовкой в app/avatar.tsx: обе
 * функции чистые, их сверяет тест, а Node не исполняет .tsx. Заодно правило
 * «одинаковый аватар во всех наших экранах» становится одним местом на
 * кабинет, Mini App и всё, что появится потом.
 */

/**
 * Устойчивый оттенок. Одна и та же почта — всегда один и тот же цвет, на
 * любом устройстве и после любой перезагрузки: цвет здесь часть узнавания, и
 * меняться ему нельзя. Отсюда простая свёртка, а не хеш со случайной солью.
 */
export function monogramHue(source: string | null): number {
  let sum = 0;
  for (const char of source ?? "") sum = (sum + char.charCodeAt(0) * 31) % 360;
  return sum;
}

/**
 * Первая буква адреса. «Ж» — для аккаунта из Mini App, где почты нет вовсе:
 * пустой круг читался бы как ошибка загрузки, а не как «фото не поставили».
 */
export function monogramLetter(source: string | null): string {
  return ((source ?? "").trim()[0] ?? "Ж").toUpperCase();
}
