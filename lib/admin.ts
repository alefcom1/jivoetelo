/**
 * Права администратора.
 *
 * ## Почему переменная окружения, а не флаг в базе
 *
 * Можно было бы завести `users.isAdmin` и проверять его как любое другое
 * поле. Мы делаем иначе: админ — это адрес, перечисленный в переменной
 * окружения `ADMIN_EMAILS` (через запятую), а не запись в таблице.
 *
 * Причина в том, чем отличаются способы получить это право по ошибке.
 * Флаг в базе можно выставить случайно: дефектом в чужом интерфейсе,
 * неосторожным запросом в консоли, багом в миграции, восстановлением дампа
 * не той версии. Всё это — обычные пути данных, которыми ежедневно ходит
 * приложение. Переменную окружения так не подставишь: её видит и меняет
 * только тот, у кого есть доступ к серверу или деплою, а изменение требует
 * перезапуска процесса, а не одного HTTP-запроса, дошедшего до нужного
 * хэндлера. Плата за это — права нельзя выдать прямо из интерфейса, только
 * через деплой. Для пилотной группы админов (нас самих) это разумный обмен.
 */

import type { CurrentUser } from "./auth.ts";

/**
 * Разбирает `ADMIN_EMAILS`: режет по запятой, обрезает пробелы по краям,
 * приводит к нижнему регистру, выбрасывает пустые куски.
 *
 * Выбрасывать пустые куски обязательно: иначе лишняя запятая или пробел в
 * переменной ("a@x.com,,b@y.com" или просто ",") превратились бы в пустую
 * строку в списке, а `isAdminEmail("", raw)` — в способ пройти проверку,
 * если где-то по ошибке сравнивается пустой email.
 *
 * Чистая функция: ни базы, ни `process.env` внутри. Это то, что тестируется
 * без поднятия чего бы то ни было — см. `tests/admin.test.mjs`.
 */
export function parseAdminEmails(raw: string | undefined): string[] {
  if (!raw) return [];
  return raw
    .split(",")
    .map((piece) => piece.trim().toLowerCase())
    .filter((piece) => piece.length > 0);
}

/**
 * Является ли `email` администратором согласно значению `raw`
 * (сырому значению `ADMIN_EMAILS`).
 *
 * Ключевое правило: пустой или не заданный `raw` означает «админов нет
 * вообще», а не «пускать всех». Список из `parseAdminEmails` в этом случае
 * пуст, а пустой список не совпадает ни с одним адресом — в том числе с
 * пустой строкой, которая теоретически могла бы прийти как `email`.
 */
export function isAdminEmail(email: string, raw: string | undefined): boolean {
  const admins = parseAdminEmails(raw);
  if (admins.length === 0) return false;
  const normalized = email.trim().toLowerCase();
  return admins.includes(normalized);
}

/**
 * Текущий пользователь, если он администратор согласно `ADMIN_EMAILS`,
 * иначе `null`. Используется на входе в каждую страницу и каждое действие
 * админки — см. `app/admin/layout.tsx` и `app/admin/actions.ts`.
 *
 * `getCurrentUser` импортируется лениво, внутри функции, а не в начале
 * модуля. Он тянет за собой обращение к БД и к `next/headers`, и обычный
 * импорт наверху сделал бы весь `lib/admin.ts` неимпортируемым в обычном
 * node без Next.js и без базы — а значит, непроверяемым тестом. Чистая
 * часть модуля (`parseAdminEmails`, `isAdminEmail`) от того, что делает
 * `requireAdmin`, зависеть не должна, и ленивый импорт это гарантирует:
 * пока `requireAdmin` не вызвана, `./auth.ts` не загружается вовсе.
 */
export async function requireAdmin(): Promise<{ id: number; email: string } | null> {
  const { getCurrentUser } = await import("./auth.ts");
  const user: CurrentUser | null = await getCurrentUser();
  if (!user) return null;
  if (!isAdminEmail(user.email, process.env.ADMIN_EMAILS)) return null;
  return { id: user.id, email: user.email };
}
