/**
 * Сколько месяцев показывает срез.
 *
 * Отдельным крошечным модулем, а не константой в lib/season.ts: на него
 * ссылается таблица вех в lib/streak.ts, а та не должна тянуть за собой весь
 * разбор месяцев. Правило в этом репозитории общее — у каждой вехи в
 * комментарии стоит модуль, который делает её обещание правдой, и модуль
 * должен быть маленьким и очевидным.
 *
 * Окно растёт вместе с человеком: сам срез появляется, как только наберётся
 * два сравнимых месяца, но охватить год он может только у того, кто год вёл.
 */
export function seasonWindow(totalDays: number): 3 | 6 | 12 {
  if (totalDays >= 365) return 12;
  if (totalDays >= 180) return 6;
  return 3;
}
