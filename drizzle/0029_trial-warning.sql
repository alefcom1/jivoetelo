-- Отметка о предупреждении про конец пробного месяца.
--
-- До этого человек узнавал о конце пробного месяца в момент отказа: навёл
-- камеру на обед, нажал «Разобрать» и получил «пробный месяц закончился».
-- Сервис молчал тридцать дней, а потом поставил перед фактом ровно тогда,
-- когда человек занят другим.
--
-- Колонка, а не вычисление на лету: сообщение одноразовое, и «отправляли ли
-- уже» неоткуда узнать, кроме как записав. Дата, а не флаг, — по той же
-- причине, что у соседей: по ней видно, когда именно предупредили, и это
-- первое, что спрашивают, если человек говорит «мне не приходило».
--
-- Запись даты здесь тоже захват права на отправку, а не отчёт о ней: пишем ДО
-- отправки, и второй процесс уходит ни с чем. Потерять сообщение при
-- перезапуске не страшно, отправить второе — неприятно.
ALTER TABLE bot_preferences ADD COLUMN IF NOT EXISTS trial_warning_on date;
