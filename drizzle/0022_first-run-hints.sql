-- Первые шаги: какие объяснения человек уже прошёл.
--
-- Массив ключей, а не столбец на каждый шаг: шагов семь, и каждый новый
-- иначе стоил бы миграции. Сам список ключей живёт в lib/first-run.ts, там же
-- проверка перед записью — в базу попадает только известное значение.
--
-- Почему не отдельная таблица. Связей у шагов нет, порядок не важен,
-- количество измеряется единицами; таблица ради этого дала бы соединение на
-- каждую загрузку «Сегодня» и ничего взамен.
--
-- Пустой массив по умолчанию, а не NULL: код читает его как список, и
-- отсутствие шагов — это пустой список, а не «неизвестно». Существующим
-- пользователям он тоже достанется пустым, и это правильно: подсказки они
-- увидят те, чьи условия по данным выполнены, а условия у давнего
-- пользователя выполнены редко (lib/first-run.ts, passedByData).
ALTER TABLE "users" ADD COLUMN IF NOT EXISTS "first_run_hints" jsonb DEFAULT '[]'::jsonb NOT NULL;
