-- Упрощённый режим учёта.
--
-- Приём пищи записывается качественно — что было на тарелке и сколько её
-- было, — без чисел вовсе. Упрощённый самомониторинг даёт приверженность
-- 97% против 49% при той же потере веса на шести месяцах
-- (docs/research-2026-08.md, раздел 7.4).
--
-- Отдельный флаг, а не значение внутри show_calories: это разные вещи.
-- show_calories убирает цифры с экрана, оставляя полный ввод; simple_mode
-- упрощает саму работу. Человек может хотеть одно без другого — например,
-- видеть калории, но не набирать состав руками.
ALTER TABLE users ADD COLUMN IF NOT EXISTS simple_mode boolean NOT NULL DEFAULT false;
