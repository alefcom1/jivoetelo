-- Голосовые в инбоксе.
--
-- До этого в инбоксе жили только снимки, и photo_key был обязателен. Теперь
-- туда же попадает расшифрованное голосовое: у него нет файла, а всё
-- содержимое — текст, который человек сказал вслух. Он ложится в уже
-- существующий note, где раньше лежала подпись к фото: и то и другое —
-- «что человек сообщил про эту еду словами», и разбор с ними работает
-- одинаково.
--
-- Отдельного столбца-признака нет намеренно: photo_key IS NULL и есть
-- признак. Столбец, который всегда выводится из другого, рано или поздно
-- с ним разойдётся.
ALTER TABLE photo_inbox ALTER COLUMN photo_key DROP NOT NULL;

-- Запись без файла и без слов разобрать нечем: это строка, которая навсегда
-- останется в инбоксе и будет мозолить глаза счётчиком «ждут разбора».
--
-- Через DO, а не ADD CONSTRAINT напрямую: у табличных ограничений нет
-- IF NOT EXISTS, а миграции здесь принято писать повторяемыми — упавший
-- посреди дела деплой не должен превращаться в ручную работу.
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'photo_inbox_has_content') THEN
    ALTER TABLE photo_inbox ADD CONSTRAINT photo_inbox_has_content
      CHECK (photo_key IS NOT NULL OR note IS NOT NULL);
  END IF;
END $$;
