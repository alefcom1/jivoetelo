-- Банк снимков: кандидаты вместо пустой очереди.
--
-- Очередь модерации была пуста не из-за ошибки. Единственный путь в неё вёл
-- из карточки приёма пищи: найти запись, выбрать продукт, поставить галочку
-- согласия, отправить. Четыре шага ради того, чтобы отдать сервису свою
-- фотографию, — и их не делал никто. Каталог остался без снимков, а именно
-- снимки были тем, чего нет ни у одного конкурента.
--
-- Теперь модератор видит все снимки дневников как кандидатов и предлагает
-- публикацию сам. Два новых поля обслуживают этот путь.

-- Запрет предлагать публикацию. По умолчанию `false` — снимок можно
-- ПРЕДЛОЖИТЬ к публикации; сама публикация по-прежнему требует ответа «да»
-- (152-ФЗ, ст. 10.1 ч. 8: молчание согласием не считается).
ALTER TABLE users
  ADD COLUMN IF NOT EXISTS photo_offers_opt_out boolean NOT NULL DEFAULT false;

-- Кто предложил снимок и когда. `null` у строк, которые автор отправил сам
-- из карточки записи: старый путь остаётся рабочим.
ALTER TABLE catalog_photos
  ADD COLUMN IF NOT EXISTS offered_by integer REFERENCES users(id) ON DELETE SET NULL;
ALTER TABLE catalog_photos
  ADD COLUMN IF NOT EXISTS offered_at timestamptz;

-- `consent_version` обязателен, а у предложенного снимка согласия ещё нет:
-- оно появится, когда автор ответит. Пустая строка была бы враньём в поле,
-- по которому через год отвечают «на что человек соглашался».
ALTER TABLE catalog_photos ALTER COLUMN consent_version DROP NOT NULL;

-- Быстрый ответ на «этот снимок уже предлагали?» — очередь кандидатов
-- обходит все снимки дневника и обязана отсеивать показанные.
CREATE INDEX IF NOT EXISTS catalog_photos_key ON catalog_photos (photo_key);
