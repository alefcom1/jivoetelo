-- Своя норма калорий вместо расчётной.
--
-- Норму человеку может назначить врач или тренер, и тогда наша формула —
-- помеха, а не помощь: Миффлин–Сан Жеор не знает ни диагноза, ни истории, ни
-- того, что решено делать дальше. До этой колонки переопределить расчёт было
-- нечем, и такому человеку оставалось либо жить с чужим числом на экране,
-- либо не пользоваться сервисом.
--
-- Nullable, и это законное состояние, а не пропуск: у подавляющего
-- большинства своей нормы нет и не будет. NULL означает «считай по формуле».
--
-- Не путать с kcal_adjustment: та — накопленная адаптивная поправка, которую
-- сервис предлагает сам по записям дневника (раздел 14.2), и она правит
-- расчёт. Эта колонка расчёт отменяет. Обе могут быть заполнены
-- одновременно — тогда adjustment просто не участвует, см. lib/targets.ts.
--
-- Нижняя граница безопасности (1200/1500 ккал) применяется и к этому числу.
-- Проверять её в базе не пытаемся: она зависит от пола из соседней колонки,
-- а такое ограничение пришлось бы менять вместе с правилом. Место правила —
-- в lib/targets.ts, где оно уже есть и покрыто тестами.
ALTER TABLE profiles ADD COLUMN IF NOT EXISTS kcal_override integer;
