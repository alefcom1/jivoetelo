-- Специалист заводит кабинет сам.
--
-- До этого путь был один: анкета из семи полей на /pro → строка в
-- `pro_applications` → человек читает → руками заводит `specialists`. Между
-- «хочу работать» и «работаю» стояли сутки ожидания и наша очередь.
--
-- Почему это можно открыть без предварительной проверки: **кабинет сам по
-- себе не открывает ни одного байта чужих данных**. Он позволяет выдать код.
-- Код показывает клиенту экран согласия. Что именно откроется — решает
-- клиент, по каждому разделу отдельно, и отзывает в один клик. Настоящая
-- дверь охраняется `canAccess` (lib/pro/access.ts) и стоит у клиента, а не у
-- нас; предварительная проверка сторожила прихожую.
--
-- Что проверка всё-таки давала — уверенность клиента, что за именем стоит
-- реальная практика. Это остаётся, но становится отметкой, а не воротами.

-- Когда специалиста подтвердил человек. `null` — зарегистрировался сам и
-- проверку не проходил. Клиенту это показывается прямо на экране согласия:
-- имя специалист указал себе сам, и делать вид, что мы его проверили, нельзя.
ALTER TABLE specialists
  ADD COLUMN IF NOT EXISTS verified_at timestamptz;

-- Уже заведённые руками — проверенные по определению: их заводили после
-- разговора. Условие по `approved_at`, а не по всем подряд: строка со
-- статусом `pending` подтверждения как раз и не проходила.
UPDATE specialists SET verified_at = approved_at WHERE approved_at IS NOT NULL AND verified_at IS NULL;
