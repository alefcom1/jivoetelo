-- Журнал выпитого: одна строка на глоток.
--
-- Почему журнал, а не сумма за день в одной строке. У веса измерение за день
-- одно, и upsert по (user, date) в weight_entries честен: новое взвешивание
-- заменяет старое. Жидкость набирается весь день по чашке, и сумма — это
-- следствие записей, а не сама запись.
--
-- Журнал даёт даром то, чего накопительная сумма не даёт: отмену последней
-- записи. Промахнулись кнопкой — убираем ровно последний глоток, а не просим
-- человека вычесть 250 самому. Для быстрых кнопок это не украшение: по ним
-- промахиваются, и без отмены единственным выходом было бы «оставьте как
-- есть».
--
-- on_date — тот же «локальный день пользователя», что и meals.eaten_on: день
-- группируется по тому, который человек видел на своих часах, без пересчёта
-- часовых поясов.
CREATE TABLE IF NOT EXISTS water_entries (
  id serial PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  on_date date NOT NULL,
  -- Миллилитры целым числом: обещать жидкость с точностью до десятых доль
  -- миллилитра — та же псевдоточность, против которой заведён сам расчёт
  -- нормы (lib/water.ts).
  ml integer NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- Единственный частый вопрос к таблице — «сколько за этот день у этого
-- человека». Он же обслуживает отмену: последняя запись ищется тем же ключом.
CREATE INDEX IF NOT EXISTS water_entries_user_date ON water_entries (user_id, on_date);
