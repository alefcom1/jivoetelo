import test from "node:test";
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";

/**
 * Словарь для распознавания речи (scripts/speech-grammar.mjs).
 *
 * Смысл словаря в том, что маленькая модель, которой не дают выбирать из
 * всего русского языка, ошибается заметно реже. Но выигрыш держится ровно до
 * тех пор, пока в словаре есть все слова фразы: недостающее слово в
 * ограниченном распознавании ломает не себя, а всю фразу целиком.
 *
 * Поэтому тест проверяет не «словарь непустой», а покрытие настоящих фраз —
 * тех, какими люди диктуют еду.
 */

const GRAMMAR = JSON.parse(
  execFileSync("node", ["scripts/speech-grammar.mjs"], { encoding: "utf8", maxBuffer: 8 * 1024 * 1024 }),
);

/** Как это звучит вслух. Падежи здесь не украшение — так и говорят. */
const PHRASES = [
  "овсянка на воде двести грамм и банан",
  "куриная грудка сто пятьдесят грамм с гречкой",
  "два сырника и ложка сметаны",
  "борщ тарелка и кусок хлеба",
  "творог пять процентов сто восемьдесят грамм",
  "яблоко и горсть миндаля",
  "тарелка гречки с курицей",
  "салат из огурцов и помидоров",
  "кофе с молоком без сахара",
  "три яйца и кусок ржаного хлеба",
  "стакан кефира и половина банана",
  "суп куриный с лапшой и хлеб",
];

test("типовые фразы покрыты словарём целиком", () => {
  const failures = [];
  for (const phrase of PHRASES) {
    const missing = phrase.split(" ").filter((word) => !GRAMMAR.includes(word));
    if (missing.length > 0) failures.push(`«${phrase}» — нет: ${missing.join(", ")}`);
  }
  assert.deepEqual(failures, [], `недостающее слово ломает всю фразу, а не себя:\n${failures.join("\n")}`);
});

test("числительные и единицы на месте", () => {
  // Вес человек называет всегда. Без числительных словарь бесполезен, каким
  // бы полным ни был список еды.
  for (const word of ["сто", "двести", "пятьдесят", "полтора", "грамм", "граммов", "ложка", "штук"]) {
    assert.ok(GRAMMAR.includes(word), `нет слова «${word}»`);
  }
});

test("словарь остаётся маленьким", () => {
  // Не эстетика: Vosk строит по словарю граф распознавания, и с ростом
  // словаря выигрыш в точности тает — а вместе с ним и смысл всей затеи.
  // Десять тысяч — граница, за которой ограничение перестаёт ограничивать.
  assert.ok(GRAMMAR.length < 10000, `слов ${GRAMMAR.length} — словарь перестал быть узким`);
  assert.ok(GRAMMAR.length > 1500, `слов всего ${GRAMMAR.length} — похоже, склонение отвалилось`);
});

test("в словаре только слова", () => {
  // Цифры, знаки и латиница в грамматике Vosk не распознаются никогда и
  // только раздувают граф: «3,2%» звучит как «три и два».
  for (const word of GRAMMAR) {
    assert.match(word, /^[а-яё-]+$/, `не слово: ${JSON.stringify(word)}`);
  }
});

test("повторов нет", () => {
  assert.equal(new Set(GRAMMAR).size, GRAMMAR.length);
});

test("словарь отсортирован — чтобы правки читались диффом", () => {
  // Без сортировки каждое пополнение справочника давало бы перемешанный
  // файл, и увидеть в нём одно новое слово было бы нельзя.
  assert.deepEqual(GRAMMAR, [...GRAMMAR].sort());
});
