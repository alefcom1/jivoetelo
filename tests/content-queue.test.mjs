import assert from "node:assert/strict";
import { existsSync, readFileSync } from "node:fs";
import { test } from "node:test";
import { parseQueue, pickBatch, slugify } from "../scripts/content-queue.mjs";

const REAL_QUEUE = readFileSync(new URL("../docs/seo-pipeline.md", import.meta.url), "utf8");

test("берёт невыполненные позиции по порядку и знает их вид", () => {
  const queue = parseQueue(`
### Блюда — кластер «Завтраки»

- [x] Куриная грудка
- [ ] Рис отварной
- [ ] Творог

### Глоссарий

- [ ] Что такое TDEE
`);

  assert.deepEqual(queue.map((i) => i.title), ["Рис отварной", "Творог", "Что такое TDEE"]);
  assert.equal(queue[0].kind, "dish");
  assert.equal(queue[2].kind, "glossary");
});

test("позиции с пометкой «НЕ брать» не берутся никогда", () => {
  // Такая строка оставлена в очереди как предупреждение будущему себе.
  // Взять её — значит своими руками сделать то, от чего она предостерегает.
  const queue = parseQueue(`
### Блюда — кластер «Завтраки»

- [ ] Сырники в духовке — НЕ брать: каннибализирует существующие «Сырники»
- [ ] Омлет
`);

  assert.deepEqual(queue.map((i) => i.title), ["Омлет"]);
});

test("строки вне известных разделов игнорируются", () => {
  // В документе есть и другие списки задач — например, чеклист утренней
  // проверки. Конвейер не должен принять пункт чеклиста за тему статьи.
  const queue = parseQueue(`
### Что проверить утром

- [ ] Правдоподобны ли числа

### Глоссарий

- [ ] Что такое дефицит энергии
`);

  assert.deepEqual(queue.map((i) => i.title), ["Что такое дефицит энергии"]);
});

test("slug транслитерируется предсказуемо: из него получается имя ветки", () => {
  assert.equal(slugify("Куриная грудка"), "kurinaya-grudka");
  assert.equal(slugify("Рис отварной"), "ris-otvarnoy");
  assert.equal(slugify("Что такое TDEE и из чего он складывается"), "chto-takoe-tdee-i-iz-chego-on-skladyvaetsya");
});

test("slug не заканчивается дефисом и не длиннее шестидесяти символов", () => {
  const long = slugify("Адаптивная цель: почему план меняется по ходу и что на это влияет вообще");
  assert.ok(long.length <= 60, `длина ${long.length}`);
  assert.ok(!long.endsWith("-"), `хвостовой дефис: ${long}`);
  assert.ok(!long.startsWith("-"), `ведущий дефис: ${long}`);
});

test("slug состоит только из латиницы, цифр и дефисов", () => {
  for (const title of ["Ёлка «в снегу»", "Что такое TDEE?", "Бутерброд с колбасой"]) {
    assert.match(slugify(title), /^[a-z0-9-]+$/, `${title} → ${slugify(title)}`);
  }
});

test("затвор «ЖДЁТ РАЗДЕЛА» закрывает раздел целиком", () => {
  // Тексты писать уже можно, а класть их некуда: страниц глоссария в коде
  // нет. Без затвора конвейер каждую ночь тратил бы треть работы на отчёт
  // «раздела нет» — пустой прогон, который выглядит как работа.
  const queue = parseQueue(`
### Блюда — кластер «Завтраки»

- [ ] Омлет

### Глоссарий

> ЖДЁТ РАЗДЕЛА: страниц глоссария в коде нет.

- [ ] Что такое TDEE
- [ ] Что такое дефицит энергии
`);

  assert.deepEqual(queue.map((i) => i.title), ["Омлет"]);
});

test("затвор действует только до следующего заголовка", () => {
  // Иначе одна строка тихо закрыла бы весь остаток документа, и заметить это
  // было бы нечем: очередь просто стала бы короче.
  const queue = parseQueue(`
### Глоссарий

> ЖДЁТ РАЗДЕЛА: раздела нет.

- [ ] Что такое TDEE

### Блюда — кластер «Завтраки»

- [ ] Омлет
`);

  assert.deepEqual(queue.map((i) => i.title), ["Омлет"]);
});

test("ночь собирается по ролям: якорь, блюдо, короткая", () => {
  // Прежнее правило «предпочитать разные разделы» работало, пока разделов
  // было пять вперемешку. Роли задают состав жёстко и в нужном порядке:
  // якорь — самое дорогое, что выходит за ночь.
  const queue = parseQueue(`
### Блюда — кластер «Завтраки»

- [ ] Омлет
- [ ] Шашлык

### Статьи журнала

- [ ] Почему у одного блюда разная калорийность

### Каталог продуктов

- [ ] Морковь
`);

  const batch = pickBatch(queue, 3);
  assert.deepEqual(batch.map((i) => i.kind), ["article", "dish", "product"]);
  assert.equal(batch[0].title, "Почему у одного блюда разная калорийность");
});

test("внутри роли берём сверху очереди", () => {
  const queue = parseQueue(`
### Блюда — кластер «Супы»

- [ ] Щи из свежей капусты
- [ ] Уха

### Глоссарий

- [ ] Базовый обмен
- [ ] Клетчатка
`);

  const batch = pickBatch(queue, 2);
  assert.deepEqual(batch.map((i) => i.title), ["Щи из свежей капусты", "Базовый обмен"]);
});

test("три текста одного вида за ночь невозможны", () => {
  // Главное, ради чего роли и заведены: три блюда за ночь — это три
  // одинаковых блюда, сколько бы разных названий у них ни было. Даже когда
  // в очереди не осталось ничего другого, ночь выдаёт максимум два.
  const queue = parseQueue(`
### Блюда — кластер «Завтраки»

- [ ] Омлет
- [ ] Шашлык
- [ ] Хачапури
- [ ] Оладьи
`);

  const batch = pickBatch(queue, 3);
  assert.equal(batch.length, 2, `взято ${batch.length} блюд подряд`);
  assert.deepEqual(batch.map((i) => i.title), ["Омлет", "Шашлык"]);
});

test("пустая роль отдаёт слот соседней, не ломая потолка", () => {
  const queue = parseQueue(`
### Блюда — кластер «Завтраки»

- [ ] Омлет
- [ ] Шашлык

### Каталог продуктов

- [ ] Морковь
- [ ] Огурец
`);

  // Якорей нет вовсе — ночь всё равно должна набраться до трёх.
  const batch = pickBatch(queue, 3);
  assert.equal(batch.length, 3);
  assert.deepEqual(batch.map((i) => i.kind), ["dish", "product", "dish"]);
});

test("позиция с неслитой веткой не берётся заново", () => {
  // Иначе простой утренней проверки превращается в повторную работу:
  // конвейер каждую ночь брал бы одну и ту же непроверенную верхушку.
  const queue = parseQueue(`
### Блюда — кластер «Завтраки»

- [ ] Омлет
- [ ] Шашлык
`);

  const batch = pickBatch(queue, 2, new Set(["omlet"]));
  assert.deepEqual(batch.map((i) => i.title), ["Шашлык"]);
});

test("выборка не переполняется, когда очередь короче запроса", () => {
  const queue = parseQueue("\n### Блюда — кластер «Завтраки»\n\n- [ ] Омлет\n");
  assert.equal(pickBatch(queue, 3).length, 1);
  assert.equal(pickBatch(queue, 3, new Set(["omlet"])).length, 0);
});

test("настоящий план — девяносто позиций, и все они читаются", () => {
  // Защита от того, что кто-то поправит разметку документа так, что скрипт
  // перестанет её понимать, — и ночной конвейер молча начнёт видеть пустую
  // очередь вместо девяноста позиций.
  //
  // Считаем план целиком: и выполненные, и затворённые. Остаток меняется
  // каждую ночь, а план — предмет договорённости, и его изменение должно
  // быть заметным.
  const all = parseQueue(
    REAL_QUEUE.replace(/^>\s*ЖДЁТ РАЗДЕЛА:.*$/gm, "").replace(/^- \[x\]/gm, "- [ ]"),
  );
  assert.equal(all.length, 101, `в плане ${all.length} позиций, а договаривались о 101`);

  // Состав по видам: две трети очереди — по-прежнему блюда и продукты, и это
  // нормально, пока роли не дают им занять ночь целиком. А вот якорей должно
  // хватать: если статьи и методология кончатся, каждая ночь потеряет самое
  // ценное, что в ней есть.
  const byKind = {};
  for (const item of all) byKind[item.kind] = (byKind[item.kind] ?? 0) + 1;
  const anchors = (byKind.article ?? 0) + (byKind.methodology ?? 0) + (byKind.calculator ?? 0);
  assert.ok(anchors >= 15, `якорных позиций всего ${anchors} — ночи останутся без якоря`);

  // Разделы очереди обязаны быть известны скрипту: незнакомый он молча
  // пропускает, и раздел, видный человеку, для конвейера не существует.
  // Проверяем по плану целиком, а не по остатку: выполненный раздел из
  // остатка исчезает, и проверка перестала бы что-либо сторожить.
  const kinds = new Set(all.map((i) => i.kind));
  assert.deepEqual([...kinds].sort(), ["article", "dish", "glossary", "methodology", "product"]);

  for (const item of all) {
    assert.ok(item.slug.length > 0, `пустой slug у «${item.title}»`);
    assert.doesNotMatch(item.title, /НЕ брать/i, `взята запрещённая позиция: ${item.title}`);
  }

  // Слаги — это имена веток. Совпадение означало бы, что две ночи пишут в
  // одну ветку и вторая затирает первую.
  assert.equal(new Set(all.map((i) => i.slug)).size, all.length, "слаги повторяются");
});

test("у каждого открытого раздела есть страница, куда класть текст", () => {
  // Затвор снимают, когда раздел построен, — и легко снять раньше времени.
  // Тогда конвейер ночь за ночью выдаёт отчёт «раздела нет»: пустой прогон,
  // который в списке веток выглядит как работа.
  const HOMES = {
    article: "app/blog/[slug]/page.tsx",
    dish: "app/skolko-kalorij/[dish]/page.tsx",
    product: "app/produkty/[slug]/page.tsx",
    glossary: "app/slovar/[slug]/page.tsx",
    methodology: "app/kak-schitaem/page.tsx",
    calculator: "app/raschet/page.tsx",
  };

  for (const kind of new Set(parseQueue(REAL_QUEUE).map((i) => i.kind))) {
    const home = HOMES[kind];
    assert.ok(home, `вид «${kind}» открыт, но неизвестно, куда он ложится`);
    assert.ok(
      existsSync(new URL(`../${home}`, import.meta.url)),
      `раздел «${kind}» открыт для конвейера, но ${home} нет — затвор сняли раньше времени`,
    );
  }
});
