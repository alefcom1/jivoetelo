  "грамм", "грамма", "граммов", "килограмм", "килограмма", "миллилитр", "миллилитров",
  "литр", "литра", "штука", "штуки", "штук", "кусок", "куска", "кусочек", "ломтик",
  "ложка", "ложки", "ложек", "столовая", "чайная", "стакан", "стакана", "чашка", "тарелка",
