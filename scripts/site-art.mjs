#!/usr/bin/env node
/**
 * Готовит иллюстрации главной из исходников в docs/illustrations.
 *
 *   node scripts/site-art.mjs
 *
 * ## Почему исходники лежат в репозитории
 *
 * Кадры сгенерированы по промптам из docs/site-home-plan.md, но генерация
 * недетерминирована: тот же промпт второй раз даст другую картинку. Значит
 * исходник — единственный способ пересобрать иллюстрацию в другом размере или
 * с другим кадром, и он должен быть под рукой.
 *
 * Хранятся они в webp с качеством 92, а не в исходном PNG: разница на глаз не
 * ловится, а репозиторий легче на порядок (15 МБ против полутора). Клонировать
 * его будут ещё много раз.
 *
 * ## Почему у каждой картинки свой размер
 *
 * Ширина подобрана под то место, где картинка стоит, с полуторным запасом на
 * плотные экраны. Отдавать снимок втрое шире, чем нужно, — это секунды
 * загрузки на мобильном интернете ради резкости, которой никто не увидит.
 */
import { mkdir } from "node:fs/promises";
import { resolve } from "node:path";
import sharp from "sharp";

const root = resolve(import.meta.dirname, "..");
const outDir = resolve(root, "public/site");

const ART = [
  // Триптих: три колонки в сетке до 1280 — около 400 CSS на кадр.
  { name: "day-morning", width: 640 },
  { name: "day-noon", width: 640 },
  { name: "day-evening", width: 640 },
  // Половина секции, примерно 600 CSS.
  { name: "range", width: 960 },
  { name: "boundaries", width: 960 },
  // Полоса во всю ширину колонки.
  { name: "calculators", width: 1920 },
  // На главной не используется — кадр для страницы /pro.
  { name: "pro-talk", width: 960 },
  // Правая часть выпадающих панелей меню: около 560 CSS в ширину, с запасом
  // на плотные экраны. Кадрируем в широкую полосу — панель низкая, и без
  // обрезки от вертикального снимка была бы видна одна середина.
  // position задан вручную: «attention» у sharp выбирает область по
  // контрасту и на утреннем кадре уводило в тёмный угол со скатертью
  // вместо тарелки. Середина кадра здесь как раз то, ради чего он снят.
  { name: "day-morning", as: "menu-product", width: 1120, height: 460, position: "centre" },
  { name: "calculators", as: "menu-calculators", width: 1120, height: 460 },
  // Полоса блока «Меню на день» на главной. Это тот же обеденный кадр, что в
  // триптихе, но взятый другой областью: там он стоит вертикальной колонкой в
  // 400 CSS, здесь — широкой полосой, где тарелка занимает левую половину, а
  // правая остаётся под заголовок. Кадрируем вручную (crop), а не «умным»
  // cover: нужен именно низ снимка с гречкой, курицей и огурцами — ровно та
  // еда, из которой генератор и собирает рационы.
  // Правая треть исходника занята полупрозрачной панелью-подложкой: в широкой
  // полосе она читалась швом, поэтому берём только левые 672px — там тарелка.
  { name: "day-noon", as: "menu-day", width: 1344, crop: { left: 0, top: 775, width: 672, height: 365 } },

  // ── Раздел для специалистов ─────────────────────────────────────────────
  // Единственный на сайте набор с живыми людьми. До него /pro был собран из
  // контурных SVG-схем и читался как техническая спецификация: тонкие серые
  // прямоугольники там, где у остальных страниц стоит плёночная съёмка.
  //
  // Кадр консультации снят в 4:3, а стоит в шапке широкой полосой. Режем
  // вручную снизу, а не «умным» cover: внизу кадра пустой стол, а нужны лица
  // и руки — то, ради чего снимок и сделан.
  { name: "pro-hero", width: 1920, crop: { left: 0, top: 0, width: 1448, height: 814 } },
  // Семь тарелок в ряд, одна посередине пустая. Ширина во всю колонку: при
  // меньшей пустая тарелка перестаёт читаться как пропущенный день и
  // выглядит просто светлым пятном.
  { name: "pro-month", width: 1920 },
  { name: "pro-client", width: 900 },
  { name: "pro-review", width: 900 },
  { name: "pro-consent", width: 1400 },
  { name: "pro-room", width: 1400 },
  // Обложка раздела для соцсетей: 1200×630 — размер, который ждут Telegram,
  // VK и поисковые сниппеты. Кадр снят с запасом справа под заголовок.
  { name: "pro-og", as: "pro-og", width: 1200, height: 630, position: "left" },
];

await mkdir(outDir, { recursive: true });

for (const { name, as, width, height, position, crop } of ART) {
  const out = as ?? name;
  const source = sharp(resolve(root, `docs/illustrations/${name}.webp`));
  // crop — ручная область кадра: когда нужна конкретная часть снимка, а не
  // та, которую sharp сочтёт самой контрастной.
  if (crop) source.extract(crop);
  // height задан — режем под нужные пропорции по центру кадра; без него
  // масштабируем по ширине, сохраняя исходное соотношение.
  const info = await source
    .resize(height ? { width, height, fit: "cover", position: position ?? "attention" } : { width })
    .webp({ quality: 82 })
    .toFile(resolve(outDir, `${out}.webp`));
  console.log(`  ok   public/site/${out}.webp — ${info.width}×${info.height}, ${Math.round(info.size / 1024)} КБ`);
}
