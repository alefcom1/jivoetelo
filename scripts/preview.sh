#!/usr/bin/env bash
# Поднимает собранное приложение для просмотра в браузере.
#
#     ./scripts/preview.sh [порт]
#
# ## Почему это скрипт, а не пара команд
#
# Очевидный способ запустить standalone-сборку выглядит так:
#
#     cd .next/standalone && node server.js
#
# и он однажды стоил нескольких часов. `.next/standalone` — не «папка со
# сборкой», а **полная копия репозитория**: Next кладёт туда `lib`, `tests`,
# `app`, `docs`, `db`, `drizzle`. А рабочий каталог оболочки сохраняется между
# командами. В результате следующая же правка с относительным путём уходит в
# копию: `lib/fan.ts` открывается, меняется и сохраняется — только не тот.
#
# Дальше всё выглядит правдоподобно. `node --test tests/...` проходит.
# `tsc --noEmit` молчит. И только вернувшись в корень, обнаруживаешь, что
# правок нет — со стороны это неотличимо от того, что кто-то откатил дерево.
#
# Поэтому здесь: абсолютные пути, `cd` только внутри подоболочки, и никакого
# следа в каталоге вызывающего.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
PORT="${1:-3000}"
APP="$ROOT/.next/standalone"

if [[ ! -f "$APP/server.js" ]]; then
  echo "Нет $APP/server.js — сначала: npm run build" >&2
  exit 1
fi

# Статика и public в standalone не попадают: Next оставляет их копирование
# на сборщика образа (см. Dockerfile). Для просмотра копируем сами.
mkdir -p "$APP/.next"
cp -r "$ROOT/.next/static" "$APP/.next/" 2>/dev/null || true
cp -r "$ROOT/public" "$APP/" 2>/dev/null || true

echo "Смотреть: http://127.0.0.1:$PORT"
# Подоболочка: cd остаётся внутри неё и не протекает в вызывающий процесс.
(cd "$APP" && PORT="$PORT" NODE_ENV=production exec node server.js)
