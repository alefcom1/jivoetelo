#!/usr/bin/env bash
# Правка одной переменной в `.env` на сервере — без входа по SSH руками.
#
# Скрипт запускается НЕ на вашей машине, а на VPS: его туда передаёт
# .github/workflows/set-env.yml по тому же ключу, что и обычную выкатку.
#
# Зачем это вообще есть. `.env` намеренно лежит вне git и заполняется руками
# один раз — но «руками» подразумевает работающий SSH. Когда доступ потерян
# (сменился адрес, сработал fail2ban, закрыт парольный вход), сервис остаётся
# без единственного способа поменять настройку, хотя GitHub Actions ходит туда
# по ключу как ни в чём не бывало. Этот скрипт — та самая запасная дверь.
#
# Переменные окружения (workflow подставляет сам):
#   DEPLOY_PATH — каталог с кодом на сервере (по умолчанию /root/jivoetelo)
#
# Аргументы:
#   $1 — имя переменной. Приходит из выпадающего списка workflow, а не
#        строкой: опечатка в имени — самый тихий отказ из возможных. Пустой
#        ADMIN_EMAILS и несуществующий ADMIN_EMAIL ведут себя одинаково —
#        админов нет, — и разбираться с этим потом приходится часами.
#   $2 — значение, закодированное base64. Именно base64, а не текст: значение
#        приходит от человека и попадает в команду ssh, то есть проходит через
#        разбор оболочки дважды. Кавычка или `$(` в нём — это выполнение чужой
#        команды на сервере. Алфавит base64 такого не содержит в принципе.
set -euo pipefail

NAME="${1:-}"
VALUE_B64="${2:-}"
DEPLOY_PATH="${DEPLOY_PATH:-/root/jivoetelo}"

if [ -z "$NAME" ]; then
  echo "Не передано имя переменной." >&2
  exit 1
fi

cd "$DEPLOY_PATH"

if [ ! -f .env ]; then
  echo "Нет файла .env в $DEPLOY_PATH — менять нечего." >&2
  echo "Он создаётся из .env.example один раз вручную (docs/deploy-github-actions.md, шаг 1.4)." >&2
  exit 1
fi

VALUE="$(printf '%s' "$VALUE_B64" | base64 -d)"

# Копия до правки. `.env*` целиком в .gitignore, так что выкатка её не тронет,
# а вернуться к прежнему значению можно одним cp.
BACKUP=".env.bak.$(date +%F-%H%M%S)"
cp .env "$BACKUP"

# Замена на месте, а не «удалить и дописать в конец»: переменная стоит под
# своим блоком комментариев, и объяснение, оторванное от значения, через
# полгода будет объяснять пустоту.
#
# Значения передаются через ENVIRON, а не через `awk -v`: последний
# разворачивает escape-последовательности, и значение с обратной косой чертой
# приехало бы искажённым.
NAME="$NAME" VALUE="$VALUE" awk '
  BEGIN { name = ENVIRON["NAME"]; value = ENVIRON["VALUE"]; done = 0 }
  !done && index($0, name "=") == 1 { print name "=" value; done = 1; next }
  { print }
  END { if (!done) print name "=" value }
' .env > .env.new

mv .env.new .env
chmod 600 .env

# Проверяем файл, а не только факт записи: строка должна быть ровно одна.
# Две строки с одним именем — это работающий, но необъяснимый сервер: docker
# compose возьмёт последнюю, а человек прочитает первую.
COUNT="$(grep -c "^${NAME}=" .env || true)"
if [ "$COUNT" != "1" ]; then
  echo "В .env оказалось $COUNT строк с ${NAME} — ожидалась одна. Возвращаю как было." >&2
  cp "$BACKUP" .env
  exit 1
fi

# Длину, а не значение. Скрипт задуман как общий, и однажды им зададут токен;
# привычка печатать значение в лог живёт дольше, чем повод её завести.
echo "▶ ${NAME} записан, длина значения: ${#VALUE}"
echo "▶ Копия до правки: $DEPLOY_PATH/$BACKUP"

echo "▶ Перезапускаем приложение"
docker compose up -d app

# Значение из .env подставляется в контейнер на старте, поэтому спрашиваем
# сам контейнер: перезапуск мог не случиться, если compose счёл конфигурацию
# неизменной, и тогда правка лежит в файле, но не действует.
echo "▶ Проверяем, что контейнер видит переменную"
for attempt in $(seq 1 15); do
  IN_CONTAINER="$(docker compose exec -T app printenv "$NAME" 2>/dev/null || true)"
  if [ -n "$IN_CONTAINER" ]; then
    if [ "$IN_CONTAINER" = "$VALUE" ]; then
      echo "✔ Готово: контейнер видит ${NAME} с новым значением"
      exit 0
    fi
    echo "✖ Контейнер видит ${NAME}, но значение другое — перезапуск не подхватил правку." >&2
    exit 1
  fi
  sleep 2
done

echo "✖ Контейнер не поднялся или не видит ${NAME}. Последние строки логов:" >&2
docker compose logs --tail 40 app >&2 || true
echo "Вернуть как было: cd $DEPLOY_PATH && cp $BACKUP .env && docker compose up -d app" >&2
exit 1
