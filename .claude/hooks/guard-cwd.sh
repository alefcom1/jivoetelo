#!/usr/bin/env bash
# PreToolUse-хук на Bash: не пускать рабочий каталог в копии репозитория.
#
# ## Что случилось
#
# `.next/standalone` — полная копия дерева проекта: Next кладёт туда `lib`,
# `tests`, `app`, `docs`, `db`. Рабочий каталог оболочки сохраняется между
# вызовами, поэтому одна команда вида
#
#     cd .next/standalone && node server.js &
#
# незаметно переводит туда **все следующие команды**. Правки с относительными
# путями уходят в копию, тесты и проверка типов там же проходят, а в
# репозитории ничего не меняется. Снаружи это неотличимо от того, что кто-то
# откатывает рабочую копию: рефлог чист, стэша нет, файлы «сами вернулись».
#
# На поиск этого ушло несколько часов и несколько потерянных правок, поэтому
# дешевле запретить сам приём, чем каждый раз вспоминать.
#
# Разрешено то же самое внутри подоболочки — `( cd ... && ... )` каталог
# вызывающего не меняет. Именно так сделан scripts/preview.sh.

input=$(cat)
command=$(printf '%s' "$input" | jq -r '.tool_input.command // ""' 2>/dev/null) || exit 0
[[ -z "$command" ]] && exit 0

# Убираем всё, что заключено в круглые скобки: это подоболочки, они безопасны.
without_subshells=$(printf '%s' "$command" | sed -E 's/\([^()]*\)//g')

if printf '%s' "$without_subshells" | grep -qE '(^|[;&|]|&&)[[:space:]]*cd[[:space:]]+[^;&|]*\.next'; then
  cat >&2 <<'MSG'
Отказ: cd в .next/* переводит туда рабочий каталог всех последующих команд.

`.next/standalone` — полная копия репозитория (lib, tests, app, docs, db).
Правки с относительными путями уйдут в неё, тесты и типы там же пройдут, а в
репозитории не изменится ничего. Это уже стоило потерянной работы и часов на
поиск «отката», которого не было.

Что делать вместо:
  ./scripts/preview.sh 3000      — поднять сборку для просмотра
  ( cd .next/standalone && ... ) — если правда нужно, то в подоболочке
MSG
  exit 2
fi

exit 0
